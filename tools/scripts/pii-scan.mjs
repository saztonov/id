/**
 * Барьер против попадания персональных данных корпуса в репозиторий.
 *
 * Правило §1.4 плана: реальные документы в git не попадают, в тестах живут
 * только синтетические данные. Правило нарушалось на практике — агенты,
 * писавшие тесты по образцам, переносили в них настоящие ФИО подписантов
 * и hex-отпечатки сертификатов ЭП. Разовая вычитка такое не удержит,
 * поэтому проверка автоматическая и входит в гейт.
 *
 * Маркеры перечислены явно, а не выводятся из корпуса: сам список не должен
 * зависеть от наличия закрытых файлов на машине, иначе в CI проверка станет
 * пустой и создаст ложное чувство безопасности.
 */
import { readFileSync } from 'node:fs';
import { execFileSync } from 'node:child_process';

/** Фамилии подписантов и заверителей из закрытого корпуса. */
const SURNAMES = [
  'Поляков',
  'Савченко',
  'Шадров',
  'Милешкин',
  'Коротинский',
  'Сарычев',
  'Свердлов',
  'Мусийчук',
  'Заусайлова',
  'Бухтерева',
  'Савичева',
  'Фонова',
];

/** Наименования организаций, идентифицирующие объект и участников. */
const ORGS = ['СУ-10', 'ЭМДМ', 'МС-90', 'СТАДИОН "СПАРТАК"', 'СТАДИОН «СПАРТАК»', 'Primavera'];

/** Реальные ИНН и ОГРН участников. */
const IDS = [
  '7709574093',
  '7736255508',
  '7725825428',
  '7702521529',
  '7720961314',
  '7728093677',
  '1047796801920',
  '5157746024662',
  '1147746393453',
  '1097799011859',
  '1267700005210',
  '124770050762',
  '1067746138138',
];

/** Отпечатки сертификатов электронной подписи. */
const CERT_HASHES = [
  '6FA5B700E6B27C854A328140750B57B4',
  '6DDFE9D00F1B20AA54136D1B5B55A1ADF',
  '6DCDEAF0044B3B68B4293A3239683AE33',
  '2A53FAF0029B34E9B432722071BE2D7F7',
  '2A18F8500DEB3BA740BFAD446DD71F75',
  '5D77EBF000CB3E0A24F8E24FDEB503091',
];

/**
 * Маркеры разделены по строгости, потому что различаются по природе.
 *
 * ФИО подписантов и отпечатки их сертификатов — персональные данные, им
 * не место нигде. Наименования организаций, ИНН и ОГРН — сведения из ЕГРЮЛ,
 * открытого реестра; в коде и тестах они не нужны, но в документации
 * проверенных фактов необходимы: без конкретного ОГРН вывод о битой
 * контрольной сумме нельзя перепроверить.
 */
const STRICT = [...SURNAMES, ...CERT_HASHES];
const CODE_ONLY = [...ORGS, ...IDS];

/** Документация, где допустимы реквизиты юрлиц из открытого реестра. */
const DOCS_ALLOWED = /^docs\/(CORPUS_FINDINGS|EXECUTION_LOG)\.md$/;

/** Сам сканер содержит маркеры по определению. */
const SELF = /^tools\/scripts\/pii-scan\.mjs$/;

const tracked = execFileSync('git', ['ls-files'], { encoding: 'utf8' })
  .split('\n')
  .filter(Boolean)
  .filter((f) => !SELF.test(f))
  .filter((f) => !/\.(pdf|png|jpg|jpeg|webp|ico|woff2?)$/i.test(f));

const hits = [];
for (const file of tracked) {
  let text;
  try {
    text = readFileSync(file, 'utf8');
  } catch {
    continue;
  }
  const markers = DOCS_ALLOWED.test(file) ? STRICT : [...STRICT, ...CODE_ONLY];
  for (const marker of markers) {
    if (text.includes(marker)) hits.push({ file, marker });
  }
}

if (hits.length > 0) {
  console.error('Найдены персональные данные корпуса в отслеживаемых файлах:\n');
  for (const { file, marker } of hits) console.error(`  ${file}: «${marker}»`);
  console.error('\nЗамените синтетическими значениями (§1.4 плана).');
  process.exit(1);
}

console.log(
  `Сканирование ПДн: чисто (${tracked.length} файлов, ${STRICT.length + CODE_ONLY.length} маркеров).`,
);
