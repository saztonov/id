import { describe, expect, it } from 'vitest';

import {
  actItemNumbers,
  ownDocNoOf,
  parseActItem3,
  registryRefNumber,
  splitItemPositions,
} from './act-items.js';

/** Запись п. 3 из боевой папки «№01_Бл_П от 21.11.2024»: две позиции, четыре номера. */
const ITEM3_TWO_POSITIONS =
  '1.Песок для строительных работ (Паспорт №0297 от 26.09.2024г., Сертификат соответствия ' +
  '№RU.MCC.234.435.37815 (с 01.08.2023г. по 01.08.2026г.)). ' +
  '2.Полиэтиленовое геотекстильное (Сертификат №275 от 08.08.2024г., Сертификат соответствия ' +
  '№ РОСС RU BY.HE06.H22245 (с 22.04.2024г. по 21.04.2027г.)).';

describe('номера внутри строки перечня', () => {
  it('берёт все номера записи, границей служит «от», запятая или скобка', () => {
    expect(actItemNumbers(ITEM3_TWO_POSITIONS)).toEqual([
      '0297',
      'RU.MCC.234.435.37815',
      '275',
      'РОСС RU BY.HE06.H22245',
    ]);
  });

  it('понимает OCR-формы знака номера: «Не», «No»', () => {
    expect(actItemNumbers('Паспорт Не 6846 от 01.02.2026')).toEqual(['6846']);
    expect(actItemNumbers('Сертификат No RU.СМИК.001.Н.00270, выдан')).toEqual([
      'RU.СМИК.001.Н.00270',
    ]);
  });

  it('латинское «N» перед буквой знаком номера не считается', () => {
    // Опечатка `N(?![p{L}])` в прежней копии правил читала «Novaya» как «№ ovaya».
    expect(actItemNumbers('Novaya Gazeta, лист 3')).toEqual([]);
  });
});

describe('собственный номер строки и ссылка на родителя', () => {
  it('первый «№» после предлога «к» принадлежит родителю, а не строке', () => {
    // Скриншот 2: правило п. 4 искало документ «ПВ-1», то есть акт, а не реестр.
    expect(ownDocNoOf('Реестр 2 к АОСР №ПВ-1 от 31.03.2026г')).toBeNull();
    expect(ownDocNoOf('Реестр приложений № 1 к акту № 48-ОТ/-1 этаж')).toBe('1');
  });

  it('у схемы собственный номер — тот, что после её наименования', () => {
    expect(
      ownDocNoOf(
        'Исполнительная схема устройства стен в/о 3-4//А-Д на отм. -3,850 № 48.1-от/-1 этаж от 10.04.2026г.',
      ),
    ).toBe('48.1-от/-1 этаж');
  });

  it('хвостовая пунктуация к номеру не относится', () => {
    expect(ownDocNoOf('Протокол № 3687.КП/03.26.')).toBe('3687.КП/03.26');
  });
});

describe('ссылка на реестр приложений', () => {
  it.each([
    ['Реестр 1 к АОСР №ПБ-1 от 31.03.2026г', '1'],
    ['Реестр №1.1 к АОСР № 48-ОТ/-1 этаж от 10.04.2026г.', '1.1'],
    ['Перечислено в реестре приложений №1', '1'],
    ['Реестр № 2 к №СИН/ОВ1/От/32 от 31.12.2024 г.', '2'],
    ['реестре приложений №1', '1'],
    // Опечатка OCR из боевой базы: заголовок реестра прочитан как «Рестр».
    ['Рестр № 2 к АОСР № ПБ-1 от 31.03.2026 г.', '2'],
  ])('«%s» → реестр № %s', (text, expected) => {
    expect(registryRefNumber(text)).toBe(expected);
  });

  it('проза без номера реестра ссылкой не является', () => {
    expect(registryRefNumber('в соответствии с п. 3, 4')).toBeNull();
    expect(registryRefNumber('Песок для строительных работ (Паспорт №0297)')).toBeNull();
  });
});

describe('позиции п. 3', () => {
  it('режет запись на позиции по порядковому номеру перед буквой', () => {
    const positions = splitItemPositions(ITEM3_TWO_POSITIONS);
    expect(positions.map((position) => position.name)).toEqual([
      'Песок для строительных работ',
      'Полиэтиленовое геотекстильное',
    ]);
    expect(positions.map((position) => position.numbers)).toEqual([
      ['0297', 'RU.MCC.234.435.37815'],
      ['275', 'РОСС RU BY.HE06.H22245'],
    ]);
  });

  it('даты и номера внутри скобок позиции не режут', () => {
    // «26.09.2024г. Сертификат» без учёта скобок выглядело бы началом позиции.
    const positions = splitItemPositions(
      '1. Грунтовка (Паспорт №112 от 26.09.2024г. Сертификат №RU.СМИК.001.Н.00270)',
    );
    expect(positions).toHaveLength(1);
    expect(positions[0]?.numbers).toEqual(['112', 'RU.СМИК.001.Н.00270']);
  });

  it('«0.5 мм» и «1. Лист» внутри названия позицией не становятся', () => {
    const positions = splitItemPositions(
      '1. Мембрана 0.5 мм толщиной (Паспорт № 4401 от 01.01.2026)',
    );
    expect(positions.map((position) => position.name)).toEqual(['Мембрана 0.5 мм толщиной']);
  });

  it('короткие и бесцифровые «номера» отбрасываются', () => {
    const positions = splitItemPositions('1. Клей (Паспорт № 12, Сертификат № РОСС)');
    expect(positions[0]?.numbers).toEqual([]);
  });
});

describe('разбор записей п. 3', () => {
  it('ссылка на реестр, перечисление и нераспознанное различаются видом', () => {
    const entries = parseActItem3([
      'Реестр 1 к АОСР №ПБ-1 от 31.03.2026г',
      ITEM3_TWO_POSITIONS,
      'см. приложения',
    ]);
    expect(entries.map((entry) => entry.kind)).toEqual(['registry_ref', 'materials', 'unparsed']);
    expect(entries[0]).toMatchObject({ kind: 'registry_ref', number: '1' });
  });

  it('перечисление, в котором встречается слово «реестр», остаётся перечислением', () => {
    const [entry] = parseActItem3(['1. Песок (Паспорт № 0297, см. также реестр 1)']);
    expect(entry?.kind).toBe('materials');
  });
});
