function activeOf(batch: RuleSeedBatch): readonly RuleSpec[] {
  const retired = new Set(batch.retired ?? []);
  return batch.rules.filter((spec) => !retired.has(spec.code));
}

function retiredOf(batch: RuleSeedBatch): readonly RuleSpec[] {
  const retired = new Set(batch.retired ?? []);
  return batch.rules.filter((spec) => retired.has(spec.code));
}

