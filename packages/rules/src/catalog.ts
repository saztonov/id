/**
 * Партии сида: какая миграция заводит какие правила.
 *
 * ## Зачем это, если каталог один
 *
 * Миграция применена — значит заморожена: раннер сверяет контрольную сумму
 * каждого применённого файла и объявляет правку `modified`. Поэтому правило,
 * добавленное после 0017, обязано приезжать СВОЕЙ миграцией, а не переписыванием
 * уже применённой.
 *
 * Пока партия была одна, это выражалось соглашением «0017 = весь каталог», и
 * сверка на дрейф сравнивала файл с генерацией по всему `RULE_CATALOG`. Первое
 * же добавление кода (S21) сломало бы либо сверку, либо контрольную сумму. Здесь
 * соглашение стало данными: каталог СОБИРАЕТСЯ из партий, у каждой партии свой
 * файл миграции, и сверка проверяет каждую пару по отдельности.
 *
 * Порядок партий задаёт порядок каталога; внутри файла правила всё равно
 * сортируются по коду.
 */
export interface RuleSeedBatch {
  /** Имя файла миграции без расширения — по нему сверка находит файл. */
  readonly migration: string;
  readonly rules: readonly RuleSpec[];
  /**
   * Замены, которыми ЗАСТЫВШИЙ файл отличается от нынешнего каталога.
   *
   * Партии append-only не хватает на один случай: значение поля существующего
   * правила переименовано. Так вышло в S44 с уровнем `revision` → `folder`:
   * ревизия поставки перестала существовать как сущность, а строки в
   * `rule_definitions` были засеяны применёнными миграциями и заморожены
   * контрольной суммой.
   *
   * Переписывать применённый файл нельзя (раннер объявит его `modified`),
   * поэтому значение в БД правит ОТДЕЛЬНАЯ миграция, а здесь записано, чем
   * старый текст отличается от нового. Сверка применяет замены к выводу
   * генератора перед сравнением — и продолжает ловить настоящий дрейф:
   * добавленное правило, изменённый заголовок, съехавшую тяжесть.
   */
  readonly seededAs?: readonly (readonly [string, string])[];
  /**
   * Коды из `rules`, СНЯТЫЕ с исполнения (S59).
   *
   * Снятие — вывод из `RULE_CATALOG`, а не удаление из БД (ADR-0019): строка
   * `rule_definitions` остаётся навсегда, потому что на неё ссылаются
   * замечания прошлых прогонов и снимки опубликованных наборов. Прецедент
   * S30 снимал ЦЕЛУЮ партию (`RETIRED_SEED_BATCHES`); здесь снимается часть —
   * файл миграции по-прежнему содержит все коды партии, генератор по-прежнему
   * их печатает, а движок и сверка при старте читают только действующие.
   *
   * Перечисляется явными кодами, как и состав партий: код, названный здесь и
   * отсутствующий в `rules`, — ошибка каталога, её ловит `unknownRetiredCodes`.
   */
  readonly retired?: readonly string[];
}

