/**
 * Каталог правил: реестр и реализации ОДНИМ объектом (§9.6).
 *
 * Два параллельных списка — «коды где-то» и «функции где-то ещё» — расходятся
 * молча. Это ровно тот дефект, который на S2 дал нулевое пересечение имён
 * ограничений между схемой Drizzle и SQL, и тот, который на S4 позволил
 * опечатке в `enabled_rule_codes` тихо выключить проверку. Поэтому здесь
 * ОДНА таблица: из неё порождается сид `rule_definitions` (`seed.ts`), по ней
 * же движок исполняет правила, и сверка при старте сравнивает БД с ней в обе
 * стороны.
 *
 * ## Что здесь можно менять, а что нет
 *
 * `severity`, `isBlocking` и `params` В ПРОГОНЕ берутся не отсюда, а из
 * неизменяемого снимка `ruleset_rules`. Поля `defaultSeverity`,
 * `defaultBlocking` и `defaultParams` — только заготовка для публикации новой
 * версии набора правил и значения по умолчанию сида. Правка кода не меняет
 * поведение уже опубликованного набора: в этом весь смысл §3.7.
 *
 * ## Кодировка
 *
 * `<ГРУППА>.<ПОДГРУППА>.<НОМЕР>` либо `<ГРУППА>.<НОМЕР>`. Номера соответствуют
 * §9.2–§9.5 плана; пропуски в нумерации оставлены намеренно, чтобы правило,
 * добавленное эксплуатацией, вставало рядом со своей группой, а не в конец.
 */
import { DATE_RULES, SIGNATURE_RULES } from './dates.js';
import { AOSR_RULES, CROSSCHECK_RULES, EXTERNAL_RULES, WORK_PERIOD_RULES } from './aosr.js';
import { EVIDENCE_RULES } from './evidence.js';
import { LLM_REVIEW_RULES } from './llm-review.js';
import type { RuleSpec } from './types.js';

/**
 * Партии сида: какая миграция заводит какие правила.
 *
 * ## Зачем это, если каталог один
 *
 * Миграция применена — значит заморожена: раннер сверяет контрольную сумму
 * каждого применённого файла и объявляет правку `modified`. Поэтому правило,
 * добавленное после 0017, обязано приезжать СВОЕЙ миграцией, а не переписыванием
 * уже применённой.
 *
 * Пока партия была одна, это выражалось соглашением «0017 = весь каталог», и
 * сверка на дрейф сравнивала файл с генерацией по всему `RULE_CATALOG`. Первое
 * же добавление кода (S21) сломало бы либо сверку, либо контрольную сумму. Здесь
 * соглашение стало данными: каталог СОБИРАЕТСЯ из партий, у каждой партии свой
 * файл миграции, и сверка проверяет каждую пару по отдельности.
 *
 * Порядок партий задаёт порядок каталога; внутри файла правила всё равно
 * сортируются по коду.
 */
export interface RuleSeedBatch {
  /** Имя файла миграции без расширения — по нему сверка находит файл. */
  readonly migration: string;
  readonly rules: readonly RuleSpec[];
}

export const RULE_SEED_BATCHES: readonly RuleSeedBatch[] = [
  {
    migration: '0017_seed_rule_definitions',
    rules: [
      ...DATE_RULES,
      ...SIGNATURE_RULES,
      ...AOSR_RULES,
      ...CROSSCHECK_RULES,
      ...EXTERNAL_RULES,
      ...EVIDENCE_RULES,
    ],
  },
  {
    // ИИ-проверка заполнения (S21). Коды объявлены в каталоге, потому что
    // `findings.rule_code` — внешний ключ на `rule_definitions`, а сверка при
    // старте сравнивает таблицу с каталогом в обе стороны. Исполняет их задача
    // `checks.llm_review`, движок отвечает `n_a` с названной причиной.
    migration: '0031_seed_llm_review_rules',
    rules: LLM_REVIEW_RULES,
  },
];

/**
 * Правила, СНЯТЫЕ с исполнения (S30).
 *
 * Их нет в `RULE_CATALOG`: движок их не исполняет, а сверка реестра при старте
 * их не ждёт — в `rule_definitions` их тоже больше нет, строки удаляет
 * миграция 0047.
 *
 * Но спеки обязаны сохраниться, и причина механическая. Миграции `0034` и
 * `0044` уже применены и содержат эти строки, а тест дрейфа сверяет их
 * контрольные суммы с выводом генераторов. Убери спек — и выбор был бы между
 * красным тестом и перегенерацией применённой миграции, которую раннер объявит
 * `modified`. Ровно этот выбор в своё время снял механизм партий; здесь он снят
 * тем же приёмом с другой стороны.
 *
 * Порядок не важен: оба генератора сортируют правила по коду, поэтому
 * возвращённый в список код встаёт на прежнее место байт в байт.
 */
export const RETIRED_SEED_BATCHES: readonly RuleSeedBatch[] = [
  {
    // Месяц комплекта против даты акта (S22, снято в S30). Правило сверяло акт
    // с числом, которое человек называл руками; теперь месяц выводится из
    // самого раннего акта, и сверять стало нечего с чем.
    migration: '0034_seed_period_rule',
    rules: WORK_PERIOD_RULES,
  },
];

export const RETIRED_RULES: readonly RuleSpec[] = RETIRED_SEED_BATCHES.flatMap(
  (batch) => batch.rules,
);

/**
 * Каталог вместе со снятыми — вход генераторов уже применённых миграций.
 *
 * Только для них: всё, что решает, ЧТО портал проверяет, обязано читать
 * `RULE_CATALOG`, иначе снятое правило вернулось бы в работу через чёрный ход.
 */
export const RULE_CATALOG_WITH_RETIRED: readonly RuleSpec[] = [
  ...RULE_SEED_BATCHES.flatMap((batch) => batch.rules),
  ...RETIRED_RULES,
];

/**
 * Полный каталог — объединение партий.
 *
 * Собирается, а не выписывается вторым списком: два списка разъезжаются молча,
 * и разъехавшись, дали бы правило, которое движок исполняет, а БД по внешнему
 * ключу не знает.
 */
export const RULE_CATALOG: readonly RuleSpec[] = RULE_SEED_BATCHES.flatMap((batch) => batch.rules);

export const RULE_CODES: readonly string[] = RULE_CATALOG.map((spec) => spec.code);

/**
 * Дубли кодов внутри каталога.
 *
 * Проверяется отдельно от сверки с БД: два спека с одним кодом дают
 * `rule_definitions`, где второй молча вытесняет первого при сиде, и одно из
 * двух правил перестаёт исполняться, оставаясь в списке включённых.
 */
export function duplicateRuleCodes(specs: readonly RuleSpec[] = RULE_CATALOG): readonly string[] {
  const seen = new Set<string>();
  const duplicates = new Set<string>();
  for (const spec of specs) {
    if (seen.has(spec.code)) duplicates.add(spec.code);
    seen.add(spec.code);
  }
  return [...duplicates].sort();
}
