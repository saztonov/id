/**
 * Калибровка нестрогого сходства наименований материалов (S59, MAT.COVER).
 *
 * `AOSR.P3.070` подтверждает материал п. 3 по номеру ИЛИ по названию, и порог
 * названия — 0.75 — обязан лежать между двумя наблюдениями корпуса: та же
 * марка с обозначением основы («Техноэласт ЭПП» ↔ «…Техноэласт П ЭПП», 1.0) и
 * соседняя марка того же производителя («КНАУФ-Тифенгрунд» ↔ «КНАУФ-Фуген»,
 * 0.5). Пары здесь — это КАЛИБРОВОЧНЫЕ точки: сдвинь стебель, отбрасывание
 * односимвольных токенов или список служебных слов — и одна из них уедет за
 * порог, а вместе с ней правило начнёт либо пропускать чужие марки, либо
 * предупреждать о своих.
 */
import { describe, expect, it } from 'vitest';

import { DEFAULT_NAME_SIMILARITY_THRESHOLD, markTokens, nameSimilarity } from './material-cover.js';

describe('nameSimilarity — калибровочные пары', () => {
  it('«Техноэласт ЭПП» ↔ «Техноэласт П ЭПП» — 1: буква основы реестром опускается', () => {
    expect(nameSimilarity('Техноэласт ЭПП', 'Материал рулонный Техноэласт П ЭПП')).toBe(1);
  });

  it('«КНАУФ-Тифенгрунд» ↔ «КНАУФ-Фуген» — 0.5: общий производитель, разная марка', () => {
    expect(nameSimilarity('Смесь сухая шпатлевочная КНАУФ-Тифенгрунд', 'КНАУФ-Фуген')).toBe(0.5);
  });

  it('«ветонит ЛР+» ↔ «Техноэласт ЭПП» — 0: чужие марки', () => {
    expect(nameSimilarity('ветонит ЛР+', 'Техноэласт ЭПП')).toBe(0);
  });

  it('«Труба стальная» ↔ «Трубы стальные водогазопроводные» — не ниже порога: стебли', () => {
    expect(
      nameSimilarity('Труба стальная', 'Трубы стальные водогазопроводные'),
    ).toBeGreaterThanOrEqual(DEFAULT_NAME_SIMILARITY_THRESHOLD);
  });

  it('порог по умолчанию лежит между соседней маркой и своей', () => {
    // 0.5 — предупреждение «марка расходится», 1.0 — совпадение. Порог,
    // сползший к 0.5, объявил бы КНАУФ-Фуген документом на Тифенгрунд.
    expect(DEFAULT_NAME_SIMILARITY_THRESHOLD).toBeGreaterThan(0.5);
    expect(DEFAULT_NAME_SIMILARITY_THRESHOLD).toBeLessThanOrEqual(1);
  });

  it('симметрично: доля считается по короткой записи независимо от порядка', () => {
    const a = 'Техноэласт ЭПП';
    const b = 'Материал рулонный кровельный Техноэласт П ЭПП';
    expect(nameSimilarity(a, b)).toBe(nameSimilarity(b, a));
  });

  it('пустая или служебная запись даёт 0, а не совпадение', () => {
    // Сравнивать нечего — это не «совпало»: иначе пустое название в п. 3
    // подтверждалось бы любым документом.
    expect(nameSimilarity('', 'Техноэласт ЭПП')).toBe(0);
    expect(nameSimilarity('марка по ГОСТ', 'Техноэласт ЭПП')).toBe(0);
  });

  it('гомоглифы и регистр не мешают: «Tехноэласт» латинской T — та же марка', () => {
    expect(nameSimilarity('Tехноэласт ЭПП', 'ТЕХНОЭЛАСТ ЭПП')).toBe(1);
  });
});

describe('markTokens', () => {
  it('отбрасывает односимвольные и служебные токены', () => {
    // «П» — обозначение основы, «марка», «ГОСТ», «для» — служебные: с ними пара
    // Техноэласта давала бы 0.67 и уходила бы за порог.
    expect(markTokens('Техноэласт П ЭПП марка ГОСТ 123 для кровли')).toEqual([
      'TEXHOЭЛACT',
      'ЭПП',
      '123',
      'KPOBЛИ',
    ]);
  });

  it('режет по дефису, скобкам и кавычкам, но сохраняет «+» в марке', () => {
    expect(markTokens('«КНАУФ-Тифенгрунд» (грунтовка)')).toEqual([
      'KHAUФ',
      'TИФEHГPUHД',
      'ГPUHTOBKA',
    ]);
    expect(markTokens('ветонит ЛР+')).toEqual(['BETOHИT', 'ЛP+']);
  });
});
