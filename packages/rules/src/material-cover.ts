/**
 * Нестрогое сходство наименований материалов (S59, MAT.COVER).
 *
 * ## Зачем сходство, если есть номер
 *
 * Постановка заказчика: у материала из п. 3 акта должен быть сертификат,
 * декларация или паспорт, и совпадение по номеру ИЛИ по названию — любое из
 * двух — считается хорошим. Номер решает первым (`normalizeDocNo`, те же две
 * ступени, что у сверки реестра); название нужно там, где номера в п. 3 нет
 * или он прочитан иначе.
 *
 * ## Почему токены, а не `pg_trgm` и не полная строка
 *
 * Полная строка не сходится никогда: реестр пишет «Техноэласт ЭПП», паспорт —
 * «Материал рулонный кровельный Техноэласт П ЭПП». Похожесть по триграммам
 * (`docs/CORPUS_FINDINGS.md`: 0.55 на одной и той же декларации в двух
 * алфавитах) требует порогов, которые никто не калибровал. Токены марки после
 * фолдинга гомоглифов дают вопрос, на который есть ответ: какая доля слов
 * КОРОТКОЙ записи есть в длинной. У «Техноэласт ЭПП» это 1.0, у «КНАУФ-Тифенгрунд»
 * против «КНАУФ-Фуген» — 0.5, у «ветонит ЛР+» против чужих марок — 0.
 *
 * Односимвольные токены отбрасываются намеренно: буква «П» в «Техноэласт П ЭПП»
 * — обозначение основы, которое реестр опускает, и с ней пара давала бы 0.67.
 * Окончания срезаются стеблем: «Труба стальная» и «Трубы стальные» — один
 * материал, а не два.
 */
import { foldHomoglyphs } from './helpers.js';

/** Порог сходства по умолчанию; профиль раздела переопределяет его `thresholds`. */
export const DEFAULT_NAME_SIMILARITY_THRESHOLD = 0.75;

/**
 * Служебные слова, которые не отличают один материал от другого.
 *
 * Список короткий и закрытый: слово, попавшее сюда, перестаёт участвовать в
 * сравнении, и расширять его «на всякий случай» значило бы сравнивать всё со
 * всем.
 */
const STOP_TOKENS: ReadonlySet<string> = new Set(
  ['МАРКА', 'МАРКИ', 'ТИП', 'ТИПА', 'ГОСТ', 'ТУ', 'СТО', 'ДЛЯ', 'ПО', 'ИЗ', 'НА'].map(
    foldHomoglyphs,
  ),
);

/** Стебель токена: без двух последних букв, но не короче четырёх знаков. */
function stemOf(token: string): string {
  return token.length <= 4 ? token : token.slice(0, Math.max(4, token.length - 2));
}

/** Токены марки: фолдинг, разбиение по разделителям, без коротких и служебных. */
export function markTokens(value: string): readonly string[] {
  return foldHomoglyphs(value)
    .split(/[\s\-–—/,;:()«»"'`]+/u)
    .map((token) => token.replace(/[^\p{L}\p{N}+]/gu, ''))
    .filter((token) => token.length > 1 && !STOP_TOKENS.has(token));
}

/**
 * Доля токенов более короткой записи, найденных в более длинной; 0 — сравнивать
 * нечего (у одной из сторон нет ни одного значащего токена).
 */
export function nameSimilarity(left: string, right: string): number {
  const a = new Set(markTokens(left).map(stemOf));
  const b = new Set(markTokens(right).map(stemOf));
  if (a.size === 0 || b.size === 0) return 0;
  const [small, large] = a.size <= b.size ? [a, b] : [b, a];
  let hits = 0;
  for (const token of small) if (large.has(token)) hits += 1;
  return hits / small.size;
}
