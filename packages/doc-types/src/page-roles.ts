/**
 * Роли страниц — ортогональны типам документов (§8.1).
 *
 * «КОПИЯ ВЕРНА», лист визуализации ЭП, пустая страница, приложение-продолжение
 * и продолжение многостраничного документа встречаются внутри любого вида ИД
 * и самостоятельными видами не являются.
 *
 * ## Почему в якорях ролей есть `^` и `$`, а в якорях типов их нет
 *
 * `matchDocTypes` сам требует `m.index === 0` и сам ограничивает длину хвоста,
 * поэтому якорю типа привязка к началу строки не нужна и запрещена.
 * `matchPageRoles` устроен иначе: он ищет якорь в произвольном месте
 * нормализованной строки и хвост не ограничивает — роль печатается где угодно
 * на странице, в том числе в подвале. Там `^`/`$` не избыточны, а являются
 * единственным средством отличить заголовок «ПРИЛОЖЕНИЕ» от упоминания
 * «(см. приложение к сертификату) и их производство» (стр. 45 корпуса) или
 * «Декларация принята на основании документов, приложение №1 на 1-м листе».
 * Без них роль с `autoAttach: true` присоединяла бы к предыдущему документу
 * любую страницу, где слово «приложение» встретилось в тексте.
 *
 * Границы строки, а не текста: при построчном матчинге (`matching.ts`) флаг `m`
 * не нужен — строка подаётся по одной; при матчинге по всему тексту
 * (`compileAnchors`, флаг `m`) `^`/`$` тоже означают границы строки.
 */

