/**
 * Кнопка «3. Проверить»: применить новые правила, не перечитывая страницы (S55).
 *
 * ## Почему сценарий нужен именно сквозной
 *
 * Тесты маршрута доказывают, что ручка ставит цепочку и стирает прошлый прогон.
 * Они не доказывают главного для пользователя: что до этой ручки МОЖНО ДОЙТИ.
 * Ровно здесь и был дефект, ради которого кнопка появилась — прогон правил по
 * готовому тексту умел маршрут `/check`, но с экрана в эту ветку не вело ни
 * одного нажатия, и «перепроверить» на практике означало «распознать заново».
 * Сценарий проверяет путь целиком: кнопка видна, подтверждение спрашивают,
 * прошлая проверка исчезает.
 *
 * ## Почему папка отдельная
 *
 * Кнопка требует ОПУБЛИКОВАННОГО распознавания, а `folderRecheck` —
 * единственная папка стенда, у которой есть версия текста страницы. На папках
 * без него маршрут честно отказывает, и проверять там было бы нечего.
 *
 * Стенд поднимает портал БЕЗ воркера: задача ложится в очередь и остаётся
 * `queued`. Поэтому исход ищется в состоянии экрана и в очереди, а не в
 * результате разбора — дожидаться его здесь нечем и не нужно.
 */
import { expect, test } from '@playwright/test';
import { IDS, KC, signIn } from './support/session.js';

const RECHECK_URL = `/ids/folders/${IDS.folderRecheck}?tab=checks`;

test('перепроверка стирает прошлый результат и запускает разбор по готовому тексту', async ({
  page,
}) => {
  await signIn(page, KC.engineer, RECHECK_URL);

  // Прошлая проверка на экране: без неё «стёрлась» было бы нечему.
  await expect(page.getByTestId('checks-run-state')).toContainText('Проверка выполнена');

  const button = page.getByTestId('pipeline-recheck');
  await expect(button).toBeVisible();
  await button.click();

  /*
   * Подтверждение обязательно и проверяется здесь, а не «где-нибудь»: нажатие
   * стирает чужую работу и тратит вызовы модели, и кнопка без вопроса стоила бы
   * ровно этого при промахе по соседней.
   */
  await expect(page.getByText('Результат прошлой проверки будет стёрт.')).toBeVisible();
  await page.getByRole('button', { name: 'Проверить', exact: true }).click();

  // Прошлая проверка исчезла, и экран объясняет, что происходит вместо неё.
  await expect(page.getByTestId('checks-run-state')).not.toContainText('Проверка выполнена');
});

test('без распознанного текста кнопки перепроверки нет вовсе', async ({ page }) => {
  // У папки с разметкой распознавания нет: кнопки быть не должно вовсе —
  // предлагать действие, которое всегда отвечает отказом, значит учить не
  // замечать кнопки.
  await signIn(page, KC.engineer, `/ids/folders/${IDS.folderMarkup}?tab=checks`);
  await expect(page.getByTestId('pipeline-recheck')).toHaveCount(0);
});

test('подрядчику перепроверка тоже доступна: право то же, что у «Распознать»', async ({ page }) => {
  await signIn(page, KC.contractor, RECHECK_URL);
  await expect(page.getByTestId('pipeline-recheck')).toBeVisible();
});
