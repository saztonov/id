/**
 * Навигация «finding → evidence» и живая лента (§14, §16, §3.8).
 *
 * §16 называет переход от замечания к доказательству отдельным пунктом
 * приёмки, и проверять его надо там, где доказательство существует: на ревизии
 * с разметкой и блоками. Проверяется не наличие ссылки, а результат перехода —
 * открыта ТА страница рабочего документа и выделен ТОТ блок, на который
 * ссылается замечание.
 *
 * Проверки дерева документов здесь больше нет: раздел удалён вместе с ручной
 * сборкой (S27, ADR-0016). Ушла и проверка «границы правятся только
 * пересборкой» — границы теперь подтверждает конвейер, и объяснять
 * пользователю недоступный маршрут стало нечем и незачем.
 *
 * Файл идёт раньше `files`/`markup` по алфавиту, то есть на нетронутой разметке:
 * это осознанно — тест про адрес блока не должен зависеть от того, что с этим
 * блоком сделал предыдущий сценарий.
 */
import { expect, test } from '@playwright/test';
import { IDS, KC, signIn } from './support/session.js';

test('замечание ведёт на страницу и выделяет блок, а не печатает идентификатор', async ({
  page,
}) => {
  await signIn(page, KC.engineer, `/ids/folders/${IDS.folderMarkup}?tab=checks`);

  const evidence = page.getByTestId('evidence-AOSR.HDR.022');
  await expect(evidence).toBeVisible();
  // Номер сквозной по комплекту: замечание указывает на вторую страницу.
  await expect(evidence).toHaveText('2');

  await evidence.getByRole('link').first().click();

  // Открылась разметка на нужной странице: страница 2 повёрнута на 90°, и её
  // карточка в ленте помечена активной.
  await expect(page.getByRole('application')).toBeVisible();
  await expect(page).toHaveURL(/tab=markup/);

  // Блок замечания выделен: выбор блока в панели инструментов — второй,
  // клавиатурный путь к тому же выделению, и именно по нему видно, что адрес
  // доехал. Пустое поле означало бы, что страница открылась, а блок нет.
  await expect(page.getByTestId('selected-block')).toContainText(/% страницы/);
});

test('цитата доказательства заменяет удалённый раздел «Реквизиты»', async ({ page }) => {
  await signIn(page, KC.engineer, `/ids/folders/${IDS.folderMarkup}?tab=checks`);

  // Раздел «Реквизиты» удалён, и вместе с ним ушёл единственный экран, где было
  // видно, ЧЕМ подтверждается замечание. У фикстурного замечания доказательства
  // нет, поэтому проверяется, что экран не выдумывает его — пустая цитата хуже
  // отсутствующей.
  await expect(page.getByTestId('checks-report')).toBeVisible();
  await expect(page.getByText('в документе написано:')).toHaveCount(0);
});

/**
 * Отчёт проверки разложен по комплектам (S44).
 *
 * До нарезки папки на комплекты отчёт был плоским списком и складывал двенадцать
 * актов в одну таблицу из 134 строк: понять по ней, у КАКОГО акта чего не
 * хватает, было нельзя. Уровень введён миграцией 0059, заголовок группы строит
 * сервер (`titleOfComplect`) — и до сих пор через браузер не проверялся ни разу.
 */
test('отчёт проверки разложен по комплектам, а не одной таблицей', async ({ page }) => {
  await signIn(page, KC.engineer, `/ids/folders/${IDS.folderReview}?tab=checks`);

  const complect = page.getByTestId('checks-report-group-complect');
  await expect(complect).toBeVisible();
  // Заголовок называет акт реквизитами, а не порядковым номером: номер и дату
  // пишет в комплект барьер извлечения, и «Комплект 1» означал бы, что они
  // потерялись по дороге.
  await expect(complect).toContainText('Акт освидетельствования № 336 от 12.01.2026');

  // Документ комплекта и его замечание лежат ВНУТРИ группы, а не в «Вне
  // комплектов»: принадлежность держится на `complect_id` у документа и у
  // замечания, и без неё группа была бы пустым заголовком. Строка названа видом
  // ИД, а не наименованием документа, — так отчёт и печатает состав.
  await expect(complect).toContainText('Акт освидетельствования скрытых работ');
  await expect(complect).toContainText('ОГРН не проходит проверку контрольной суммы');
});

/** Адрес ленты событий ревизии — им же перехватывается поток ниже. */
const STREAM_URL = /\/api\/v1\/folders\/[^/]+\/events/u;

/**
 * Живой поток доказывается сетью, а не видом шапки.
 *
 * До этого сценарий ждал зелёную плашку «поток событий». Плашки больше нет:
 * индикатор молчит, пока свежесть держит поток, — и проверка «плашки нет»
 * доказывала бы ничего, потому что её нет и когда провайдер не смонтирован
 * вовсе. Поэтому живость берётся с сети: ответ 200 с `text/event-stream`.
 *
 * Заодно проверяется то, что прежний тест пропустил бы: переключение вкладок
 * НЕ переоткрывает поток. Провайдер живёт на уровне ревизии, и переоткрытие
 * означало бы, что вкладки роняют соединение и проигрывают ленту заново.
 */
test('экран ревизии держится живой лентой событий, а шапка о ней молчит', async ({ page }) => {
  const opened: string[] = [];
  page.on('request', (request) => {
    if (STREAM_URL.test(request.url())) opened.push(request.url());
  });

  // Ожидание ставится ДО входа: заголовки потока приходят сразу после
  // навигации, и подписка после неё опоздала бы к собственному ответу.
  const streamResponse = page.waitForResponse(
    (response) => STREAM_URL.test(response.url()) && response.status() === 200,
  );
  await signIn(page, KC.engineer, `/ids/folders/${IDS.folderMarkup}?tab=history`);

  // Тело намеренно не читается: поток не закрывается, и `body()` ждал бы конца,
  // которого нет.
  expect((await streamResponse).headers()['content-type']).toContain('text/event-stream');

  // Экран ревизии загружен — значит и шапка отрисована, и «плашки нет» говорит
  // о шапке, а не о недорисованной странице.
  await expect(page.getByRole('tab', { name: 'Файлы' })).toBeVisible();
  await expect(page.getByTestId('stream-status')).toHaveCount(0);

  const beforeSwitch = opened.length;
  await page.getByRole('tab', { name: 'Файлы' }).click();
  await expect(page.getByTestId('file-input')).toBeVisible();
  expect(opened).toHaveLength(beforeSwitch);
  await expect(page.getByTestId('stream-status')).toHaveCount(0);
});

/**
 * Деградация обязана быть громкой.
 *
 * Молчание шапки читается как «экран обновляется сам», и оно честно ровно
 * потому, что потерянный поток о себе говорит. Без этой проверки индикатор
 * можно было бы выключить целиком, и первый сценарий остался бы зелёным.
 */
test('потерянный поток называет себя, а не молчит вместе с живым', async ({ page }) => {
  // Перехват ставится ДО входа: открытое соединение живёт до получаса, и отказ,
  // включённый после, не оборвал бы его.
  await page.route(STREAM_URL, (route) => route.abort('failed'));

  await signIn(page, KC.engineer, `/ids/folders/${IDS.folderMarkup}?tab=history`);

  // Первая же неудачная попытка переводит цикл в «восстанавливается» и держит
  // его до исчерпания попыток; экран при этом остаётся рабочим — свежесть
  // держит опрос.
  await expect(page.getByTestId('stream-status')).toHaveText('поток восстанавливается');
  await expect(page.getByRole('tab', { name: 'Файлы' })).toBeVisible();
});
