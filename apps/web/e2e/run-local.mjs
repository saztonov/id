/**
 * Прогон сквозных сценариев локального входа.
 *
 * Обёртка нужна ради переносимости: `VAR=value команда` — синтаксис POSIX-оболочки,
 * а скрипты пакета на Windows исполняет cmd, где такая строка просто не запустится.
 * Заводить ради одной переменной зависимость вроде `cross-env` дороже, чем десять
 * строк здесь: стандарт требует сверять версии всех зависимостей, и каждая новая
 * — это ещё одна строка в этой сверке.
 *
 * Переменная передаётся и самому Playwright (он выбирает набор сценариев), и
 * стенду через наследование окружения (он выбирает режим портала).
 */
/* global process */
import { spawnSync } from 'node:child_process';

const result = spawnSync('playwright', ['test', ...process.argv.slice(2)], {
  stdio: 'inherit',
  shell: true,
  env: { ...process.env, E2E_AUTH_MODE: 'local' },
});

process.exit(result.status ?? 1);
