/**
 * Подсказки к полю пароля.
 *
 * КОПИЯ серверной политики (`apps/api/src/auth/local/policy.ts`), и это
 * сознательно. Решение принимает сервер: он проверяет длину, разнообразие,
 * список распространённых паролей, прогулки по клавиатуре и совпадение с
 * личными данными, и его отказ приходит списком в ответе 422. Здесь — только
 * текст, чтобы человек узнал требования до отправки формы, а не после.
 *
 * Тот же приём и та же оговорка, что у копии матрицы прав в `app/session.tsx`:
 * расхождение копии с оригиналом ухудшает подсказку, но не открывает доступ.
 */

/** Умолчание совпадает с `AUTH_LOCAL_PASSWORD_MIN_LENGTH`. */
const FALLBACK_MIN_LENGTH = 12;

/** Ниже этой длины сервер требует три вида символов из четырёх. */
const LENGTH_WITHOUT_CLASSES = 16;

export function passwordHints(minLength: number | undefined): string {
  const min = minLength ?? FALLBACK_MIN_LENGTH;

  return (
    `Не короче ${String(min)} символов. ` +
    `Пароль короче ${String(LENGTH_WITHOUT_CLASSES)} символов должен содержать минимум ` +
    'три вида символов: строчные и прописные буквы, цифры, знаки — длинной парольной фразе ' +
    'это не требуется. Нельзя использовать распространённые пароли, подряд идущие клавиши ' +
    'и части своего адреса, имени или названия организации.'
  );
}
