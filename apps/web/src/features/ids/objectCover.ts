/** Запасная пара: недостижима при непустом коде, но снимает `undefined` при индексации. */
const FALLBACK_STOPS: readonly [string, string] = ['#25619d', '#154779'];

/**
 * FNV-1a на 32 битах с финальным перемешиванием.
 *
 * Перемешивание (два сдвига и умножение) добавлено не для красоты: без него
 * различие в одном ПОСЛЕДНЕМ символе оседает в младших битах, а слот берётся из
 * старших. Кодовые точки читаются через `codePointAt`, потому что код объекта по
 * контракту — любые буквы или цифры, включая кириллицу
 * (`objectCodeSchema`, `/^[\p{L}\p{N}]{1,5}$/u`).
 */
function hashCode(code: string): number {
  let hash = 0x811c9dc5;
  for (const ch of code.toLowerCase()) {
    hash ^= ch.codePointAt(0) ?? 0;
    hash = Math.imul(hash, 0x01000193);
  }
  hash ^= hash >>> 15;
  hash = Math.imul(hash, 0x2545f491);
  hash ^= hash >>> 13;
  return hash >>> 0;
}

/**
 * Градиент обложки: детерминирован по коду и переживает переименование объекта.
 *
 * Слот берётся из СТАРШИХ битов (`>>> 27`), а не остатком от деления: у
 * мультипликативного хеша младшие биты перемешаны хуже старших, и на контрольной
 * выборке кодов остаток давал совпадение `zil18` с `msk1`, а сдвиг — ни одного.
 */
export function coverGradient(code: string): string {
  const stops = COVER_STOPS[hashCode(code) >>> 27] ?? FALLBACK_STOPS;
  return `linear-gradient(135deg, ${stops[0]} 0%, ${stops[1]} 100%)`;
}

/**
 * Буквы наименования: первые буквы двух первых слов, иначе две первые буквы.
 *
 * Слова, начинающиеся с цифры, пропускаются: «1-я очередь строительства» это
 * «ЯО», а не «1О» — цифра в качестве опознавательного знака бесполезна, она
 * повторяется у половины объектов.
 */
export function objectInitials(name: string): string {
  const words = name.split(/[^\p{L}\p{N}]+/u).filter((word) => /^\p{L}/u.test(word));
  const [first, second] = words;
  if (first === undefined) {
    const fallback = name.trim().slice(0, 1);
    return fallback === '' ? '?' : fallback.toUpperCase();
  }
  if (second === undefined) return first.slice(0, 2).toUpperCase();
  return `${first.slice(0, 1)}${second.slice(0, 1)}`.toUpperCase();
}
