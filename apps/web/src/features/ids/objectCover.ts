/**
 * Обложка карточки объекта: цвет по коду и буквы по наименованию.
 *
 * Фотографий у объектов ИД нет и не заводится, поэтому обложка — не картинка, а
 * опознавательный знак: человек возвращается в этот раздел каждый день и ищет
 * глазами один и тот же объект. Работает это цветовым пятном, а не чтением
 * подписей, и цвет обязан быть закреплён за объектом навсегда — отсюда хеш от
 * кода, а не порядковый номер в списке: раздача цветов по позиции меняла бы
 * цвет объекта при заведении соседнего, то есть ломала бы ровно то узнавание,
 * ради которого всё и делается.
 *
 * ## Почему таблица цветов, а не формула
 *
 * Портал смет считает оттенок формулой `hsl(charCodeAt(0) * 37 % 360, 60%, 55%)`
 * (`client/src/components/shared/placeholderCover.tsx`). Здесь она не годится
 * дважды.
 *
 * Во-первых, хеш по ПЕРВОМУ символу: коды объектов одной стройки —
 * `zil18`, `zil19`, `zil27` — получают побайтово один и тот же цвет, то есть
 * знак перестаёт различать ровно те объекты, которые чаще всего путают.
 *
 * Во-вторых, обложка несёт БЕЛЫЕ буквы, то есть является фоном текста, и её
 * контраст обязан проверяться, а не предполагаться. Проверить вычисленный на
 * лету `hsl()` нечем: порог зависит от оттенка нелинейно — при насыщенности
 * 62 % белый держит 4.5:1 до светлоты 54.6 % на красном и всего до 29.7 % на
 * жёлтом. Формула со светлотой 55 % даёт на жёлтом `#d1d147` контраст 1.62:1
 * при требуемых 4.5:1, и это не мелочь на проценты, а разница в три раза.
 *
 * Автоматика такую ошибку не поймает: `linear-gradient` — это
 * `background-image`, правило `color-contrast` в axe возвращает на нём
 * `incomplete`, а гейт §17 смотрит только `violations`. Значит контраст обязан
 * быть заложен в данные и проверен собственным тестом — см. `objectCover.test.ts`.
 *
 * Поэтому цвета лежат таблицей: 16 оттенков с шагом золотого угла (137.5°, при
 * нём соседние клетки далеки по цвету сами по себе) на двух уровнях
 * насыщенности, а светлота КАЖДОЙ клетки подобрана под постоянную
 * относительную яркость — 0.115 у верхнего стопа, 0.062 у нижнего. Все обложки
 * портала поэтому одинаково тёмные и различаются только цветом, а худший
 * контраст белого по всей таблице — 6.16:1 при пороге 4.5:1.
 *
 * ## Совпадения цветов допускаются
 *
 * Тридцать два слота при десятке объектов дают совпадение примерно в девяти
 * случаях из десяти (парадокс дней рождения). Это осознанный размен, а не
 * недосмотр: увеличивать таблицу вредно — при 64 клетках шаг между оттенками
 * падает до 11°, и цвета станут «почти одинаковыми», то есть вернётся та самая
 * проблема, от которой уходим. Совпадение не мешает: у таких объектов
 * различаются инициалы, наименование и код, а цвет работает грубым фильтром
 * «не туда смотрю», а не идентификатором.
 */

