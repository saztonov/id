describe('КПП', () => {
  it('принимает ровно 9 знаков', () => {
    expect(checkKpp(KPP_9)).toEqual(ACCEPTED);
  });

  it('8 и 10 знаков отвергаются', () => {
    expect(checkKpp('77001234')).toEqual(rejected('length'));
    expect(checkKpp('7700123456')).toEqual(rejected('length'));
  });

  it('латинские буквы кода причины постановки на учёт не принимаются', () => {
    // Не упущение: так же ограничивает значение CHECK `counterparties_kpp_chk`,
    // и расхождение схемы с БД дало бы 500 вместо внятного отказа на границе.
    expect(checkKpp('7700AB345')).toEqual(rejected('non_digits'));
  });

  it('причины `checksum` у КПП не бывает: контрольной суммы у него нет', () => {
    for (const value of [KPP_9, '000000000', '999999999', '123456789']) {
      expect(checkKpp(value)).toEqual(ACCEPTED);
    }
    for (const value of ['', '7', '7700123456', '7700-2345']) {
      expect(defectOf(checkKpp(value))).not.toBe('checksum');
    }
  });
});

// =====================================================================
// Порождение контрольных цифр: та же арифметика, что и проверка
// =====================================================================

describe('порождение контрольных цифр согласовано с проверкой', () => {
  it('дописанная контрольная цифра делает значение принятым', () => {
    // Свойство, ради которого арифметика в портале одна: обезличиватель корпуса
    // (§1.4) СТРОИТ синтетические реквизиты этими функциями, а портал судит о них
    // `check*`. Разойдись они — «валидный» ИНН производного корпуса перестал бы
    // быть валидным для портала, и обезличенные фикстуры проверяли бы не то.
    for (const body of ['770012345', '000123456', '999999999']) {
      expect(checkInn(body + innControlDigits(body))).toEqual(ACCEPTED);
    }
    for (const body of ['7700123456', '0001234567', '9999999999']) {
      expect(checkInn(body + innControlDigits(body))).toEqual(ACCEPTED);
    }
    for (const body of ['102770012345', '000000000000']) {
      expect(checkOgrn(body + ogrnControlDigit(body))).toEqual(ACCEPTED);
    }
    for (const body of ['30277001234567', '00000000000000']) {
      expect(checkOgrn(body + ogrnControlDigit(body))).toEqual(ACCEPTED);
    }
  });

  it('испорченная контрольная цифра отвергается ИМЕННО по сумме', () => {
    // Обезличиватель обязан сохранять и НАМЕРЕННУЮ невалидность: он портит ровно
    // последний знак, и причина отказа обязана остаться `checksum`. Иначе класс
    // дефекта в производном корпусе сменится с `undetermined` на `fail`.
    const body = '102770012345';
    const control = ogrnControlDigit(body);
    const spoiled = String((Number(control) + 1) % 10);
    expect(checkOgrn(body + spoiled)).toEqual(badSum(control, spoiled));
  });

  it('порождённые цифры совпадают с посчитанными в этом файле значениями', () => {
    expect(innControlDigits(INN_10.slice(0, 9))).toBe('9');
    // Две цифры возвращаются строкой: «06» — это не 6.
    expect(innControlDigits(INN_12.slice(0, 10))).toBe('06');
    expect(ogrnControlDigit(OGRN_13.slice(0, 12))).toBe('0');
    expect(ogrnControlDigit(OGRN_15.slice(0, 14))).toBe('9');
  });

  it('тело неверной длины — ошибка вызывающего, а не значение с плохой суммой', () => {
    // Молчаливый ноль вместо исключения дал бы ЛОЖНОЕ подтверждение реквизита:
    // проверка сказала бы «сумма сходится» о значении, которого не считала.
    expect(() => innControlDigits('7700')).toThrow(RangeError);
    expect(() => ogrnControlDigit('102770012345678')).toThrow(RangeError);
    expect(() => innControlDigits('77001234A')).toThrow(TypeError);
  });
});
