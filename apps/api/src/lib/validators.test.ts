/**
 * Контрольные суммы ИНН и ОГРН, форма КПП.
 *
 * ## Значения синтетические, классы дефектов — из корпуса
 *
 * Реальные ИНН и ОГРН участников в код и тесты не попадают: это держит
 * `pnpm pii:scan`, поэтому оба известных битых значения корпуса живут только в
 * `docs/CORPUS_FINDINGS.md`, где их и можно перепроверить. Здесь воспроизводятся
 * их КЛАССЫ на синтетических значениях:
 *
 * | Класс из корпуса           | Представитель здесь | `defect`   | Вердикт §9.2   |
 * | -------------------------- | ------------------- | ---------- | -------------- |
 * | 12 цифр вместо 13          | `102770012345`      | `length`   | `fail`         |
 * | 13 цифр, сумма не сходится | `1027700123451`     | `checksum` | `undetermined` |
 *
 * Различие ровно этих двух строк — единственная причина, по которой функции
 * возвращают причину отказа, а не `boolean`. Первый случай обвиняет подрядчика в
 * оформлении документа, второй — только распознавание (значение вычитано с
 * печати, перекрытой подписью). Правило, слившее их в одно «невалидно», выдало бы
 * ложное обвинение в подделке реквизитов, поэтому проверки ниже сравнивают
 * результат ЦЕЛИКОМ, а не через `.ok`: отказ с верной причиной и отказ с чужой
 * причиной — разные результаты.
 *
 * ## Откуда берутся функции
 *
 * `check*` берутся через `lib/validators.js` — тем же путём, которым их видит
 * продакшн (`modules/catalog/schemas.ts`), так что тест заодно держит полноту
 * реэкспорта. Сама реализация лежит в `@id/contracts`: копий арифметики в портале
 * больше нет, потому что обезличиватель корпуса обязан судить о валидности ровно
 * так же (§1.4). Оттуда же напрямую берутся ПОРОЖДАЮЩИЕ функции — API их не
 * вызывает, а проверить их согласие с `check*` нужно именно здесь, где посчитаны
 * ожидаемые контрольные цифры.
 */
import { describe, expect, it } from 'vitest';

import { innControlDigits, ogrnControlDigit } from '@id/contracts';

import { checkInn, checkKpp, checkOgrn, type IdentifierCheck } from './validators.js';

// =====================================================================
// Синтетические значения с посчитанными контрольными цифрами
// =====================================================================

/** ИНН организации: взвешенная сумма даёт контрольную цифру 9. */
const INN_10 = '7700123459';

/** ИНН физического лица: сходятся ОБЕ контрольные цифры — 11-я «0» и 12-я «6». */
const INN_12 = '770012345606';

/** Тот же ИНН с испорченной ВТОРОЙ контрольной цифрой; первая по-прежнему верна. */
const INN_12_SECOND_BROKEN = '770012345607';

/** ОГРН организации: остаток первых 12 цифр по модулю 11 равен 0. */
const OGRN_13 = '1027700123450';

/** Тот же ОГРН, у которого при наборе потеряна последняя цифра: 12 знаков. */
const OGRN_12 = '102770012345';

/** Тот же ОГРН с верной длиной и неверной контрольной цифрой: ожидалась 0, стоит 1. */
const OGRN_13_BROKEN_SUM = '1027700123451';

/** ОГРНИП: остаток первых 14 цифр по модулю 13 равен 9. */
const OGRN_15 = '302770012345679';

const KPP_9 = '770012345';

const ACCEPTED: IdentifierCheck = { ok: true };

function rejected(defect: 'empty' | 'non_digits' | 'length'): IdentifierCheck {
  return { ok: false, defect, checksum: null };
}

function badSum(expected: string, actual: string): IdentifierCheck {
  return { ok: false, defect: 'checksum', checksum: { expected, actual } };
}

/** Причина отказа либо `null` у принятого значения: сравнивать причины прямо. */
function defectOf(result: IdentifierCheck): string | null {
  return result.ok ? null : result.defect;
}

// =====================================================================
// ИНН
// =====================================================================

describe('ИНН', () => {
  it('принимает 10 знаков организации и 12 знаков физического лица', () => {
    expect(checkInn(INN_10)).toEqual(ACCEPTED);
    expect(checkInn(INN_12)).toEqual(ACCEPTED);
  });

  it('11 знаков отвергаются по длине: такой длины ИНН не существует', () => {
    expect(checkInn('77001234560')).toEqual(rejected('length'));
  });

  it('9 и 13 знаков тоже отвергаются по длине', () => {
    expect(checkInn('770012345')).toEqual(rejected('length'));
    expect(checkInn('7700123456060')).toEqual(rejected('length'));
  });

  it('верная длина и неверная сумма дают ДРУГУЮ причину и называют обе цифры', () => {
    // Один знак отличается от INN_10, длина та же. Текст замечания строится по
    // `checksum`, и без него инженер не знает, читать ли реквизит заново.
    expect(checkInn('7700123458')).toEqual(badSum('9', '8'));
  });

  it('вторая контрольная цифра 12-значного ИНН обязательна', () => {
    // Значение проходит первую проверку и падает на второй. Реализация,
    // считающая только первую цифру, приняла бы одну OCR-ошибку в последнем
    // знаке насквозь.
    expect(checkInn(INN_12_SECOND_BROKEN)).toEqual(badSum('6', '7'));
  });

  it('пустое значение и посторонние символы различаются между собой', () => {
    expect(checkInn('')).toEqual(rejected('empty'));
    // Значение НЕ нормализуется: решение «здесь пробел лишний» принимает
    // нормализация извлечённого реквизита, которая видит контекст страницы.
    expect(checkInn('7700 12345 9')).toEqual(rejected('non_digits'));
    expect(checkInn('7700-123459')).toEqual(rejected('non_digits'));
    // Неразрывный пробел — то, что OCR ставит в номерах чаще обычного.
    expect(checkInn('7700\u00a0123459')).toEqual(rejected('non_digits'));
    expect(checkInn('770012345Z')).toEqual(rejected('non_digits'));
  });

  it('порядок проверок фиксирован: символы важнее длины, длина важнее суммы', () => {
    // Верная длина, непригодное содержимое: причина обязана быть `non_digits`,
    // а не `checksum`. Контрольная сумма на нецифрах не имеет смысла, а
    // `checksum` в §9.2 означает дефект распознавания, а не мусор во вводе.
    expect(checkInn('ABCDEFGHIJ')).toEqual(rejected('non_digits'));
    // 11 цифр: контрольной цифры у такой длины нет по определению, поэтому
    // отказ — `length`, и никакая сумма при этом не считается.
    expect(checkInn('77001234599')).toEqual(rejected('length'));
  });
});

// =====================================================================
// ОГРН: главное различение §9.2
// =====================================================================

describe('ОГРН: длина и контрольная сумма — разные дефекты', () => {
  it('принимает 13 знаков организации и 15 знаков ИП', () => {
    expect(checkOgrn(OGRN_13)).toEqual(ACCEPTED);
    expect(checkOgrn(OGRN_15)).toEqual(ACCEPTED);
  });

  it('12 знаков отвергаются ИМЕННО по длине, а не по контрольной сумме', () => {
    // Полное сравнение результата, а не проверка «отказано»: подмена причины на
    // `checksum` превратила бы дефект оформления документа (§9.2 — `fail`) в
    // дефект распознавания (`undetermined`), то есть сняла бы с подрядчика
    // замечание, которое обязано быть предъявлено.
    expect(checkOgrn(OGRN_12)).toEqual(rejected('length'));
    expect(defectOf(checkOgrn(OGRN_12))).toBe('length');
  });

  it('верная длина и неверная сумма дают причину `checksum` с обеими цифрами', () => {
    expect(checkOgrn(OGRN_13_BROKEN_SUM)).toEqual(badSum('0', '1'));

    // Два отказа обязаны различаться причиной: на одинаковой причине вызывающий
    // код не может выбрать между `fail` и `undetermined`.
    expect(defectOf(checkOgrn(OGRN_13_BROKEN_SUM))).not.toBe(defectOf(checkOgrn(OGRN_12)));
  });

  it('14 и 16 знаков — длина; пустое и нецифры — свои причины', () => {
    expect(checkOgrn('10277001234500')).toEqual(rejected('length'));
    expect(checkOgrn('1027700123450000')).toEqual(rejected('length'));
    expect(checkOgrn('')).toEqual(rejected('empty'));
    expect(checkOgrn('1027700 123450')).toEqual(rejected('non_digits'));
  });
});

// =====================================================================
// ОГРН 15 знаков: целочисленный остаток
// =====================================================================

describe('ОГРН 15 знаков: остаток берётся целочисленно и по своему модулю', () => {
  it('модуль 15-значного — 13, а не 11', () => {
    expect(checkOgrn(OGRN_15)).toEqual(ACCEPTED);

    // Значение подобрано так, что модуль 11 дал бы контрольную цифру 0.
    // Реализация, применившая к 15 знакам правило 13-значного ОГРН, приняла бы
    // «…670» и отвергла настоящий ОГРНИП — то есть ровно наоборот.
    expect(checkOgrn('302770012345670')).toEqual(badSum('9', '0'));
  });

  it('остаток совпадает с BigInt-эталоном на границах области значений', () => {
    // Ожидание считается BigInt-ом здесь, независимо от реализации: тест
    // проверяет арифметику, а не переписывает её.
    for (const body of [
      '10000000000000',
      '30000000000000',
      '30277001234567',
      '99999999999999',
      '99999999999987',
    ]) {
      const expected = ((BigInt(body) % 13n) % 10n).toString();
      const wrong = String((Number(expected) + 1) % 10);

      expect(checkOgrn(`${body}${expected}`)).toEqual(ACCEPTED);
      expect(checkOgrn(`${body}${wrong}`)).toEqual(badSum(expected, wrong));
    }
  });

  /**
   * Честная граница: на 14 знаках `Number` ЕЩЁ точен.
   *
   * Тело 15-значного ОГРН — 14 цифр, то есть максимум 9,99·10¹³ против предела
   * точности 9,007·10¹⁵: запас почти два порядка. Значит утверждение «15-значный
   * ОГРН не влезает в Number» неверно, и тест, объявивший бы наивную реализацию
   * сломанной на настоящем ОГРНИП, был бы зелёным по ложной причине.
   *
   * Проверяется поэтому то, что действительно верно и действительно ценно:
   * BigInt-путь совпадает с точным ответом там, где точен и `Number`, и остаётся
   * точным за его пределом. Расхождение показано на 17 знаках — длине, которую
   * ОГРН не принимает, но которая доказывает цену выбора, а не только объявляет
   * её. Если завтра тот же код применят к идентификатору длиннее (внутренние
   * коды, реквизиты ЕАЭС), выбор уже сделан правильно.
   */
  it('за пределом точности Number наивное вычисление расходится с BigInt', () => {
    const withinNumber = '9'.repeat(14);
    expect(Number.isSafeInteger(Number(withinNumber))).toBe(true);
    expect(String((Number(withinNumber) % 13) % 10)).toBe(
      ((BigInt(withinNumber) % 13n) % 10n).toString(),
    );
    expect(checkOgrn(`${withinNumber}8`)).toEqual(ACCEPTED);

    const beyondNumber = '9'.repeat(17);
    expect(Number.isSafeInteger(Number(beyondNumber))).toBe(false);
    expect(String((Number(beyondNumber) % 13) % 10)).not.toBe(
      ((BigInt(beyondNumber) % 13n) % 10n).toString(),
    );
  });
});

