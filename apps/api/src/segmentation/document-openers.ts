/**
 * Слова, которыми открывается заголовок документа ИД.
 *
 * Вынесено из `classify.ts` без изменения состава списка. Причина выноса —
 * второй читатель: извлечение реквизитов (`extract.ts`) отвечает на вопрос
 * «какой из напечатанных на листе номеров принадлежит САМОМУ документу», и
 * сильнейший ответ на него — «тот, что стоит при заголовке». Копия списка во
 * втором файле означала бы, что вид документа, добавленный в один список,
 * второму неизвестен, и разойтись они могли бы молча: тесты у них разные.
 *
 * Тот же приём и по той же причине уже применён к `table-flow.ts` (S33).
 */

/**
 * Список закрытый и намеренно КОРОТКИЙ: он отвечает на вопрос «этот лист
 * начинает документ?», а не «какой это документ?». Ни одно слово здесь не
 * относится к разделу работ — иначе на незнакомом разделе классификатор
 * притягивал бы документы к знакомым видам (§0.5, п.6), то есть повторял бы
 * ошибку, ради которой открытый мир и вводится.
 *
 * Почему не «любая строка, набранная прописными»: вторая страница бланка
 * АОСР, шапка объекта и подписной блок тоже набраны прописными, и любая из
 * них открыла бы новый документ посреди существующего. Это тихая
 * высокоуверенная ошибка границы — по §16 она хуже, чем пропуск.
 */
export const DOCUMENT_OPENERS: readonly string[] = [
  'АКТ',
  'ПРОТОКОЛ',
  'ПАСПОРТ',
  'СЕРТИФИКАТ',
  'ДЕКЛАРАЦИЯ',
  'ЗАКЛЮЧЕНИЕ',
  'ВЕДОМОСТЬ',
  'ЖУРНАЛ',
  'РЕЕСТР',
  'РАЗРЕШЕНИЕ',
  'ПРИКАЗ',
  'ДОВЕРЕННОСТЬ',
  'СПРАВКА',
  'СВИДЕТЕЛЬСТВО',
  'ОТЧЁТ',
  'ОТЧЕТ',
  'ПИСЬМО',
];

// `\b` между пробелом и кириллической буквой границы слова не даёт: `\w`
// остаётся ASCII-классом даже под флагом `u`. Тот же дефект уже ловился в
// нормализации заголовка кандидата, поэтому конец открывающего слова выражен
// явно: либо конец строки, либо не-буква.
export const OPENER_RE = new RegExp(`^(?:${DOCUMENT_OPENERS.join('|')})(?:$|[^\\p{L}])`, 'u');

/**
 * Те же слова для шаблона БЕЗ флага `i`: прописью и с прописной буквы.
 *
 * Флаг `i` в шаблонах номера запрещён — на нём держится отделение служебных
 * слов «от», «с», «по» от продолжения номера (см. `NUMBER_STRONG` в
 * `extract.ts`), и включение его подмешивало бы в номер дату выдачи. Поэтому
 * регистронезависимость выражается перечислением ровно тех двух начертаний,
 * которыми заголовки печатают: «СВИДЕТЕЛЬСТВО О ПОВЕРКЕ» и «Свидетельство о
 * поверке». Третьего в корпусе нет.
 */
export const OPENER_ALTERNATION: string = DOCUMENT_OPENERS.flatMap((word) => [
  word,
  word.charAt(0) + word.slice(1).toLowerCase(),
]).join('|');
