/**
 * Документы, которых никто не ВЫДАЁТ и у которых нет срока действия.
 *
 * Две группы, и обе — по природе документа, а не по удобству:
 *
 * * акт освидетельствования (мирроринг `ACT_TYPES` правил): он не выдаётся
 *   органом, а составляется комиссией, и его дата — `act_date`, реквизит бланка
 *   со своим шаблоном «(дата составления акта)»;
 * * чертёж — исполнительная схема, генплан, схема сетей: он подписывается и
 *   штампуется, но не выдаётся и не истекает.
 *
 * Базовые шаблоны, применённые к таким документам, находят не «ничего», а
 * ЧУЖОЕ. Акт комплекта `№01_Бл_П` получил «выдан 10.04.2023, действует до
 * 01.08.2026»: первая дата — из договора строительного контроля в шапке, вторая
 * — из сертификата на песок, названного в п. 3; обе показаны на экране в шапке
 * акта как его собственные. Исполнительная схема того же комплекта получила
 * «выдан 26.12.2020» — дату альбома типовых дорожных конструкций из примечания.
 *
 * Исключение именно для этих двух групп, а не общий запрет: у сертификата,
 * паспорта и свидетельства дата выдачи и срок действия законны и нужны
 * проверкам сроков (§9.2).
 */
const NOT_ISSUED_TYPE_RE = /^aosr|^exec_|^other_exec_schemes$/u;

const FIELDS_ABSENT_IN_NOT_ISSUED: ReadonlySet<string> = new Set([
  'issued_at',
  'valid_from',
  'valid_to',
  'valid_until',
]);

/**
 * Базовые реквизиты. Применяются ко ВСЕМ документам без исключения.
 *
 * `typeConfident` здесь не читается намеренно: условие на уверенность означало
 * бы, что документ незнакомого вида остаётся без номера и дат, то есть выпадает
 * и из сверки с реестром, и из проверок сроков. `docTypeCode` читается ровно для
 * одного вычета — реквизитов, которых у акта и чертежа не существует (см.
 * `NOT_ISSUED_TYPE_RE`).
 */
export function extractBaseFields(input: ExtractionInput): readonly ExtractedField[] {
  const fields: ExtractedField[] = [];
  const notIssued = input.docTypeCode !== null && NOT_ISSUED_TYPE_RE.test(input.docTypeCode);

  for (const definition of BASE_EVIDENCE_FIELDS) {
    if (definition.extractor !== 'rule') continue;
    if (notIssued && FIELDS_ABSENT_IN_NOT_ISSUED.has(definition.code)) continue;
    const rule = RULES_BY_CODE.get(definition.code);
    if (rule === undefined) continue;

    const field = runRule(rule, input.pages);
    if (field !== null) fields.push(field);
  }

  return fields;
}

/**
 * Типо-специфичные реквизиты. Только при уверенно определённом типе.
 *
 * При `typeConfident === false` возвращается пустой список, и это не потеря:
 * базовые реквизиты уже извлечены, а специфичный экстрактор на документе
 * чужого вида нашёл бы не «ничего», а НЕ ТО — например, взял бы за класс
 * бетона обозначение с чертежа.
 */
export function extractTypeFields(input: ExtractionInput): readonly ExtractedField[] {
  if (!input.typeConfident || input.docTypeCode === null) return [];

  const definition = DOC_TYPES.find((type) => type.code === input.docTypeCode);
  if (definition === undefined) return [];

  const fields: ExtractedField[] = [];

  for (const field of fieldsForType(definition.fieldSchema, definition.kind)) {
    if (field.extractor !== 'rule') continue;
    // Базовые коды уже извлечены `extractBaseFields`; `fieldsForType` их
    // подмешивает, и без этого фильтра значения удвоились бы.
    if (BASE_CODES.has(field.code)) continue;

    const rule = RULES_BY_CODE.get(field.code);
    if (rule === undefined) continue;

    const extracted = runRule(rule, input.pages);
    if (extracted !== null) fields.push(extracted);
  }

  return fields;
}

/**
 * Реквизиты-даты, у которых есть СВОЯ подпись в документе.
 *
 * Дата, найденная одним из них по ярлыку, уже названа документом: «Действительно
 * до», «Дата изготовления», «Дата испытаний». Слабая ступень `issued_at`
 * ярлыков не читает и берёт первую подходящую форму — то есть ту же самую.
 */
const LABELLED_DATE_CODES: ReadonlySet<string> = new Set([
  // `valid_from` сюда НЕ входит, и это не пропуск. Начало срока действия и дата
  // выдачи у сертификата совпадают по существу: «Срок действия с 05.05.2022 по
  // 04.05.2025» — единственная дата, которую бланк печатает, и она же и есть
  // дата выдачи. Сняв её, портал отвечал бы `CERT.600` «поле „Дата выдачи“ не
  // заполнено» на сертификате, который заполнен.
  'valid_to',
  'valid_until',
  'manufactured_at',
  'issuer_accreditation_valid_to',
  'tested_at',
  'sampled_at',
  'made_at',
  'measured_at',
  'shipped_at',
  'order_date',
]);

/**
 * Слабая дата выдачи, занятая другим реквизитом, снимается.
 *
 * Три свидетельства о поверке комплекта `№01_Бл_П` печатают ровно одну дату
 * заметно: «Действительно до 16.04.2025 г.». Она законно уходит в `valid_to`, а
 * слабая ступень `issued_at` находила ТУ ЖЕ подстроку — и документ получал
 * «выдан 16.04.2025, до 16.04.2025», то есть выдан в день окончания действия.
 *
 * Сверка идёт по СПАНУ, а не по значению: одинаковая дата в двух разных местах
 * документа — это два разных факта («изготовлено 07.09.2023» и «выдан
 * 07.09.2023» могут совпасть законно), а один и тот же участок текста дважды
 * реквизитом быть не может.
 *
 * Снимается только слабая находка. Дата, названная ярлыком выдачи, остаётся,
 * даже если совпала с чужим спаном: у неё есть собственное основание.
 */
function dropBorrowedIssuedAt(fields: readonly ExtractedField[]): readonly ExtractedField[] {
  const issued = fields.find((field) => field.fieldCode === 'issued_at');
  const evidence = issued?.evidence ?? null;
  if (issued === undefined || evidence === null || issued.confidence > CONFIDENCE.weak) {
    return fields;
  }

  const borrowed = fields.some(
    (field) =>
      LABELLED_DATE_CODES.has(field.fieldCode) &&
      field.evidence !== null &&
      field.evidence.pageTextVersionId === evidence.pageTextVersionId &&
      field.evidence.charStart === evidence.charStart &&
      field.evidence.charEnd === evidence.charEnd,
  );

  return borrowed ? fields.filter((field) => field !== issued) : fields;
}

/**
 * Оба уровня вместе — то, что вызывает job извлечения.
 *
 * Порядок: сначала базовые, затем специфичные. Поля с `extractor: 'llm'` в
 * результате отсутствуют по построению — их место занимает LLM-стадия.
 *
 * Пост-проход стоит здесь, а не внутри правила: правило видит только свой
 * шаблон, а вопрос «не занята ли эта дата другим реквизитом» задаётся о наборе
 * целиком и ответ на него зависит от типо-специфичных правил тоже.
 */
export function extractFields(input: ExtractionInput): readonly ExtractedField[] {
  const base = extractBaseFields(input);
  const seen = new Set(base.map((field) => field.fieldCode));

  return dropBorrowedIssuedAt([
    ...base,
    ...extractTypeFields(input).filter((field) => !seen.has(field.fieldCode)),
  ]);
}

