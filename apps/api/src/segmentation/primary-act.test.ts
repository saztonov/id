/**
 * Опознание акта по форме бланка.
 *
 * ## Почему тексты синтетические, а раскладка — настоящая
 *
 * Признаки калиброваны по шести реальным актам `temp/MD/new`, но фикстуры здесь
 * собраны из печатных подписей граф бланка РД-11-02 без единого значения из
 * документов: наименований организаций, фамилий и адресов в тестах нет.
 *
 * ## Что именно проверяется
 *
 * Не «функция возвращает массив», а два дефекта, каждый из которых уже
 * наблюдался на корпусе:
 *
 * 1. протокол лабораторных испытаний содержит девять нумерованных строк подряд
 *    («1. Наименование Заказчика», «2. Заказ/Заявка», …) и был бы опознан как
 *    акт, если бы признаком считались нумерованные пункты;
 * 2. раскладка бланка непостоянна — в одном пакете первый лист несёт только
 *    шапку, а все семь пунктов уезжают на второй, и детектор формы честно
 *    видит там бланк. Отличить второй лист от первого листа СЛЕДУЮЩЕГО акта
 *    можно только по собственному заголовку.
 */
import { describe, expect, it } from 'vitest';

import {
  detectActContinuation,
  detectPrimaryAct,
  isActContinuation,
  isPrimaryAct,
} from './primary-act.js';

/** Первый лист: титул, строка осмотра, п. 1. */
const FIRST_SHEET = [
  '**АКТ**',
  '',
  '**освидетельствования скрытых работ**',
  '',
  '№ 01-СИН/П',
  '',
  '**произвели осмотр работ, выполненных:**',
  '',
  '**1. К освидетельствованию предъявлены следующие работы:**',
  '',
  '**2. Работы выполнены по проектной документации:**',
].join('\n');

/** Второй лист: пункты 4–7 и подписи. Собственного заголовка нет. */
const SECOND_SHEET = [
  '**4. Предъявлены документы, подтверждающие соответствие работ предъявляемым к ним требованиям:**',
  '',
  '5. Даты: начала работ "27" сентября 2024 г.',
  'окончания работ "04" октября 2024 г.',
  '',
  '**6. Работы выполнены в соответствии с:**',
  '',
  '**7. Разрешается производство последующих работ:**',
  '',
  'Дополнительные сведения',
].join('\n');

/** Протокол испытаний: девять нумерованных строк, ни одной фразы бланка. */
const LAB_PROTOCOL = [
  '1. Наименование Заказчика*: СИНТЕТ-ГРУПП',
  '2. Заказ*/Заявка: 04-131-24/Ф711',
  '3. Адрес отбора проб*: синтетический адрес',
  '4. Место и точка отбора проб*: синтетическая точка',
  '5. Наименование образца испытаний: образец',
  '6. Наименование объекта: объект',
  '7. Информация по отбору Отбор проб выполнил: Заказчик',
  '8. Дата(ы) проведения испытаний: 20.11.2024',
  '9. Наименование применяемой методики: методика',
].join('\n');

describe('detectPrimaryAct — первый лист бланка', () => {
  it('опознаёт бланк по фразам печатной формы', () => {
    const evidence = detectPrimaryAct(FIRST_SHEET);

    expect(isPrimaryAct(evidence)).toBe(true);
    expect(evidence.hasStrong).toBe(true);
    expect(evidence.markers).toContain('строка титула «АКТ»');
    expect(evidence.markers).toContain('предъявлены работы');
  });

  it('опознаёт бланк и без титула — ради этого признак и заведён', () => {
    // Титул срезан сканом либо не распознан: якорь каталога не сработает,
    // а форма воспроизведена целиком.
    const withoutTitle = FIRST_SHEET.split('\n').slice(4).join('\n');
    const evidence = detectPrimaryAct(withoutTitle);

    expect(isPrimaryAct(evidence)).toBe(true);
    expect(evidence.titleLineIndex).toBe(-1);
  });
});

describe('detectPrimaryAct — чего он НЕ опознаёт', () => {
  it('протокол с девятью нумерованными пунктами актом не считается', () => {
    const evidence = detectPrimaryAct(LAB_PROTOCOL);

    expect(evidence.markers).toStrictEqual([]);
    expect(isPrimaryAct(evidence)).toBe(false);
  });

  it('одинокая строка «АКТ» типа не присваивает', () => {
    // «АКТ» открывает и акт приёмки, и акт входного контроля: одного признака
    // мало, иначе вид документа подменялся бы семейством.
    const evidence = detectPrimaryAct('**АКТ**\n\nприёмки выполненных работ');

    expect(evidence.markers).toStrictEqual(['строка титула «АКТ»']);
    expect(isPrimaryAct(evidence)).toBe(false);
  });

  it('двух слабых признаков без сильного мало', () => {
    const weakOnly = [
      '**2. Работы выполнены по проектной документации:**',
      '5. Даты: начала работ',
    ].join('\n');
    const evidence = detectPrimaryAct(weakOnly);

    expect(evidence.hasStrong).toBe(false);
    expect(evidence.markers).toHaveLength(2);
    expect(isPrimaryAct(evidence)).toBe(false);
  });

  it('пустой текст признаков не даёт', () => {
    expect(detectPrimaryAct('').markers).toStrictEqual([]);
  });
});

describe('detectActContinuation — второй лист', () => {
  it('опознаёт продолжение по пунктам 6-7', () => {
    const evidence = detectActContinuation(SECOND_SHEET);

    expect(isActContinuation(evidence)).toBe(true);
    expect(evidence.markers).toContain('п.6 соответствие нормативам');
  });

  it('одних слабых признаков подвала недостаточно', () => {
    // «Дополнительные сведения» печатается и в подвале акта приёмки:
    // присоединение по нему разорвало бы сразу два документа (§16).
    const evidence = detectActContinuation(
      'Дополнительные сведения\n\nАкт составлен в 4 экземплярах',
    );

    expect(evidence.hasStrong).toBe(false);
    expect(isActContinuation(evidence)).toBe(false);
  });

  it('первый лист продолжением не считается', () => {
    // Списки признаков не пересекаются намеренно: иначе первый лист СЛЕДУЮЩЕГО
    // акта был бы принят за продолжение предыдущего.
    expect(isActContinuation(detectActContinuation(FIRST_SHEET))).toBe(false);
  });

  it('протокол испытаний продолжением не считается', () => {
    expect(isActContinuation(detectActContinuation(LAB_PROTOCOL))).toBe(false);
  });
});

describe('признаки не называют раздела работ (§0.5, п. 6)', () => {
  it('ни один шаблон не содержит слов материала или конструкции', () => {
    // Признак обязан работать на разделе, которого система не видела. Проверка
    // идёт по ИСХОДНИКАМ шаблонов: они и есть то, что зашито в код.
    const source = [FIRST_SHEET, SECOND_SHEET]
      .join('\n')
      .toLowerCase()
      .replace(/[^а-яё\s.]/gu, ' ');
    const forbidden = ['кровл', 'армирован', 'арматур', 'гидроизоляц', 'бетон', 'монолит'];

    for (const marker of forbidden) {
      expect(source.includes(marker), `фикстура называет раздел работ: ${marker}`).toBe(false);
    }
  });
});
