/**
 * Подставляет страницу и её соседей в шаблон пользовательского промта.
 *
 * Соседи передаются урезанными: для решения о границе нужен конец
 * предыдущего листа и начало следующего, а не их содержимое целиком.
 * Полный текст соседей раздул бы промт втрое и вместе с ним — стоимость и
 * ключ кэша, который включает полный эффективный промт (§8.2).
 */
export function renderUserPrompt(
  page: PageInput,
  neighbours: { readonly before: PageInput | null; readonly after: PageInput | null },
  docTypeCodes: readonly string[],
  template: string = PAGE_CLASSIFY_PROMPT.user,
): string {
  const blocks = page.blockTypes.length > 0 ? page.blockTypes.join(', ') : 'блоков нет';
  const absent = '(страницы нет)';
  // Замена ФУНКЦИЕЙ, а не строкой: строковая замена трактует `$&`, `$'` и `$1`
  // как ссылки на совпадение, а текст страницы приходит от OCR и такие
  // последовательности содержать может. Тихое искажение текста в промте —
  // худший вид дефекта: ответ модели остаётся правдоподобным.
  const put = (text: string, token: string, value: string): string =>
    text.replace(token, () => value);
  let out = template;
  out = put(out, '{{DOC_TYPE_CODES}}', docTypeCodes.join(', '));
  out = put(out, '{{ORDINAL}}', String(page.revisionOrdinal));
  out = put(out, '{{ROTATION}}', `${page.rotation}°`);
  out = put(out, '{{BLOCKS}}', blocks);
  out = put(
    out,
    '{{BEFORE}}',
    neighbours.before ? clip(neighbours.before.text, NEIGHBOUR_TEXT_BUDGET) : absent,
  );
  out = put(out, '{{PAGE}}', clip(page.text, PAGE_TEXT_BUDGET) || '(текста нет)');
  out = put(
    out,
    '{{AFTER}}',
    neighbours.after ? clip(neighbours.after.text, NEIGHBOUR_TEXT_BUDGET) : absent,
  );
  return out;
}

