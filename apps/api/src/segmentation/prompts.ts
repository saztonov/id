/**
 * Тексты промтов сегментации по умолчанию (§8.2, фаза 2; §10).
 *
 * Это ЗНАЧЕНИЯ ПО УМОЛЧАНИЮ, а не источник правды прогона: боевой промт
 * берётся из `prompt_templates` в состоянии `published` и версионируется
 * отдельно. Здесь лежит текст, которым справочник заполняется при первом
 * развёртывании и с которым сверяются тесты.
 *
 * ## Главное требование к этим текстам — то, чего в них НЕТ (§0.5, п. 6)
 *
 * Промт не сообщает модели раздел работ и ничем на него не намекает. Корпус
 * покрывает два раздела из многих; промт, знающий про эти два, на третьем
 * начнёт притягивать документы к знакомым типам, и ошибка будет тихой и
 * высокоуверенной — ровно тот класс, который §16 ставит выше F1.
 *
 * Из этого следуют два неочевидных решения:
 *
 * 1. **Список типов передаётся целиком.** Отбор «релевантных разделу» кодов
 *    и был бы намёком: сам факт, что в списке остались только акты по
 *    несущим конструкциям, сообщает модели раздел вернее любого текста.
 * 2. **В промт уходят КОДЫ, а не названия типов.** Часть названий каталога
 *    содержит наименование материала или конструкции (`mix_quality_doc`,
 *    `act_formwork`), то есть название само по себе является подсказкой о
 *    разделе. Плата известна: код менее понятен модели, чем название, и
 *    качество на редких типах от этого ниже. Она принята сознательно —
 *    поднять качество можно калибровкой промта, а восстановить доверие
 *    после ложной классификации на новом разделе нечем.
 *
 * Запрет проверяется тестом, который сканирует эффективный промт на
 * маркерах разделов корпуса. Он относится к САМОМУ промту — шаблону, списку
 * кодов и инструкциям, — а не к тексту страницы, который в шаблон
 * подставляется: текст реального документа, разумеется, говорит о своём
 * предмете, и это данные, а не инструкция.
 */
import { DOC_TYPES } from '@id/doc-types';
import type { PageInput } from './types.js';

export interface PromptText {
  readonly system: string;
  readonly user: string;
}

/**
 * Маркеры разделов, которыми покрыт корпус, и слова материалов этих разделов.
 *
 * Список задан прямо, а не выведен из справочника: он должен пережить появление
 * новых разделов и продолжать проверять именно эти два, которые система видела
 * и к которым способна притягивать документы.
 *
 * Список живёт в коде, а не в тесте, потому что проверять надо не только тексты
 * по умолчанию. Боевой промт заполняет администратор через `prompt_templates`,
 * и запрет §0.5 п. 6 относится именно к тому, что уедет провайдеру. Проверка,
 * знающая только про константы этого файла, доказывала бы, что автор файла
 * ничего не нарушил, — и молчала бы о промте, опубликованном в бою.
 */
export const SECTION_MARKERS: readonly string[] = [
  'кровля',
  'кровел',
  'армирован',
  'арматур',
  'гидроизоляц',
  'бетон',
  '2.5.1',
  '2.1.5',
  'раздел работ',
  'монолит',
];

/**
 * Маркеры разделов, найденные в тексте. Пустой массив — запрет соблюдён.
 *
 * Применяется к ИНСТРУКЦИИ — системной части, шаблону пользовательской части,
 * списку кодов, — но не к тексту страницы, который в шаблон подставляется:
 * текст реального документа, разумеется, говорит о своём предмете, и это
 * данные, а не указание модели.
 */
export function findSectionMarkers(text: string): readonly string[] {
  const lower = text.toLocaleLowerCase('ru');
  return SECTION_MARKERS.filter((marker) => lower.includes(marker));
}

/**
 * Коды типов для промта.
 *
 * Резервные типы (`isFallback`) исключены, и это НЕ отбор по разделу:
 * `unknown_document` и `other_*` моделью не выбираются вовсе. Их присваивает
 * декодер, получив исход `other`, — вместе с записью наблюдённого заголовка
 * в `doc_type_candidates` (§3.2). Предложи мы их модели как обычные коды,
 * она выбрала бы резерв вместо честного `other`, и цикл роста каталога
 * остался бы без входных данных.
 */
export function promptDocTypeCodes(): readonly string[] {
  return DOC_TYPES.filter((t) => !t.isFallback).map((t) => t.code);
}

/** Сколько символов текста страницы уходит в промт. */
const PAGE_TEXT_BUDGET = 6000;
/** Сколько символов соседней страницы уходит в промт как контекст. */
const NEIGHBOUR_TEXT_BUDGET = 700;

function clip(text: string, budget: number): string {
  const trimmed = text.trim();
  if (trimmed.length <= budget) return trimmed;
  return `${trimmed.slice(0, budget)}\n…[текст обрезан]`;
}

