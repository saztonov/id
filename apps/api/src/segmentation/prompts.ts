/**
 * Подставляет документ и список полей в шаблон промта извлечения.
 *
 * Текст страниц склеивается подряд: реквизиты живут в шапке и подвале, и
 * постраничный вызов заставил бы модель отвечать по обрывку — на втором листе
 * четырёхлистного сертификата изготовителя нет вовсе, и честным ответом там
 * было бы `null` по всем полям.
 */
export function renderExtractUserPrompt(
  input: {
    readonly docTypeLabel: string;
    readonly fields: readonly { readonly code: string; readonly label: string }[];
    readonly pages: readonly { readonly text: string }[];
  },
  template: string = FIELD_EXTRACT_PROMPT.user,
): string {
  // Замена ФУНКЦИЕЙ, а не строкой: строковая замена трактует `$&`, `$'` и `$1`
  // как ссылки на совпадение, а текст приходит от OCR и такие
  // последовательности содержать может (см. `renderUserPrompt`).
  const put = (text: string, token: string, value: string): string =>
    text.replace(token, () => value);

  const fields = input.fields.map((field) => `- ${field.code}: ${field.label}`).join('\n');
  const document = clip(
    input.pages
      .map((page) => page.text.trim())
      .filter((text) => text.length > 0)
      .join('\n\n'),
    DOCUMENT_TEXT_BUDGET,
  );

  let out = template;
  out = put(out, '{{DOC_TYPE}}', input.docTypeLabel);
  out = put(out, '{{FIELDS}}', fields);
  out = put(out, '{{DOCUMENT}}', document || '(текста нет)');
  return out;
}
