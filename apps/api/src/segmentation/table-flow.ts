/**
 * Структурный признак «страница продолжает таблицу предыдущей» (§8.2).
 *
 * Вынесено из `decoder.ts` без единого изменения поведения. Причина выноса та
 * же, по которой из `registry.ts` был вынесен `md-table.ts`, — второй
 * читатель. Признак нужен уже фазе 1: якорь роли `signature_visual` означает
 * «на листе нет ничего, кроме штампа», и безголовое продолжение таблицы этот
 * ответ опровергает раньше, чем декодер вообще увидит метку. Импортировать
 * признак из декодера в классификатор нельзя — это инверсия фаз.
 *
 * ## Почему разбор строки здесь свой, а не из `md-table.ts`
 *
 * Тому разбору нужны ЗНАЧЕНИЯ ячеек, поэтому он снимает разметку и
 * экранирование; здесь нужны только число граф и их пустота, а шаблон
 * разделителя намеренно строже (`-{2,}` против `-{1,}`). Свести их в один —
 * изменить поведение обоих, и сделать это можно только замером, а не из
 * соображений опрятности.
 */

interface TableRow {
  readonly columns: number;
  readonly isSeparator: boolean;
  /** Все ячейки пусты. Так OCR печатает продолжение таблицы без шапки. */
  readonly isEmpty: boolean;
}

function tableRows(text: string): readonly TableRow[] {
  return text
    .split(/\r?\n/u)
    .map((l) => l.trim())
    .filter((l) => l.length > 0)
    .map((l) => {
      if (!l.startsWith('|') || !l.endsWith('|') || l.length < 3) return null;
      const cells = l.slice(1, -1).split('|');
      return {
        columns: cells.length,
        isSeparator: cells.every((c) => /^\s*:?-{2,}:?\s*$/u.test(c)),
        isEmpty: cells.every((c) => c.trim() === ''),
      };
    })
    .filter((r): r is TableRow => r !== null);
}

/**
 * Открывается ли страница таблицей — прежде любого текста.
 *
 * Второй вопрос к тем же строкам, и задаёт его фаза 1. `continuesTable`
 * отвечает «таблица предыдущего листа продолжается здесь», но сама по себе
 * этого мало, чтобы назвать лист продолжением документа: таблица может стоять
 * НИЖЕ собственного заголовка, и тогда лист начинает новый документ, а
 * совпадение ширины граф — случайность. Лист, у которого таблица идёт первой,
 * такого заголовка не имеет по построению.
 */
export function opensWithTable(text: string): boolean {
  const first = text
    .split(/\r?\n/u)
    .map((l) => l.trim())
    .find((l) => l.length > 0);
  return first !== undefined && first.startsWith('|') && first.endsWith('|') && first.length >= 3;
}

/**
 * Продолжает ли страница таблицу предыдущей.
 *
 * Признак структурный и единственный, которым лист без заголовка и без
 * счётчика вообще отличим от начала документа: таблица той же ширины,
 * начинающаяся БЕЗ шапки.
 *
 * ## Почему «есть строка-разделитель» само по себе ничего не значит
 *
 * Первая редакция считала новой таблицей любую, у которой вторая строка —
 * разделитель. На реальном корпусе это отбрасывало ровно тот случай, ради
 * которого правило написано: продолжение реестра приложений (АОСР № 336,
 * страница 4) начинается строкой `| | | | |` и следом `|---|---|---|---|`.
 * Иначе OCR и не может — синтаксис markdown ТРЕБУЕТ разделителя после первой
 * строки таблицы, поэтому разделитель есть у любой таблицы, включая
 * безголовое продолжение. Следствие было не косметическим: четырнадцать строк
 * реестра из двадцати девяти оставались бы за пределами документа, а сам лист
 * уходил бы в непривязанные. Найдено сквозным прогоном, а не чтением.
 *
 * Различает их СОДЕРЖИМОЕ первой строки: у настоящей шапки ячейки заполнены
 * («№ п/п», «Наименование документа»), у продолжения — пусты.
 */
export function continuesTable(previousText: string, text: string): boolean {
  const before = tableRows(previousText);
  const after = tableRows(text);
  const last = before.at(-1);
  const first = after[0];
  const second = after[1];
  if (!last || !first) return false;
  if (last.columns !== first.columns) return false;
  if (first.isSeparator) return false;
  // Шапка со значащими ячейками — новая таблица, то есть, скорее всего, новый
  // документ. Пустая «шапка» перед разделителем — та же таблица без шапки.
  if (second?.isSeparator === true && !first.isEmpty) return false;
  return true;
}
