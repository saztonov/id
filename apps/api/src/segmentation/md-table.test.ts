/**
 * Разбор ячейки markdown-таблицы (§8.3).
 *
 * У модуля не было ни одного собственного набора: его поведение проверялось
 * только через реестр приложений и опись передачи папки. Пропуск стоил дорого
 * — литеральное `<br>` доехало до `doc_no_norm` строк реестра боевого
 * комплекта, — поэтому обратимость печати ячейки проверяется здесь напрямую,
 * рядом с самой функцией.
 *
 * Фикстуры воспроизводят ровно то, что печатает рендер портала
 * (`packages/recognition/src/render-fragments.ts`): перевод строки внутри
 * ячейки как `<br>`, вертикальную черту как `\|`.
 */

import { describe, expect, it } from 'vitest';
import { isSeparator, scanBlocks, tableCells, toTable } from './md-table.js';

describe('tableCells', () => {
  it('строкой таблицы считает только строку, обрамлённую трубами', () => {
    expect(tableCells(undefined)).toBeNull();
    expect(tableCells('обычный абзац')).toBeNull();
    expect(tableCells('| 1 | Протокол | №1753.КП/02.26 |')).toEqual([
      '1',
      'Протокол',
      '№1753.КП/02.26',
    ]);
  });

  it('перенос строки внутри ячейки не остаётся в значении', () => {
    // `<br>` ставит сам портал: GFM иначе не выражает многострочную ячейку.
    // Снять его обязан разбор — в рендере правка сдвинула бы все `char_span`.
    expect(tableCells('| 1 | Исполнительная схема<br>стяжки | № К14/ДК2-СЦ2 |')).toEqual([
      '1',
      'Исполнительная схема стяжки',
      '№ К14/ДК2-СЦ2',
    ]);
  });

  it('завёрнутая графа номера собирается обратно в одну строку', () => {
    // Боевой комплект 01-ДК2-СЦ: длинный номер декларации заворачивался вместе
    // со сроком действия, и `<br>` уезжал в `doc_no_norm` — документ по такому
    // номеру не находился ни точным сравнением, ни фолдингом.
    const cells = tableCells(
      '|  | POCC RU Д-RU.<br>PA01.B.36916/24 с 11.02.2024 по<br>10.09.2027 |',
    );

    expect(cells?.[1]).toBe('POCC RU Д-RU. PA01.B.36916/24 с 11.02.2024 по 10.09.2027');
  });

  it('пробелы вокруг переноса не удваиваются', () => {
    expect(tableCells('| A<br> B | C <br>D |')).toEqual(['A B', 'C D']);
  });

  it('все написания тега снимаются одинаково', () => {
    expect(tableCells('| a<br>b<BR>c<br/>d<br />e |')).toEqual(['a b c d e']);
  });

  it('экранированная труба остаётся внутри ячейки, а не делит её', () => {
    // Без этого ячейка «АР3 | КЖ1» превращалась в две графы, строка не
    // сходилась по их числу и выбрасывалась разбором реестра с предупреждением.
    expect(tableCells(String.raw`| Марка | АР3 \| КЖ1 | ООО «Ромашка» |`)).toEqual([
      'Марка',
      'АР3 | КЖ1',
      'ООО «Ромашка»',
    ]);
  });

  it('полужирное начертание по-прежнему снимается', () => {
    expect(tableCells('| **№ п/п** | **Наименование документа** |')).toEqual([
      '№ п/п',
      'Наименование документа',
    ]);
  });

  it('пустая шапка продолжения остаётся пустыми графами', () => {
    // Их пустота — единственный признак, отличающий безголовое продолжение
    // таблицы от начала новой.
    expect(tableCells('|  |  |  |  |')).toEqual(['', '', '', '']);
  });
});

describe('isSeparator', () => {
  it('узнаёт разделитель шапки в обоих написаниях', () => {
    expect(isSeparator(tableCells('| --- | :---: |') ?? [])).toBe(true);
    expect(isSeparator(tableCells('| 1 | 2 |') ?? [])).toBe(false);
    expect(isSeparator([])).toBe(false);
  });
});

describe('scanBlocks', () => {
  it('разделяет таблицы и полужирные строки в порядке текста', () => {
    const blocks = scanBlocks(
      [
        '**Исполнительные геодезические схемы**',
        '',
        '| № | Наименование |',
        '| --- | --- |',
        '| 1 | Схема<br>стяжки |',
      ].join('\n'),
    );

    expect(blocks).toEqual([
      { kind: 'bold', text: 'Исполнительные геодезические схемы' },
      {
        kind: 'table',
        table: { header: ['№', 'Наименование'], rows: [['1', 'Схема стяжки']] },
      },
    ]);
  });
});

describe('toTable', () => {
  it('разделитель первой строкой оставляет таблицу без шапки', () => {
    expect(
      toTable([
        ['---', '---'],
        ['1', 'Протокол'],
      ]),
    ).toEqual({
      header: null,
      rows: [['1', 'Протокол']],
    });
  });
});
