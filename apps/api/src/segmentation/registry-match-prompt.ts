/**
 * Промт сверки строк перечня с документами комплекта (S57).
 *
 * ## Что модель решает и чего от неё НЕ ждут
 *
 * Задач две, и они разные. Первая — какой документ отвечает строке перечня.
 * Вторая — верно ли строка этот документ ОПИСЫВАЕТ: та ли организация, тот ли
 * акт назван, та ли форма номера, те ли даты. Инженеру вторая важна не меньше
 * первой: номер может совпасть точно, а графа организации — называть чужое
 * лицо, и такая строка сегодня проходит проверку молча.
 *
 * Модель не решает, дефект это или опечатка, и не выносит вердикт: она
 * называет документ, называет расхождение и цитирует обе стороны. Что с этим
 * делать, решают правила и человек.
 *
 * ## Почему в промте признаки, а не список частных равенств
 *
 * Соблазн после лестницы регулярных выражений — переписать её исключения
 * словами: «б/н означает приложение», «„-1 этаж“ и „ЭТАЖ“ — одно и то же»,
 * «номер партии — имя документа». Это тот же список исключений, перенесённый из
 * TypeScript в текст, и он ошибается ровно там же. Отсутствие номера означает
 * отсутствие номера, а не приложение; знак перед числом этажа — часть номера, а
 * не оформление; партия называет партию, и совпадение партии у двух паспортов
 * разных изготовителей документ не отождествляет.
 *
 * Поэтому промт разрешает НОРМАЛИЗАЦИЮ написания и запрещает терять содержание:
 * различие раскладки, регистра, пробелов и разделителей несущественно, различие
 * знака, цифры или слова единицы — существенно и называется расхождением.
 *
 * ## Почему цитаты обязательны с обеих сторон
 *
 * Замечание, называющее одну сторону расхождения, проверяющему приходится
 * достраивать самому; не называющее ни одной — это мнение. Цитаты проверяются
 * точным поиском по переданному тексту (`acceptDecisions`), и выдуманная цитата
 * обесценивает решение целиком.
 */
import type { PromptText } from './prompts.js';

/** Строка перечня в том виде, в каком её показывают модели. */
export interface PromptRow {
  readonly rowId: string;
  /** Позиция, как напечатана в перечне: «поз. 5.16» либо «строка 3». */
  readonly position: string;
  readonly docNameRaw: string;
  readonly docNoRaw: string | null;
  readonly orgRaw: string | null;
  readonly issuedAt: string | null;
  readonly validFrom: string | null;
  readonly validTo: string | null;
  /** Что решил предфильтр: найденный документ либо кандидаты с причиной. */
  readonly prefilter: string;
}

/** Документ выборки в том виде, в каком его показывают модели. */
export interface PromptDocument {
  readonly documentId: string;
  /** Русское имя вида из каталога: «Исполнительная схема», «Паспорт качества». */
  readonly kind: string;
  readonly title: string | null;
  readonly pageCount: number | null;
  /**
   * Реквизиты ПОДПИСЯМИ каталога: «Организация, составившая схему: ООО «МАСТЕР»».
   *
   * Именно подписями, а не кодами: роль организации в документе модель читает
   * из подписи поля, и списка «какие коды считать организацией» здесь нет
   * вовсе. Такой список дважды подводил портал — `executor` и `designer_org` не
   * попали в него и остались непрочитанными, хотя ИИ-ступень их заполняла.
   */
  readonly fields: readonly string[];
}

export interface PromptPartition {
  /** Заголовок выборки: раздел описи с его актом либо перечень приложений акта. */
  readonly scope: string;
  readonly rows: readonly PromptRow[];
  readonly documents: readonly PromptDocument[];
  /** Пометка об усечении, если выборка не поместилась целиком. */
  readonly truncated?: string | null;
}

