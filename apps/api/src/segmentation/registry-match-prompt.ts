function cell(label: string, value: string | null): string | null {
  if (value === null || value.trim() === '') return null;
  return `${label}: ${value.trim()}`;
}

function renderRow(row: PromptRow): string {
  const parts = [
    `- rowId: ${row.rowId}`,
    `  ${row.position}`,
    cell('  наименование', row.docNameRaw),
    cell('  номер в перечне', row.docNoRaw),
    cell('  организация в перечне', row.orgRaw),
    cell('  дата в перечне', row.issuedAt),
    cell('  действует с', row.validFrom),
    cell('  действует по', row.validTo),
    `  предварительно: ${row.prefilter}`,
  ];
  return parts.filter((part): part is string => part !== null).join('\n');
}

function renderDocument(document: PromptDocument): string {
  const head = [
    `- documentId: ${document.documentId}`,
    `  вид: ${document.kind}`,
    cell('  заголовок', document.title),
    document.pageCount === null ? null : `  листов: ${String(document.pageCount)}`,
  ].filter((part): part is string => part !== null);

  const fields =
    document.fields.length === 0
      ? ['  реквизиты: не прочитаны']
      : document.fields.map((field) => `  ${field}`);

  return [...head, ...fields].join('\n');
}

/**
 * Подставить выборку в шаблон.
 *
 * Замена — функцией, а не строкой: в тексте перечня встречаются `$&` и `$1`, и
 * подстановочные последовательности `String.prototype.replace` испортили бы
 * значение молча (тот же довод, что в `renderReviewUserPrompt`).
 */
export function renderRegistryMatchPrompt(
  partition: PromptPartition,
  template: string = REGISTRY_MATCH_PROMPT.user,
): string {
  const rows = partition.rows.map(renderRow).join('\n');
  const documents =
    partition.documents.length === 0
      ? '(документов в выборке нет)'
      : partition.documents.map(renderDocument).join('\n');
  const scope =
    partition.truncated == null || partition.truncated === ''
      ? partition.scope
      : `${partition.scope}\n${partition.truncated}`;

  return template
    .replace(/\{\{SCOPE\}\}/gu, () => scope)
    .replace(/\{\{ROWS\}\}/gu, () => (rows === '' ? '(строк нет)' : rows))
    .replace(/\{\{DOCUMENTS\}\}/gu, () => documents);
}
