/**
 * Признаки ВТОРОГО листа бланка: пункты 4–7 и блок подписей.
 *
 * ## Что теряется без этого
 *
 * Бланк РД-11-02 не помещается на один лист. На втором лежат п. 4 (перечень
 * подтверждающих документов), п. 5 (даты работ), п. 7 (разрешение последующих
 * работ) и подписи четырёх представителей — то есть вход восьми правил
 * чек-листа сразу. Заголовка на этом листе нет по построению, счётчика «лист 2
 * из 2» типографский бланк не печатает, и страница уходила в `unassigned`,
 * унося с собой п. 4, п. 5 и всех подписантов.
 *
 * ## Почему признаки ДРУГИЕ, а не те же
 *
 * Маркеры первого листа («К освидетельствованию предъявлены…») на втором не
 * повторяются: печатная форма не дублирует шапку. Поэтому список свой и
 * заведомо не пересекается с `FORM_MARKERS` — иначе первый лист второго акта,
 * идущий следом за первым, был бы принят за его продолжение.
 */
const CONTINUATION_MARKERS: readonly FormMarker[] = [
  {
    id: 'п.6 соответствие нормативам',
    weight: 'strong',
    pattern: /Работы\s+выполнены\s+в\s+соответствии\s+с/iu,
  },
  {
    id: 'разрешение последующих работ',
    weight: 'strong',
    pattern: /Разрешается\s+производство\s+последующих\s+работ/iu,
  },
  {
    id: 'дополнительные сведения',
    weight: 'weak',
    pattern: /Дополнительные\s+сведения/iu,
  },
  {
    id: 'экземпляры акта',
    weight: 'weak',
    pattern: /Акт\s+составлен\s+в\s+\d+\s+экземплярах/iu,
  },
  {
    id: 'подписи представителей',
    weight: 'strong',
    pattern:
      /Представитель\s+лица,\s*выполнившего\s+работы[\s\S]{0,3000}?Представитель\s+лица,\s*осуществляющего\s+строительств/iu,
  },
];

export interface ActContinuationEvidence {
  readonly markers: readonly string[];
  readonly hasStrong: boolean;
}

/** Признаки продолжения бланка в тексте страницы. */
export function detectActContinuation(text: string): ActContinuationEvidence {
  const body = normalizeLines(text).join('\n');
  const markers: string[] = [];
  let hasStrong = false;

  for (const marker of CONTINUATION_MARKERS) {
    if (!marker.pattern.test(body)) continue;
    markers.push(marker.id);
    if (marker.weight === 'strong') hasStrong = true;
  }

  return { markers, hasStrong };
}

/**
 * Достаточно ли признаков, чтобы присоединить страницу к акту.
 *
 * Требуется ХОТЯ БЫ ОДИН сильный признак: слабые («Дополнительные сведения»,
 * «Акт составлен в N экземплярах») встречаются в подвале любого акта, включая
 * акты приёмки, и присоединение по ним разорвало бы сразу два документа —
 * этот потерял бы начало, а предыдущий получил бы чужой хвост (§16).
 */
export function isActContinuation(evidence: ActContinuationEvidence): boolean {
  return evidence.hasStrong;
}
