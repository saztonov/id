/**
 * Опознание акта освидетельствования по ФОРМЕ БЛАНКА, а не по титулу (§8.2).
 *
 * ## Зачем второй способ, если есть якорь заголовка
 *
 * Акт — единственный документ комплекта, потеря которого обнуляет весь анализ:
 * не опознали сертификат — потеряли строку, не опознали акт — потеряли связь
 * «документ качества относится к работам», все двенадцать правил дат и весь
 * чек-лист АОСР. Якорь заголовка при этом хрупок ровно там, где дороже всего:
 * титул печатается двумя строками, склеивается провайдером распознавания в
 * одну, разрывается переносом, теряется при плохом скане верха листа.
 *
 * Форма же бланка РД-11-02 воспроизводится целиком: семь нумерованных пунктов
 * с печатными подписями граф, строка осмотра, строка разрешения последующих
 * работ, блок из четырёх представителей. Эти признаки уже лежали в каталоге
 * (`matchHints.bodyHints` типа `aosr`) и работали только МНОЖИТЕЛЕМ уверенности
 * у типа, чей якорь уже сработал, — то есть ровно в том случае, когда они и не
 * нужны. Здесь они получают право присвоить тип сами.
 *
 * ## Чего здесь намеренно НЕТ
 *
 * **Нумерованных пунктов как признака.** Соблазн засчитать «строки, начинающиеся
 * с 1. … 7.» велик и обманчив: протокол лабораторных испытаний из корпуса
 * (`temp/MD/new`) содержит девять таких строк подряд — «1. Наименование
 * Заказчика», «2. Заказ/Заявка», «3. Адрес отбора проб» … Признак опознал бы
 * протокол как акт, а это тихая высокоуверенная ошибка границы, которую §16
 * ставит выше F1. Поэтому засчитываются только ФРАЗЫ бланка вместе с их
 * печатными подписями граф — они не воспроизводятся ни в одной другой форме.
 *
 * **Слов раздела работ.** Ни один маркер не называет ни материала, ни
 * конструкции (§0.5, п. 6): признак обязан работать на разделе, которого
 * система не видела.
 */
import { normalizeLines } from '@id/doc-types';

/**
 * Признак бланка: фраза печатной формы и её вес.
 *
 * `strong` — фраза, встречающаяся ТОЛЬКО в бланке освидетельствования;
 * `weak` — фраза, возможная и в родственных актах приёмки. Порог считает и те,
 * и другие, но одиночный `weak` типа не присваивает.
 */
interface FormMarker {
  readonly id: string;
  readonly weight: 'strong' | 'weak';
  readonly pattern: RegExp;
}

const FORM_MARKERS: readonly FormMarker[] = [
  {
    id: 'предъявлены работы',
    weight: 'strong',
    pattern: /К\s+освидетельствованию\s+предъявлен[ыо]\s+следующие\s+работы/iu,
  },
  {
    id: 'осмотр работ',
    weight: 'strong',
    pattern: /произвели\s+осмотр\s+работ,?\s*выполненных/iu,
  },
  {
    id: 'разрешение последующих работ',
    weight: 'strong',
    pattern: /Разрешается\s+производство\s+последующих\s+работ/iu,
  },
  {
    id: 'п.4 подтверждающие документы',
    weight: 'strong',
    pattern: /Предъявлены\s+документы,?\s*подтверждающие\s+соответствие\s+работ/iu,
  },
  {
    id: 'п.2 проектная документация',
    weight: 'weak',
    pattern: /Работы\s+выполнены\s+по\s+проектной\s+документации/iu,
  },
  {
    id: 'п.5 даты работ',
    weight: 'weak',
    pattern: /Дат[ыа]:?\s*начала\s+работ/iu,
  },
  {
    id: 'блок подписантов',
    weight: 'weak',
    // Две роли из бланка сразу: одинокая строка «Представитель лица,
    // осуществляющего строительство» встречается и в актах приёмки.
    pattern:
      /Представитель\s+лица,\s*осуществляющего\s+строительств[оа][\s\S]{0,4000}?Представитель\s+лица,\s*выполнившего\s+работы/iu,
  },
];

/**
 * Строка, состоящая ровно из слова «АКТ».
 *
 * Отдельно от `FORM_MARKERS`, потому что проверяется по СТРОКЕ, а не по телу:
 * слово «акт» встречается в тексте любого документа, и признаком является
 * только отдельная строка титула.
 */
const ACT_TITLE_LINE = /^АКТ$/iu;

/** Сколько маркеров достаточно, чтобы объявить страницу актом. */
export const PRIMARY_ACT_MIN_MARKERS = 2;

/**
 * Сколько маркеров достаточно, чтобы тип считался определённым УВЕРЕННО.
 *
 * Три и более — это уже не совпадение фразы, а воспроизведённая форма: столько
 * печатных подписей граф подряд не встречается ни в одном другом виде ИД.
 */
export const PRIMARY_ACT_CONFIDENT_MARKERS = 3;

export interface PrimaryActEvidence {
  /** Названия сработавших признаков — уходят в объяснение решения. */
  readonly markers: readonly string[];
  /** Сработал ли хотя бы один признак, встречающийся только в этом бланке. */
  readonly hasStrong: boolean;
  /** Строка титула «АКТ», если она есть, — на неё указывает доказательство. */
  readonly titleLineIndex: number;
}

/**
 * Признаки бланка освидетельствования в тексте страницы.
 *
 * Чистая функция: ни базы, ни каталога, ни состояния. Решение о метке
 * принимает вызывающий (`classify.ts`), сверяясь с порогами выше, — здесь
 * только наблюдение.
 */
export function detectPrimaryAct(text: string): PrimaryActEvidence {
  const lines = normalizeLines(text);
  const body = lines.join('\n');

  const markers: string[] = [];
  let hasStrong = false;

  const titleLineIndex = lines.findIndex((line) => ACT_TITLE_LINE.test(line));
  if (titleLineIndex >= 0) markers.push('строка титула «АКТ»');

  for (const marker of FORM_MARKERS) {
    if (!marker.pattern.test(body)) continue;
    markers.push(marker.id);
    if (marker.weight === 'strong') hasStrong = true;
  }

  return { markers, hasStrong, titleLineIndex };
}

/**
 * Достаточно ли признаков, чтобы объявить страницу первым листом акта.
 *
 * Одиночная строка «АКТ» плюс одна слабая фраза порогом не считаются: обе
 * встречаются в актах приёмки и освидетельствования ответственных конструкций,
 * и присвоить по ним `aosr` значило бы подменить вид документа. Требуется либо
 * признак, встречающийся только в этом бланке, либо три любых.
 */
export function isPrimaryAct(evidence: PrimaryActEvidence): boolean {
  if (evidence.markers.length < PRIMARY_ACT_MIN_MARKERS) return false;
  return evidence.hasStrong || evidence.markers.length >= PRIMARY_ACT_CONFIDENT_MARKERS;
}

