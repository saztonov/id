/**
 * Реестр открывается КАНОНИЧЕСКОЙ ШАПКОЙ, а шапка распознаётся только вместе со
 * строкой-разделителем. Значит потеря разделителя роняла разбор целиком: ноль
 * строк вместо двадцати девяти и ни одного предупреждения. Дальше
 * `doc.match_registry` докладывал «реестра в поставке нет: сверять нечего»,
 * `graph.build` не строил связей, а на S9 это стало бы «комплект без реестра».
 *
 * В md от RD WEB разделитель есть всегда, поэтому вероятность низкая — но отказ
 * полный и беззвучный, а таких в конвейере быть не должно.
 */
describe('реестр без строки-разделителя шапки не теряется молча', () => {
  const HEADER_ROW =
    '| № п/п | Наименование документа | № чертежа, акта, разрешения, журнала и др. | ' +
    'Организация, составившая документ |';
  const BODY = [
    '| 1 | Заключение Плита тестовая | №02(а)-2020 с 01.12.2021 по 30.11.2026 | ООО "Синтет-Пром" |',
    '| 2 | Сертификат качества Пруток | №16005 от 26.11.2025 | ООО "Тест-Материал" |',
  ];

  it('разбор восстанавливается и предупреждает с указанием страницы', () => {
    const result = parseAnnexRegistry({
      pages: pages([HEADER_ROW, ...BODY].join('\n')),
    });

    // Положительный путь: строки на месте, а не «ноль и тишина».
    expect(result.rows.map((row) => row.rowNo)).toEqual([1, 2]);
    expect(result.warnings).toContainEqual(expect.stringContaining('строки-разделителя'));
    expect(result.warnings.some((warning) => warning.includes('p1'))).toBe(true);
  });

  it('с разделителем предупреждения нет: восстановление не подменяет норму', () => {
    const result = parseAnnexRegistry({
      pages: pages([HEADER_ROW, '|---|---|---|---|', ...BODY].join('\n')),
    });

    expect(result.rows.map((row) => row.rowNo)).toEqual([1, 2]);
    expect(result.warnings).toEqual([]);
  });

  it('таблица, похожая на реестр, но с неузнанной шапкой, даёт предупреждение', () => {
    // Шапка искажена OCR до неузнаваемости — восстановить нечего. Но молчать
    // тоже нельзя: строки с номерами позиций и наименованиями были и пропали.
    const result = parseAnnexRegistry({
      pages: pages(
        ['| N п.п | Наимен0вание док-та | № док-та | Организация |', ...BODY].join('\n'),
      ),
    });

    expect(result.rows).toEqual([]);
    expect(result.warnings).toContainEqual(expect.stringContaining('похожа на реестр приложений'));
    expect(result.warnings.some((warning) => warning.includes('p1'))).toBe(true);
  });

  it('таблица показателей паспорта предупреждения не порождает', () => {
    // Обратная сторона: громкость не должна превратиться в шум. Таблица
    // «Норма по НД / Фактически» идёт на тех же страницах поставки, и
    // предупреждение о ней инженер перестанет читать вместе со всеми (§9.1).
    const result = parseAnnexRegistry({
      pages: pages(
        [
          '| Показатель | Норма по НД | Фактически |',
          '|---|---|---|',
          '| Толщина | 4 ± 0,2 | 3,9 |',
          '| Прочность | не менее 100 | 118 |',
        ].join('\n'),
      ),
    });

    expect(result).toEqual({ rows: [], warnings: [] });
  });

  it('страница без строк закрывает реестр вслух, а не молча', () => {
    const result = parseAnnexRegistry({
      pages: pages(
        [HEADER_ROW, '|---|---|---|---|', ...BODY].join('\n'),
        'ДОКУМЕНТ ПОДПИСАН ЭЛЕКТРОННОЙ ПОДПИСЬЮ',
        [
          '| | | | |',
          '|---|---|---|---|',
          '| 3 | Паспорт качества Плита | №79825 от 12.01.2026 | ООО "Синтет-Изоляция" |',
        ].join('\n'),
      ),
    });

    // Остаток реестра после закрытия действительно теряется — и именно поэтому
    // о закрытии обязано быть сказано: «реестр кончился» и «продолжение
    // потеряно» неразличимы по одному только числу строк.
    expect(result.rows.map((row) => row.rowNo)).toEqual([1, 2]);
    expect(result.warnings).toContainEqual(expect.stringContaining('реестр'));
    expect(result.warnings.some((warning) => warning.includes('p2'))).toBe(true);
  });
});

