const CORPUS_DIR = new URL('../../../../temp/MD', import.meta.url).pathname.replace(
  /^\/([A-Za-z]:)/u,
  '$1',
);

/** Комплект АОСР №336: реестр на 29 позиций, разложенный по двум страницам. */
function corpusRegistryMarkdown(): string | null {
  if (!existsSync(CORPUS_DIR)) return null;

  for (const dir of readdirSync(CORPUS_DIR)) {
    if (!dir.includes('336')) continue;
    const file = readdirSync(join(CORPUS_DIR, dir)).find((name) => name.endsWith('_results.md'));
    if (file !== undefined) return readFileSync(join(CORPUS_DIR, dir, file), 'utf8');
  }

  return null;
}

const corpusMarkdown = corpusRegistryMarkdown();

describe.skipIf(corpusMarkdown === null)('реестр АОСР №336 на настоящем корпусе', () => {
  it('даёт ровно 29 строк с номерами 1..29', () => {
    // Корпус закрыт и в репозиторий не входит, поэтому набор пропускается там,
    // где его нет. Но там, где он есть, гейт S8 обязан проверяться на
    // оригинале: синтетика воспроизводит структуру по моему пониманию, а
    // оригинал — источник, из которого это понимание взято.
    const parts = (corpusMarkdown ?? '').split(/^## Page (\d+)\s*$/mu);
    const corpusPages: RegistryPageInput[] = [];
    for (let index = 1; index < parts.length; index += 2) {
      corpusPages.push({
        sourcePageId: `page-${parts[index]}`,
        pageTextVersionId: `ptv-${parts[index]}`,
        text: parts[index + 1] ?? '',
      });
    }

    const result = parseAnnexRegistry({ pages: corpusPages });

    expect(result.rows.map((row) => row.rowNo)).toEqual(
      Array.from({ length: 29 }, (_, index) => index + 1),
    );
  });
});
