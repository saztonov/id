/**
 * Промт ИИ-проверки заполнения (§9.1, S21).
 *
 * Отдельный файл, а не строка внутри обработчика: текст промта — предмет
 * governance (`prompt_templates`, цикл `draft → test → published`), и в коде он
 * живёт как ДЕФОЛТ для сида, а не как источник правды прогона. Прогон читает
 * опубликованную версию из БД; расхождение между ними — штатное состояние,
 * означающее, что администратор промт правил.
 *
 * ## Чего промт запрещает, и почему именно это
 *
 * **Не проверять то, что проверяет движок.** Даты, контрольные суммы ИНН/ОГРН,
 * соответствие номера шаблону — детерминированные правила, и второе мнение по
 * ним породило бы два замечания об одном факте с правом противоречить друг
 * другу. Модель зовут ровно туда, где формы нет: смысловые расхождения.
 *
 * **Не додумывать нормативные требования.** «ГОСТ требует указывать класс
 * прочности» — юридическое утверждение, которое портал делать не вправе (§8.1),
 * и от модели оно приходит особенно правдоподобным. Сравнивать разрешено только
 * то, что напечатано В САМИХ документах.
 *
 * **Молчать, когда сказать нечего.** Без явного разрешения на пустой ответ
 * модель находит замечание всегда — и портал начинает выдавать ложные ошибки,
 * которые §0.5 называет разрушающими доверие быстрее пропущенных.
 */
import type { PromptText } from '../segmentation/prompts.js';

/** Сколько символов текста документа уходит в промт проверки. */
const DOCUMENT_TEXT_BUDGET = 12_000;

export const LLM_REVIEW_PROMPT: PromptText = {
  system: [
    'Ты проверяешь ЗАПОЛНЕНИЕ одного документа исполнительной документации.',
    'Тебе передан его распознанный текст и реквизиты, извлечённые порталом.',
    '',
    'Ищи ТОЛЬКО смысловые расхождения. Не проверяй то, что проверяется формально:',
    'арифметику дат, контрольные суммы ИНН и ОГРН, соответствие номера шаблону,',
    'наличие приложений по списку — это делают детерминированные правила, и второе',
    'мнение по ним создаёт два замечания об одном факте.',
    '',
    'Допустимые коды замечаний и их смысл:',
    '  LLM.FILL.010 — обязательная графа документа пуста или заполнена прочерком,',
    '                 хотя по бланку она обязательна;',
    '  LLM.FILL.020 — извлечённое порталом значение реквизита расходится с тем, что',
    '                 напечатано в документе (перепутаны графы, взята соседняя строка);',
    '  LLM.FILL.030 — сведения внутри документа противоречат друг другу',
    '                 (в шапке одна организация, в подвале другая; номер в заголовке',
    '                 и в штампе разный);',
    '  LLM.FILL.040 — содержание документа не похоже на заявленный вид.',
    '',
    'Правила, обязательные к соблюдению.',
    '',
    '1) Пустой ответ — законный и частый. Если расхождений нет, верни',
    '   {"findings": []}. Не выдумывай замечание ради непустого ответа.',
    '',
    '2) Поле quote ОБЯЗАТЕЛЬНО и содержит ДОСЛОВНЫЙ фрагмент текста документа, на',
    '   котором основано замечание. Не пересказывай и не исправляй: фрагмент',
    '   проверяется точным поиском, и изменённый отбрасывает замечание целиком.',
    '',
    '3) Не ссылайся на требования ГОСТ, СП, СТО или иных норм: их текста тебе не',
    '   передавали. Сравнивать можно только то, что напечатано в самом документе',
    '   и в переданных реквизитах.',
    '',
    '4) state = "open", если ты уверен в расхождении; state = "undetermined", если',
    '   текст не даёт сделать вывод (плохое распознавание, обрезанная графа). Это',
    '   разные ответы, и путать их нельзя: второй не обвиняет подрядчика.',
    '',
    '5) hint — одна короткая фраза о том, что сделать подрядчику. Замечание без',
    '   способа устранения бесполезно тому, кто его получит.',
    '',
    'Ответ — один объект JSON без пояснений и без обрамления:',
    '{"findings": [{"code": "...", "state": "open", "severity": "warning",',
    '               "message": "...", "hint": "...", "quote": "..."}]}',
  ].join('\n'),
  user: [
    'Вид документа по данным портала: {{DOC_TYPE}}.',
    '',
    'Реквизиты, извлечённые порталом:',
    '{{FIELDS}}',
    '',
    '=== ТЕКСТ ДОКУМЕНТА ===',
    '{{DOCUMENT}}',
  ].join('\n'),
};

function clip(text: string, budget: number): string {
  const trimmed = text.trim();
  if (trimmed.length <= budget) return trimmed;
  return `${trimmed.slice(0, budget)}\n…[текст обрезан]`;
}

/**
 * Подставляет документ и его реквизиты в шаблон промта проверки.
 *
 * Реквизиты передаются моделью НЕ ради удобства: без них код `LLM.FILL.020`
 * («извлечённое значение расходится с документом») не имеет смысла — сравнивать
 * будет не с чем, и модель начнёт выдавать под этим кодом что попало.
 */
export function renderReviewUserPrompt(
  input: {
    readonly docTypeCode: string | null;
    readonly fields: readonly {
      readonly fieldCode: string;
      readonly valueText: string | null;
      readonly valueDate: string | null;
    }[];
    readonly pages: readonly { readonly text: string }[];
  },
  template: string = LLM_REVIEW_PROMPT.user,
): string {
  // Замена ФУНКЦИЕЙ, а не строкой: `$&`, `$'` и `$1` в тексте от OCR иначе
  // читаются как ссылки на совпадение и тихо искажают промт.
  const put = (text: string, token: string, value: string): string =>
    text.replace(token, () => value);

  const fields =
    input.fields.length === 0
      ? '(реквизитов не извлечено)'
      : input.fields
          .map((field) => `- ${field.fieldCode}: ${field.valueText ?? field.valueDate ?? '—'}`)
          .join('\n');

  const document = clip(
    input.pages
      .map((page) => page.text.trim())
      .filter((text) => text.length > 0)
      .join('\n\n'),
    DOCUMENT_TEXT_BUDGET,
  );

  let out = template;
  out = put(out, '{{DOC_TYPE}}', input.docTypeCode ?? 'не определён');
  out = put(out, '{{FIELDS}}', fields);
  out = put(out, '{{DOCUMENT}}', document || '(текста нет)');
  return out;
}
