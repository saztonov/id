/**
 * Отметка о производности в метаданных PDF для реализации на `qpdf` (§13).
 *
 * ## Задача
 *
 * §13 требует: «любая нарезка помечается `is_derived_copy=true`, и в метаданные
 * PDF добавляется отметка о производности». Флаг в БД пишет задача 22 и держит
 * ограничение `logical_documents_derived_marked_chk`. Метаданные пишет тот, кто
 * производит файл, — и вот здесь боевая реализация до сих пор молчала.
 *
 * ## Что было неверно
 *
 * `QpdfToolkit` возвращал `derivedNoteApplied: false` с комментарием «qpdf не
 * пишет /Info». Первая половина верна: у `qpdf` нет ни одной опции, задающей
 * поля словаря информации о документе, — есть только `--remove-info`. Но вывод
 * из неё был сделан неверный. В production работает именно `qpdf` (ADR-0003),
 * значит §13 не выполнялся ровно там, где он и нужен: в тестах отметка стояла
 * (её пишет `pdf-lib`), в бою — нет.
 *
 * ## Как это решается без правки самого qpdf
 *
 * Документация qpdf говорит прямо: «Document-level information … is taken from
 * the primary input file … If you don't want to preserve the primary file's
 * metadata, use `--empty` as the primary input file». То есть `--empty` — это
 * ОТКАЗ от метаданных, а не единственный способ собрать документ из чужих
 * страниц. Подставив вместо `--empty` крошечный документ, несущий нужный
 * `/Info`, мы получаем выход с нашей отметкой, а страницы по-прежнему берутся
 * только из спецификаций `--pages`.
 *
 * Шаблон здесь — документ БЕЗ страниц, ровно как фиктивный вход `--empty`.
 * Выбор не косметический: даже если предположение о поведении `--pages`
 * окажется неверным, лишних страниц взяться неоткуда, а расхождение числа
 * страниц с планом всё равно остановило бы задачу (`assertPageCountMatches`).
 * Худший исход изменения — отметка не появилась, то есть ровно то состояние,
 * которое было до него.
 *
 * ## Почему PDF собирается байтами, а не библиотекой
 *
 * `pdf-lib` объявлен зависимостью воркера и в `apps/api` не резолвится (см.
 * `pdf-lib.ts`), а тащить его в боевую ветку `qpdf` значило бы вернуть в
 * процесс ровно ту библиотеку, ради ухода от которой выбран внешний бинарник.
 * Документ из трёх объектов пишется здесь целиком и детерминированно, а его
 * пригодность проверяется настоящей библиотекой в тесте — то есть чужим
 * разбором, а не собственным утверждением.
 *
 * ## Отметка не объявляется поставленной без проверки
 *
 * `derivedNoteApplied` возвращается по результату ЧТЕНИЯ готового файла, а не
 * по факту «мы передали параметр». Причина прямая: настройка, которая
 * принимается и молча не действует, — это отдельный класс дефекта, найденный на
 * S9 у порогов профиля. Проверка одна на обе реализации (`verifyDerivedNote`),
 * поэтому «qpdf соврал» и «pdf-lib соврал» ловятся одинаково, а не каждым по
 * своим правилам.
 */
import { createReadStream } from 'node:fs';

/** Метка порядка байт: без неё UTF-16 в PDF читается как PDFDocEncoding. */
const UTF16_BOM = '\uFEFF';

interface PdfObject {
  readonly number: number;
  readonly body: string;
}

/**
 * Строка PDF в UTF-16BE с BOM.
 *
 * PDFDocEncoding кириллицу не представляет вовсе, поэтому единственная форма,
 * в которой отметка доедет до читателя неискажённой, — шестнадцатеричная строка
 * с меткой порядка байт. Экранирование при этом не нужно по построению: в hex
 * нет символов, значимых для синтаксиса PDF.
 */
export function pdfTextString(value: string): string {
  const utf16 = Buffer.from(UTF16_BOM + value, 'utf16le').swap16();
  return `<${utf16.toString('hex').toUpperCase()}>`;
}

/**
 * Документ без страниц, несущий только словарь информации о документе.
 *
 * Возвращает байты, а не путь: решение «куда положить временный файл»
 * принадлежит вызывающему (у него уже есть рабочий каталог задачи), а функция
 * обязана быть чистой — тот же текст даёт те же байты, и повторная нарезка не
 * порождает второй объект хранилища из-за плавающей даты.
 */
export function buildDerivedNotePdf(note: string): Buffer {
  const text = pdfTextString(note);
  const objects: readonly PdfObject[] = [
    { number: 1, body: '<< /Type /Catalog /Pages 2 0 R >>' },
    { number: 2, body: '<< /Type /Pages /Kids [] /Count 0 >>' },
    {
      number: 3,
      // Четыре поля, а не одно: разные читатели показывают разные. `/Keywords`
      // добавлено потому, что именно оно чаще всего попадает в поиск по
      // хранилищу документов, а вопрос «это оригинал или нарезка портала?»
      // задают именно там.
      body: `<< /Producer ${text} /Creator ${text} /Subject ${text} /Keywords ${text} >>`,
    },
  ];

  // Вторая строка заголовка с байтами выше 0x7F — требование формата к файлам,
  // содержащим двоичные данные: без неё передача по текстовому каналу
  // «починила» бы переводы строк и сломала смещения xref.
  const header = '%PDF-1.7\n%\xE2\xE3\xCF\xD3\n';
  const parts: string[] = [header];
  const offsets: number[] = [];
  let cursor = Buffer.byteLength(header, 'latin1');

  for (const object of objects) {
    const chunk = `${object.number} 0 obj\n${object.body}\nendobj\n`;
    offsets.push(cursor);
    parts.push(chunk);
    cursor += Buffer.byteLength(chunk, 'latin1');
  }

  // Таблица перекрёстных ссылок: записи ровно по 20 байт, иначе смещения,
  // вычисляемые читателем арифметикой, укажут в середину соседней строки.
  const size = objects.length + 1;
  let xref = `xref\n0 ${size}\n0000000000 65535 f \n`;
  for (const offset of offsets) {
    xref += `${String(offset).padStart(10, '0')} 00000 n \n`;
  }

  const trailer =
    `trailer\n<< /Size ${size} /Root 1 0 R /Info 3 0 R >>\n` + `startxref\n${cursor}\n%%EOF\n`;
  parts.push(xref, trailer);

  return Buffer.from(parts.join(''), 'latin1');
}

/**
 * Есть ли отметка о производности в готовом файле.
 *
 * Ищутся ОБЕ формы, в которых строка может лежать в словаре информации:
 * шестнадцатеричная UTF-16BE (её пишет и наш шаблон, и `pdf-lib` для текста с
 * кириллицей) и обычная литеральная — на случай чисто латинской отметки.
 * Регистр hex не фиксирован ни форматом, ни библиотеками, поэтому сравнение
 * идёт по нижнему регистру.
 *
 * Чтение потоковое с перекрытием между кусками: файл нарезки — это десятки
 * мегабайт сканов, и поднимать его в heap ради поиска подстроки означало бы
 * вернуть ту самую проблему, из-за которой выбран `qpdf` (ADR-0003). Перекрытие
 * обязательно: искомая последовательность может лечь на границу кусков.
 *
 * Отсутствие отметки — не ошибка этой функции, а ответ. Решение, что с ним
 * делать, принимает вызывающий: у `logical_documents.derived_note_applied`
 * ровно этот смысл, а источником правды остаётся `is_derived_copy` в БД.
 */
export async function verifyDerivedNote(path: string, note: string): Promise<boolean> {
  // Hex сравнивается в нижнем регистре, литеральная форма — как есть.
  const hexNeedle = pdfTextString(note).slice(1, -1).toLowerCase();
  // Литеральная форма ищется только у чисто латинской отметки: для кириллицы
  // такой записи в PDF не бывает, а «поиск байтов latin1 от русского текста»
  // проверял бы последовательность, которой в файле не может быть в принципе.
  const plainNeedle = /^[\x20-\x7e]+$/.test(note) ? note : null;
  const overlap = Math.max(hexNeedle.length, plainNeedle?.length ?? 0) - 1;

  let tail = '';
  for await (const chunk of createReadStream(path, { highWaterMark: 1 << 20 })) {
    const window = tail + (chunk as Buffer).toString('latin1');
    if (window.toLowerCase().includes(hexNeedle)) return true;
    if (plainNeedle !== null && window.includes(plainNeedle)) return true;
    tail = window.slice(Math.max(0, window.length - overlap));
  }
  return false;
}
