/**
 * Схемы двух кнопок S21.
 *
 * Ответ называет СТАДИЮ, с которой прогон продолжился, а не просто «принято».
 * Без этого экран не может сказать пользователю, что происходит: он нажал одну
 * кнопку, а портал мог начать с распознавания, с анализа или с прогона правил —
 * в зависимости от того, где ревизия остановилась в прошлый раз.
 */
import { z } from 'zod';

export const folderIdParamSchema = z.object({ folderId: z.uuid() });
export const runIdParamSchema = z.object({ runId: z.uuid() });

/**
 * Стадия, с которой продолжился сквозной прогон.
 *
 * Перечисление закрытое: экран печатает по нему фразу пользователю, и
 * незнакомое значение означало бы «идёт что-то», то есть отсутствие ответа.
 */
export const pipelineStageSchema = z.enum(['recognition', 'analysis', 'checks']);

export const startMarkupPipelineResponseSchema = z.object({
  /**
   * `false` — рабочий документ ещё собирается, и разметка пойдёт следом сама
   * (задача `layout.start`). Экран по этому полю выбирает формулировку: «идёт
   * сборка» против «идёт детекция», и обе честны.
   */
  bundleReady: z.boolean(),
  bundleId: z.string().nullable(),
  layoutRevisionId: z.string().nullable(),
  /**
   * `null` — задачи не ставились вовсе.
   *
   * Прежде здесь стояла пустая строка: локальная ветка отдаёт список задач, и
   * маршрут брал из него первый элемент с запасным `''`. Пока задачи ставились
   * всегда, запас был недостижим; с появлением ветки «модель детекции не
   * загружена» он стал достижим — и пустая строка выдавала бы себя за
   * идентификатор задачи, которой нет.
   */
  jobId: z.string().nullable(),
  jobCreated: z.boolean(),
  /**
   * Детекция не запускалась, потому что запускать нечем.
   *
   * Черновик разметки при этом создан, и страницы размечаются вручную — то есть
   * нажатие не пропало впустую. Признак существует ради честной формулировки на
   * экране: «идёт детекция» над очередью, в которую ничего не положили, — это
   * ложь, а молчание оставило бы пользователя ждать результата, которого не будет.
   */
  detectionSkipped: z.boolean(),
  /** Почему детекция пропущена. `null`, когда она не пропускалась. */
  detectionSkipReason: z.string().max(500).nullable(),
});

/**
 * Что делать с уже распознанным комплектом (S40).
 *
 * Различие существенно и стоит денег: `errors` перечитывает только проблемные
 * листы и переносит остальные блоки из прошлого прогона без единого вызова
 * модели, `full` перечитывает всё заново, снеся прежний результат.
 *
 * `auto` — прежнее поведение и умолчание. Оно и должно оставаться умолчанием:
 * первое нажатие на неразобранном комплекте выбирать не из чего, и спрашивать
 * там нечего.
 */
export const recheckModeSchema = z.enum(['auto', 'errors', 'full']);

/**
 * Тело необязательно целиком, а не только его поле.
 *
 * Нажатие без тела — это прежний вызов, и он обязан продолжать работать: так
 * зовут маршрут гранулярный путь инженера, сквозные сценарии и всё, что было
 * написано до S40. Схема без `.nullish()` отвечала бы им 422 на пустое тело,
 * то есть ломала бы кнопку ради поля, которого они не знают.
 */
export const checkRequestSchema = z.object({ mode: recheckModeSchema.optional() }).nullish();

export const checkResponseSchema = z.object({
  stage: pipelineStageSchema,
  recognitionRunId: z.string().nullable(),
  jobId: z.string(),
  jobCreated: z.boolean(),
  /**
   * Сколько листов уйдёт на повторное распознавание (S40).
   *
   * Экран называет объём в подписи пункта: «перечитать 6 листов из 20». Ноль при
   * `mode: 'errors'` означает, что перечитывать нечего, и прогон продолжился
   * правилами — без числа это выглядело бы как молчаливое бездействие кнопки.
   */
  retriedPages: z.number().int().nonnegative().optional(),
  /**
   * Прогон, который новый восстанавливает (S28); `null` — распознавание с нуля.
   *
   * Экран обязан различать эти два случая: у восстановления другая цена и
   * другая длительность — часть блоков берётся из упавшего прогона, и модель
   * для них не вызывается вовсе.
   */
  repairOfRunId: z.string().nullable().optional(),
  /**
   * Нажатие пришлось на идущий прогон и заказало ему довести до проверки (S50).
   *
   * Экран обязан различать это от старта нового прогона: работа не началась
   * заново, ждать надо ровно столько, сколько оставалось, и повторное нажатие
   * ничего не ускорит.
   */
  continuedRun: z.boolean().optional(),
});

/**
 * Ответ кнопки «Стоп» (S50).
 *
 * Числом, а не пустым 204: остановка обязана быть проверяемой. «Снято 0 задач»
 * — законный ответ на повторное нажатие, и отличать его от «снято 218» экран
 * должен, иначе человек не знает, успел он остановить работу или она кончилась
 * сама.
 */
export const stopResponseSchema = z.object({
  /** Сколько задач снято с очереди этим нажатием. */
  cancelledJobs: z.number().int().nonnegative(),
  /** Прогон распознавания, закрытый остановкой; `null` — идущего не было. */
  recognitionRunId: z.string().nullable(),
  /**
   * Прогон закрыт именно этим нажатием.
   *
   * `false` при непустом `recognitionRunId` означает, что прогон завершился
   * сам между чтением и записью — гонка штатная, и врать о ней нельзя.
   */
  runFinished: z.boolean(),
});

export const recognitionProgressSchema = z.object({
  recognitionRunId: z.string(),
  status: z.string(),
  pagesTotal: z.number(),
  pagesDone: z.number(),
  pagesFailed: z.number(),
  pagesPending: z.number(),
  blocksTotal: z.number(),
  blocksRecognized: z.number(),
  blocksInvalid: z.number(),
  blocksRefused: z.number(),
  /** Сколько раундов дораспознавания потратила финализация (S28). */
  recoveryRound: z.number(),
  /** Прогон-родитель, если этот восстанавливает упавший (S28). */
  repairOfRunId: z.string().nullable(),
  /** Блоки, перенесённые из родителя без вызова модели (S28). */
  blocksReused: z.number(),
});
