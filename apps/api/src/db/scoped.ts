/**
 * Применение области видимости к запросам Drizzle.
 *
 * Единственное место, где `AuthScope` превращается в условие SQL. Репозитории
 * обязаны получать условие отсюда: продублированная логика фильтрации — это
 * второй источник правды для правила доступа, и разойтись они могут молча.
 *
 * ## Граница осталась одна (S37)
 *
 * До S37 областей было две: «своя организация» у подрядчика и «назначенные
 * объекты» у инженера и генподрядчика. Вторую заказчик снял: портал внутренний,
 * наружу из него ничего не уходит, а список объектов оказался не защитой, а
 * препятствием — инженеру, которому объекты не назначили, портал показывал
 * пустой справочник и не давал завести ни одного комплекта.
 *
 * Осталось ровно одно ограничение, и оно названо здесь целиком: **подрядчик
 * видит комплекты своей организации**. Это не остаток прежней конструкции, а
 * единственная граница, у которой есть предмет: на одной стройке работают
 * разные субподрядчики, и чужая исполнительная документация — не их дело.
 */
import { and, eq, sql, type SQL } from 'drizzle-orm';
import type { PgColumn } from 'drizzle-orm/pg-core';
import { type AuthScope } from '../auth/scope.js';

export interface ScopeTarget {
  readonly objectId: PgColumn;
  readonly contractorId: PgColumn;
}

/**
 * Условие, ограничивающее выборку областью видимости.
 *
 * Возвращает `SQL`, а не `SQL | undefined`: необязательное условие пришлось бы
 * проверять на каждом вызове, и пропущенная проверка означала бы выборку без
 * ограничения. Поэтому «без ограничения» выражается явным `TRUE`.
 *
 * `switch` сохранён при двух ветках намеренно: он исчерпывает тип-сумму, и
 * область нового вида не скомпилируется, пока о ней здесь не решат. Ветка
 * `default` по той же причине отвечает `FALSE`, а не `TRUE`.
 */
export function scopeWhere(scope: AuthScope, target: ScopeTarget): SQL {
  switch (scope.kind) {
    case 'contractor':
      return eq(target.contractorId, scope.contractorId);
    case 'general_contractor':
    case 'engineer':
    case 'manager':
    case 'admin':
      // Объект больше не ограничивает: генподрядчик ведёт реестр из комплектов
      // субподрядчиков, инженер проверяет чужие комплекты, и обоим нужна вся
      // стройка, а не её назначенная часть.
      return sql`true`;
    default:
      // Недостижимо: варианты выше исчерпывают тип. Возврат FALSE, а не TRUE, —
      // чтобы новый вариант области, добавленный без правки этой функции,
      // закрывал доступ, а не открывал его.
      return sql`false`;
  }
}

/** Совмещает область видимости с прикладными условиями. */
export function withScope(scope: AuthScope, target: ScopeTarget, ...conditions: SQL[]): SQL {
  const combined = and(scopeWhere(scope, target), ...conditions);
  // and() возвращает undefined только при пустом списке, а первый аргумент
  // здесь всегда задан; проверка нужна лишь для сужения типа.
  return combined ?? sql`false`;
}
