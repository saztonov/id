/**
 * Локальная детекция не сконфигурирована или сконфигурирована противоречиво:
 * пустая `detection.model_version`, отсутствующие в хранилище веса/манифест,
 * битый манифест, несовпавший sha256, недоступный растеризатор.
 *
 * Повтор задачи здесь не помогает по построению — чинит оператор, поэтому
 * текст обязан называть, что именно сделать. Ручная разметка при этом работает
 * всегда: отказывает только автоматическая детекция.
 */
export class DetectionConfigurationError extends Error {
  constructor(message: string) {
    super(message);
    this.name = 'DetectionConfigurationError';
  }
}
