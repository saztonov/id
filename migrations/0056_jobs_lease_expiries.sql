-- S41. Потеря аренды перестаёт считаться попыткой задачи.
--
-- ## Что происходило
--
-- `attempts` растёт в момент ЗАХВАТА (`claimJobs`), а не по исходу попытки, —
-- иначе счётчик не пережил бы смерть воркера, и убитая задача выглядела бы
-- никогда не запускавшейся. Обратная сторона обнаружилась на боевом инциденте:
-- воркер, убитый OOM, сжигал по попытке у каждой задачи, которую держал, ничего
-- при этом не выполнив. Хост перезагрузился, комплект на 220 страниц шёл
-- разметкой и распознаванием — три таких смерти подряд, и задачи детекции
-- ушли в `failed` с сообщением «аренда истекла», ни разу не отработав.
--
-- Дальше срабатывал второй механизм: мёртвая задача ДЕРЖИТ `dedupe_key`
-- (0039, намеренно — «мертвеца разбирает человек»), поэтому повторное нажатие
-- «Выделить блоки» для этих страниц не ставило ничего и молча возвращало
-- существующую мёртвую задачу. Пользователь видел разметку, сброшенную в ноль и
-- не двигавшуюся, — без единой ошибки на экране.
--
-- ## Что вводится
--
-- Отдельный счётчик молчаливых смертей. Попытка, не давшая никакого ответа
-- (воркер убит, хост перезагружен, процесс завис), больше не тратит бюджет
-- `attempts`: reaper увеличивает `lease_expiries` и поднимает `max_attempts`,
-- возвращая задаче потраченный квант. Бюджет попыток остаётся бюджетом
-- СОСТОЯВШИХСЯ попыток — успехов, отказов и отсрочек.
--
-- ## Почему у счётчика собственный потолок
--
-- Иначе задача, роняющая воркер (страница-гигант, которая не влезает в память),
-- получила бы вечный цикл: убила процесс — вернулась в очередь — снова убила.
-- Потолок в пять потерь аренды подряд эту задачу останавливает и отдаёт
-- человеку с различимой причиной: «вероятно, роняет воркер» — это другой разбор,
-- чем «упала пять раз с ошибкой». Значение потолка живёт в коде
-- (`LEASE_EXPIRY_LIMIT`), здесь только хранение счётчика.
--
-- Колонка добавляется со значением по умолчанию и старым кодом не читается:
-- миграция накатывается до подъёма новых контейнеров, как все прочие.

ALTER TABLE jobs
  ADD COLUMN lease_expiries integer NOT NULL DEFAULT 0;

ALTER TABLE jobs
  ADD CONSTRAINT jobs_lease_expiries_chk CHECK (lease_expiries >= 0);

COMMENT ON COLUMN jobs.lease_expiries IS
  'Сколько раз аренда истекала без ответа воркера (OOM, kill, зависание). Свой потолок, отдельный от attempts: молчаливая смерть не тратит бюджет попыток, но и не повторяется бесконечно.';
