-- S54. Идентификатор документа RD WEB перестал содержать слэш.
--
-- ## Что сломалось на бою
--
-- Комплект «ИД Мастер апрель 2026» (220 страниц, 293 блока) уезжал в RD WEB
-- целиком — снимок объявлялся, файл загружался, распознавание выполнялось, — а
-- прогон вставал на предпоследней задаче:
--
--   обработка остановилась: задача «rd.sync_fetch» исчерпала попытки
--   RD WEB ответил <n>: not_found — Request rejected
--
-- В журнале RD WEB тот же запрос помечен маршрутом
-- `/api/executive/v1/{unmatched}` — синтетической меткой обработчика, который
-- отвечает на запрос, НЕ СОПОСТАВИВШИЙСЯ ни с одной ручкой.
--
-- ## Почему слэш ломает путь
--
-- ADR-0027 назвал документ `folder/{uuid}` — префикс, чтобы идентификатор
-- читался человеком в чужом интерфейсе. Значение подставляется в путь
-- `GET /api/executive/v1/documents/{external_document_id}/blocks` и кодируется
-- `encodeURIComponent`, то есть уходит на провод как `folder%2F<uuid>`.
--
-- Дальше решает ASGI: uvicorn декодирует путь ДО сопоставления маршрутов, `%2F`
-- становится обычным разделителем сегментов, и шаблон `{external_document_id}`
-- (по умолчанию — ровно один сегмент) не сопоставляется. Ответ приходит не из
-- ручки блоков, а из обработчика несопоставленного маршрута: `404 not_found`
-- вместо `404 document_not_found`. Это не «документа нет» — это «такого адреса
-- нет», и повторы задачи ничего изменить не могли.
--
-- Три остальных пути контура слэша не видели никогда: `external_project_id` и
-- `external_sync_id` идут ТЕЛОМ, а в `/document-syncs/{sync_id}` подставляется
-- идентификатор, выданный сервером. Поэтому и проба связи в администрировании
-- оставалась зелёной, пока прогон падал: она ходит только в `init` и в чтение
-- синхронизации.
--
-- ## Что делает миграция
--
-- Идентификатор становится `folder-{uuid}` (тот же разделитель, что у `sync-…`
-- и `blk-…`), а прежние строки УДАЛЯЮТСЯ вместе с реестром блоков и журналом
-- отправок (каскадом по FK из 0069).
--
-- Удаление, а не переименование, потому что документ под новым идентификатором
-- для RD WEB — НОВЫЙ. Перенести к нему счётчики нельзя: `init` объявляет
-- `base_generation` принятой сервером генерации, а у нового документа принято
-- ничего не было, и первая же отправка получила бы `409 stale_base_generation`.
-- Лечится такой конфликт пересборкой снимка вслепую (ручки, отдающей
-- действующую серверную генерацию, в контракте нет) с потолком в два круга —
-- то есть прогон встал бы снова, только на другой задаче. Реестр
-- `rd_exec_blocks` без переноса тоже бесполезен: его ценность — история блока
-- НА ТОЙ СТОРОНЕ, а у нового документа её нет.
--
-- Цена известна и ограничена: блоки трёх папок объявятся `new_block` и будут
-- распознаны заново — ровно то следствие, которое ADR-0027 уже записал для
-- первого прогона после выката реестра. Документы `folder/…`, заведённые на
-- стороне RD WEB, остаются там сиротами: удалять чужие записи порталу нечем.
DELETE FROM rd_exec_documents WHERE external_document_id LIKE '%/%';

-- Гейт живёт там же, где проверяемое: форма идентификатора — свойство данных, а
-- не соглашение вызывающего кода. Без ограничения та же порча вернулась бы
-- любой правкой `externalDocumentIdOf`, и снова не на сборке снимка, а через
-- четыре задачи после неё.
ALTER TABLE rd_exec_documents
  ADD CONSTRAINT rd_exec_documents_document_path_chk
  CHECK (position('/' in external_document_id) = 0);
