-- S53. Замена исполнителя, прочитанного из акта, перестала спотыкаться о комплекты.
--
-- ## Что сломалось на бою
--
-- Папка «ИД Мастер апрель 2026» простояла одиннадцать часов на одной задаче:
-- `doc.extract_finalize` падал девяносто три раза подряд с одним отказом
--
--   update or delete on table "folders" violates foreign key constraint
--   "complects_folder_fk" on table "complects"
--
-- и конвейер за ним не доходил ни до разбора описи, ни до сверки, ни до
-- проверки правилами. На экране это выглядело как бесконечный «разбор
-- документов и реквизитов», а опись значилась найденной, но неразобранной.
--
-- ## Почему ключ мешает
--
-- `contractor_id` денормализован вниз по дереву составными ключами, и S37
-- (миграция 0054) сделал ОТСРОЧИВАЕМЫМИ те из них, которые тогда существовали:
-- `logical_documents_scope_fk` и `findings_scope_fk`. Замена исполнителя идёт
-- одной транзакцией, где сперва меняется папка, затем её копии, и без отсрочки
-- такой транзакции не существует ни в каком порядке операторов: папка первой —
-- отказ от документов, документы первыми — отказ от папки.
--
-- Миграция 0059 завела `complects` с тем же составным ключом на папку, но
-- отсроченным его не сделала: комплектов на момент 0054 не было, а 0059 о
-- замене исполнителя не думала. Ровно об этом предупреждал докстринг
-- `replaceAssumedContractor`: «отсрочить то, о чём никто не думал, — это уже
-- другое решение». Решение принимается здесь.
--
-- ## Что делает миграция
--
-- Ключ пересоздаётся отсрочиваемым, `INITIALLY IMMEDIATE`: по умолчанию он
-- по-прежнему проверяется на каждом операторе, и отсрочку просит явно только та
-- транзакция, которой она нужна. Проверка не отменяется — оборванная ссылка не
-- доживёт до коммита и в отсроченном режиме.
ALTER TABLE complects DROP CONSTRAINT complects_folder_fk;

ALTER TABLE complects
  ADD CONSTRAINT complects_folder_fk
  FOREIGN KEY (folder_id, object_id, contractor_id)
  REFERENCES folders (id, object_id, contractor_id)
  DEFERRABLE INITIALLY IMMEDIATE;
