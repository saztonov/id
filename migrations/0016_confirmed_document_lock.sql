-- Подтверждённый человеком документ не удаляется пересегментацией (§8.2).
--
-- ## Что было неверно
--
-- Охранник «в ревизии есть подтверждённые документы» стоял только в обработчике
-- задачи 15 (`apps/worker/src/jobs/segmentation.ts`). Сама же операция, которая
-- уничтожает работу инженера, — это `DELETE FROM logical_documents` внутри
-- `applySegmentation`, и она не проверяла ничего. Проверено прямым вызовом
-- репозитория мимо обработчика: документ подтверждён, `applySegmentation`
-- проходит успешно, подтверждение исчезает вместе со строкой.
--
-- Сегодня вызывающий один, поэтому в бою это не проявлялось бы. Но «инвариант
-- держится тем, что его нарушителя пока не написали» — не инвариант: любой
-- второй вызывающий снял бы подтверждение молча и с зелёными тестами.
--
-- ## Почему запрет уместен в БД и почему он не перерасширен
--
-- §8.2 объявляет ручную разметку приоритетной, и приоритет абсолютен: он не
-- зависит ни от роли актора, ни от статуса ревизии, ни от того, какой код
-- выполняет удаление. Ровно это БД и обязана держать (см. рассуждение о
-- границе ответственности в 0008).
--
-- Запрет узкий по трём осям и потому не повторяет ошибку S2, где триггер
-- заперли шире смысла и проверяющий лишился работы:
--
--   * только DELETE. Правка подтверждённого документа (смена вида, границ,
--     снятие пометки) остаётся разрешённой — это и есть работа инженера;
--   * только строка с `is_confirmed`. Неподтверждённые документы
--     пересегментация переписывает свободно, как и раньше;
--   * снятие подтверждения `UPDATE ... SET is_confirmed = false` триггер не
--     трогает, поэтому законный путь «снять подтверждение → пересобрать»
--     остаётся открытым. Именно его называет текст отказа репозитория.
--
-- Каскадного удаления документов не существует: `logical_documents.revision_id`
-- ссылается на `submission_revisions (id)` БЕЗ `ON DELETE CASCADE` (0005),
-- поэтому триггер не может сработать в чужой уборке. Обратное направление —
-- `page_assignments` каскадом уходят ЗА документом — на запрет не влияет:
-- удаления документа не будет, значит и каскада не будет.
--
-- ## Почему имя ограничения задаётся явно
--
-- `RAISE ... USING CONSTRAINT` кладёт имя в поле `constraint` ошибки драйвера, и
-- `guardWrites()` в репозитории разбирает отказы именно по нему. Без имени
-- отказ пришёл бы с SQLSTATE 23001, который уже занят триггерами неизменяемости
-- ревизии, и пользователь увидел бы «ревизия в терминальном статусе» — то есть
-- верный отказ с неверной причиной.

CREATE FUNCTION deny_confirmed_document_delete() RETURNS trigger
LANGUAGE plpgsql AS $fn$
BEGIN
  IF OLD.is_confirmed THEN
    RAISE EXCEPTION 'Удалить логический документ нельзя: он подтверждён человеком'
      USING ERRCODE = 'restrict_violation',
            CONSTRAINT = 'logical_documents_confirmed_lock',
            HINT = 'Снимите подтверждение явным действием, затем пересоберите документы';
  END IF;

  RETURN OLD;
END
$fn$;

CREATE TRIGGER logical_documents_confirmed_lock
  BEFORE DELETE ON logical_documents FOR EACH ROW
  EXECUTE FUNCTION deny_confirmed_document_delete();
