-- Нумерация реестра приложений начинается заново в каждом разделе (§8.3).
--
-- ## Что было неверно
--
-- `registry_rows_row_uq UNIQUE (document_id, row_no)` в 0005 исходил из того,
-- что `row_no` — сквозной порядок строки в реестре. На настоящем корпусе это
-- не так, и проверяется прямым чтением: в комплекте `АОСР № 01-ДК2-СЦ` реестр
-- разбит на три раздела («Документы, подтверждающие качество…», «Исполнительные
-- схемы», «Прочее»), и подрядчик нумерует каждый раздел с единицы — 1..3, 1..5,
-- 1..15. Строк двадцать три, различных `row_no` — пятнадцать.
--
-- Следствие не косметическое: задача 17 (`doc.parse_registry`) на таком реестре
-- упиралась бы в уникальный индекс на восьмой строке и падала бы все три
-- попытки. Причём диагностика указывала бы на «дубль строки реестра», то есть
-- на дефект комплекта, которого нет: реестр оформлен ровно так, как принято.
--
-- ## Что здесь делается
--
-- Разводятся два разных факта, которые прежде выражались одной колонкой.
--
-- `row_no` остаётся тем, что НАПЕЧАТАНО в реестре, — его показывают человеку и
-- на него ссылается замечание («позиция 14 раздела „Документы о качестве“»).
-- Уникальным он быть не обязан и не может.
--
-- `ordinal` — сквозной порядок строки в разобранном реестре, от нуля. Он и
-- становится ключом: именно по нему строка адресуется программно, по нему же
-- идёт устойчивый порядок выдачи. Пересборка реестра переписывает набор
-- целиком, поэтому промежуточных состояний с частично сдвинутой нумерацией
-- здесь не возникает — в отличие от `logical_documents.ordinal`, где уникальный
-- ключ по этой причине не заводится вовсе.
--
-- Расширение ключа до `(document_id, row_no, section_title)` рассматривалось и
-- отвергнуто: `section_title` nullable, а NULL в уникальном индексе не
-- сравнивается, то есть строки без раздела снова оказались бы без защиты — и
-- ровно они составляют весь комплект `АОСР № 336`.
--
-- Таблица на момент миграции пуста (сегментация появляется этим же этапом),
-- поэтому NOT NULL добавляется без backfill'а. Значения по умолчанию нет
-- намеренно: вставка, забывшая порядок, обязана быть отвергнута, а не молча
-- получить нулевой ordinal у каждой строки и упасть уже на уникальном индексе.

ALTER TABLE registry_rows
  DROP CONSTRAINT registry_rows_row_uq;

ALTER TABLE registry_rows
  ADD COLUMN ordinal integer;

UPDATE registry_rows SET ordinal = row_no WHERE ordinal IS NULL;

ALTER TABLE registry_rows
  ALTER COLUMN ordinal SET NOT NULL;

ALTER TABLE registry_rows
  ADD CONSTRAINT registry_rows_ordinal_chk CHECK (ordinal >= 0);

ALTER TABLE registry_rows
  ADD CONSTRAINT registry_rows_ordinal_uq UNIQUE (document_id, ordinal);

-- Порядок выдачи строк реестра: экран и правила читают их сквозным порядком,
-- а не порядком вставки.
CREATE INDEX ix_registry_rows_document_ordinal ON registry_rows (document_id, ordinal);
