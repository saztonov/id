-- Встроенный администратор для первого входа (ADR-0009, решение 9).
--
-- Логин `admin`, пароль `qwedcxz1@`. Учётная запись существует сразу после
-- миграций, поэтому свежее развёртывание открывается в браузере без обращения
-- к консоли сервера.
--
-- ЧТО ЭТО ЗНАЧИТ ДЛЯ БЕЗОПАСНОСТИ. Пароль лежит в git, то есть известен всем,
-- у кого есть доступ к репозиторию, и одинаков во всех развёртываниях.
-- Единственное, что ограничивает последствия, — `must_change_password = true`:
-- до смены пароля учётная запись не может НИЧЕГО, кроме `/me`, выхода,
-- получения CSRF-токена и самой смены пароля (`auth/local/must-change-guard.ts`).
-- Смените пароль сразу после первого входа: пока он не сменён, войти может
-- любой, кто видел этот файл.
--
-- Пароль `qwedcxz1@` короче минимума политики портала (12 символов), поэтому
-- задать его ЗАНОВО через форму смены нельзя — форма его отвергнет. Это не
-- дефект: пароль первого входа и не должен переживать первый вход.
--
-- Восстановление, если пароль забыт после смены:
--   pnpm local-admin reset --email admin
--
-- Почему три отдельных оператора, а не один запрос с CTE. Триггер
-- `user_credentials_local_only_trg` читает `users` собственным снимком, и
-- строка, вставленная data-modifying CTE в том же операторе, ему не видна —
-- вставка учётных данных упала бы с «пользователь не найден». Миграция
-- применяется в транзакции, поэтому отдельные операторы друг друга видят.
--
-- Почему seed НЕ пишет в `audit_log`. Внешний ключ `audit_log.actor_user_id`
-- объявлен без `ON DELETE` (0001), и запись из seed сделала бы невозможным
-- `DELETE FROM users` — а именно так очищают состояние некоторые тесты.
-- Заведение встроенной учётной записи и не является действием пользователя
-- портала: его выполнил тот, кто накатил миграции.

-- `kc_sub` — читаемый идентификатор вместо `local:<uuid>`: это единственный
-- ключ конфликта, обеспечивающий идемпотентность (колонка UNIQUE), и его видно
-- в выдаче администрирования. Пересечься с субъектом Keycloak он не может:
-- тот всегда UUID, а префикс `local:` эту форму нарушает.
--
-- `email` остаётся NULL намеренно: `admin` адресом почты не является и
-- притворяться им не должен.
INSERT INTO users (kc_sub, full_name, position, is_active)
VALUES ('local:builtin-admin', 'Администратор портала', 'Встроенная учётная запись', true)
ON CONFLICT (kc_sub) DO NOTHING;

INSERT INTO user_roles (user_id, role)
SELECT id, 'admin' FROM users WHERE kc_sub = 'local:builtin-admin'
ON CONFLICT DO NOTHING;

-- Хэш посчитан боевым профилем scrypt (N=2^16, r=8, p=2) от `qwedcxz1@` в
-- нормальной форме NFKC. Параметры лежат внутри значения, поэтому проверка
-- пароля не зависит от текущей настройки стоимости; при первом успешном входе
-- хэш перевычисляется под неё (`needsRehash` в auth/local/routes.ts).
--
-- `ON CONFLICT DO NOTHING` без указания цели: цель `(user_id)` не поймала бы
-- конфликт по `login_key`, если логин `admin` уже занят учётной записью,
-- заведённой через `pnpm local-admin create`.
INSERT INTO user_credentials
  (user_id, login_key, login_display, password_hash, password_algorithm, must_change_password)
SELECT
  id,
  'admin',
  'admin',
  'scrypt$N=65536,r=8,p=2$X2KYltv7cgsBpO-ezVRgtQ$87CNSMIDn4xlhQSwBh3V4jkGKavFeq4_PzQhnQomJT4',
  'scrypt',
  true
FROM users WHERE kc_sub = 'local:builtin-admin'
ON CONFLICT DO NOTHING;
