-- S57. Метки инженера на строках перечня: чем измеряется качество сверки.
--
-- ## Зачем таблица
--
-- Сверку строк теперь судит модель (ADR-0028), и главный вопрос о ней —
-- «стало ли лучше» — по самим решениям не отвечается. Портал может сопоставить
-- больше строк и сопоставить их неправильно; может найти расхождение и
-- придумать его. Отличить одно от другого способен только человек, посмотревший
-- на строку, — и его ответ надо где-то хранить.
--
-- Метка ставится ОДИН РАЗ на папку и живёт дольше прогона: замечания
-- пересоздаются каждой проверкой, а «этой строке отвечает вот этот документ» —
-- факт о бумаге, а не о прогоне. Поэтому таблица привязана к строке перечня, а
-- не к прогону правил.
--
-- ## Почему две оси, а не одна
--
-- `match_verdict` отвечает про сопоставление: тот ли документ назван. Метки
-- `checks` — про замечания: подтвердилось ли расхождение, не выдумано ли оно,
-- не пропущено ли настоящее. Смешать их нельзя: правильно найденный документ
-- ничего не говорит о качестве замечаний по нему, а верное замечание об
-- организации бывает и у строки, документ которой выбран неверно.
--
-- Отсюда же вывод для приёмки: доля сопоставленных строк сама по себе не
-- показатель. Она растёт и когда портал стал точнее, и когда он стал смелее.
--
-- ## Что здесь НЕ хранится
--
-- Ни значений реквизитов, ни цитат: §11 (ПДн). Метка — это код и ссылка на
-- строку, всё остальное уже лежит в самой строке перечня.

CREATE TABLE registry_row_labels (
  registry_row_id  uuid PRIMARY KEY REFERENCES registry_rows(id) ON DELETE CASCADE,
  folder_id        uuid NOT NULL REFERENCES folders(id),

  -- Про сопоставление: `correct` — назван тот документ; `wrong_document` —
  -- не тот; `not_in_folder` — документа в папке нет вовсе; `unclear` —
  -- проверяющий сам не смог решить (это тоже данные: строка, о которой человек
  -- не уверен, не должна считаться ни успехом, ни промахом модели).
  match_verdict    text NOT NULL,
  -- Какой документ отвечает строке на самом деле. Заполняется, когда
  -- проверяющий его нашёл, и именно он делает метку `wrong_document`
  -- измеримой: без него «не тот» не позволяет посчитать, стал ли следующий
  -- прогон ближе к истине.
  expected_document_id uuid REFERENCES logical_documents(id) ON DELETE SET NULL,

  -- Про замечания: массив объектов `{kind, verdict}`, где verdict —
  -- `confirmed` (расхождение настоящее), `false_alarm` (портал придумал),
  -- `missed` (расхождение есть, а портал промолчал). Массив, а не таблица:
  -- метки ставятся и читаются только целиком, по строке.
  check_labels     jsonb NOT NULL DEFAULT '[]'::jsonb,

  labeled_by       uuid NOT NULL REFERENCES users(id),
  labeled_at       timestamptz NOT NULL DEFAULT now(),
  -- Прогон, который человек видел, когда ставил метку. Не ключ и не
  -- ограничение: метка переживает прогоны, но знать, на что смотрел
  -- проверяющий, нужно — иначе «портал исправился» и «человек смотрел на
  -- другое» неразличимы.
  seen_validation_run_id uuid REFERENCES validation_runs(id) ON DELETE SET NULL,

  CONSTRAINT registry_row_labels_verdict_chk
    CHECK (match_verdict IN ('correct', 'wrong_document', 'not_in_folder', 'unclear')),
  CONSTRAINT registry_row_labels_checks_array_chk
    CHECK (jsonb_typeof(check_labels) = 'array'),
  -- «Не тот документ» без указания верного — законно (проверяющий увидел
  -- ошибку, но не нашёл правильный), а вот верный документ при вердикте
  -- «назван правильно» противоречил бы сам себе.
  CONSTRAINT registry_row_labels_expected_chk
    CHECK (expected_document_id IS NULL OR match_verdict <> 'correct')
);

CREATE INDEX ix_registry_row_labels_folder ON registry_row_labels (folder_id);
