-- S46. У страницы появляется её собственное разрешение.
--
-- ## Что чинится
--
-- Портал рендерит страницу в 300 dpi всегда. Замер по пяти боевым комплектам
-- (эталонный «Мастер апрель 2026», три АОСР, реестр) показал, что сканы в них
-- лежат в 200 dpi: лист A4 — это 1650 x 2338 пикселей. Рендер в 300 растягивает
-- те же пиксели в 1.28 раза по стороне, новых деталей не создаёт, а стоит 37 %
-- байтов и столько же процессорного времени на кодирование. Из ~280
-- полностраничных сканов в замере 200 dpi оказались все, кроме трёх.
--
-- ## Почему колонка, а не вычисление на лету
--
-- Значение выводится из PDF, а PDF после приёма файла портал больше не
-- разбирает: рендер идёт из рабочего документа, собранного слиянием. Считать его
-- в воркере значило бы разбирать чужой файл на каждом прогоне ради числа,
-- которое не меняется. Зонд уже проходит дерево страниц и словари ресурсов, и
-- одно дополнительное чтение `/Width` и `/Height` покрывающей картинки ему почти
-- ничего не стоит.
--
-- ## Почему NULL — законное значение
--
-- `NULL` означает «покрывающего растра не нашлось»: страница нарисована шрифтами,
-- либо картинка на ней есть, но по одному словарю ресурсов нельзя сказать,
-- покрывает ли она лист (матрица размещения лежит в потоке содержимого, который
-- зонд не разбирает). Обе причины ведут к прежнему поведению — рендеру на полном
-- разрешении, — и различать их незачем. Страницы, принятые до этой миграции,
-- остаются с `NULL` и рендерятся как раньше.

ALTER TABLE source_pages
  ADD COLUMN native_dpi integer,
  ADD CONSTRAINT source_pages_native_dpi_chk
    CHECK (native_dpi IS NULL OR native_dpi > 0);

COMMENT ON COLUMN source_pages.native_dpi IS
  'Разрешение покрывающего страницу растра; NULL — растра нет либо он не опознан (S46).';
