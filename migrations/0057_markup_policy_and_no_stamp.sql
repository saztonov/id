-- S42. Правило разметки по формату листа запинывается на ревизии.
--
-- ## Зачем пин, а не чтение настройки
--
-- Правило «лист A4 и мельче размечается целиком, на листе крупнее ищется штамп»
-- включается настройкой `detection.sheet_strategy`. Настройку администратор
-- меняет когда угодно, а разметка комплекта на 220 страниц — это веер из
-- двухсот с лишним постраничных задач, живущий минутами. Если каждая задача
-- читает настройку на своём исполнении, переключение посреди веера даёт ОДНУ
-- ревизию разметки, где часть страниц размечена одним правилом, а часть —
-- другим, и в базе не остаётся ничего, чем это объяснить.
--
-- Хуже того, правило нужно не только детекции: по нему анализ покрытия решает,
-- какие флаги внимания ставить странице, заплатка покрытия — трогать ли лист
-- вовсе, а экран разметки — что написать человеку. Все четверо читали бы
-- настройку в РАЗНЫЕ моменты времени, и «страница размечена как A4, а флаги ей
-- посчитали как крупному листу» стало бы штатным состоянием.
--
-- Поэтому политика — свойство ревизии разметки, а не текущего состояния
-- админки. Прецедент здесь же, в этой таблице: `layout_profile_id` и
-- `detector_profile` (0012) пиннятся ровно по той же причине — они объясняют
-- ПРОШЛУЮ разметку, а не описывают настройки на сегодня.
--
-- ## Почему умолчание — прежнее поведение
--
-- `detect_all` и `numberZone: off` означают «детектор идёт по каждой странице,
-- все три его класса попадают в разметку» — то, что портал делал до этой
-- работы. Так все существующие ревизии получают политику, по которой их
-- действительно размечали, и продолжают судиться ею: анализ покрытия не начнёт
-- задним числом ставить флаги по правилу, которого при их разметке не было.
--
-- Пороги (`numberZonePad`) лежат в политике ДАННЫМИ, а не константами кода:
-- калибровка, попавшая в пин, продолжает объяснять старую разметку и после
-- того, как её изменили. Настройками они при этом не становятся — версия
-- политики меняется релизом, и `version` в значении именно для этого.
--
-- ## Второй предмет миграции: код причины
--
-- `detect.no_stamp` — «модель что-то на листе видела, но штампа среди этого не
-- было». Отдельный код, а не существующий `detect.no_blocks` («модель не
-- увидела ничего»): у них разный смысл, разное следствие для оператора и
-- разные годовые ряды. `detect.no_blocks` говорит о дефекте конвейера — рендер,
-- порог, модель; `detect.no_stamp` говорит о качестве ВХОДЯЩЕЙ документации:
-- крупный лист пришёл без основной надписи. Склеив их, портал потерял бы
-- единственную метрику, по которой это различается.

ALTER TABLE layout_revisions
  ADD COLUMN markup_policy jsonb NOT NULL
    DEFAULT '{"version":1,"sheetStrategy":"detect_all","numberZone":"off","numberZonePad":{"x":0.1,"y":0.25}}'::jsonb;

COMMENT ON COLUMN layout_revisions.markup_policy IS
  'Слепок правила разметки на момент создания черновика: что портал искал на странице. Разбор — parseMarkupPolicy в @id/contracts; непригодное значение читается как прежнее поведение, а не роняет экран.';

