-- Третий исход попытки: задача отложена, а не упала (S27).
--
-- ## Что было неверно
--
-- Три задачи конвейера устроены как поллеры: `vlm.finalize_run` ждёт, пока все
-- страницы прогона станут терминальными, `rd.poll_recognition` — пока OCR
-- закончит, `rd.wait_pages` — пока отрендерятся страницы рабочего документа.
-- Ожидание выражалось единственным способом, который у движка был, — броском
-- повторяемой ошибки, и записывалось единственным исходом, который был у
-- попытки: `failed`.
--
-- Из-за этого нормальный ход дела выглядел как серия отказов. На стенде
-- `vlm.finalize_run` с `max_attempts = 60` дал двенадцать строк `outcome =
-- 'failed'` за одну минуту ожидания, `jobs.last_error` заполнился текстом
-- «Распознавание ещё идёт», а плашка конвейера напечатала «Обработка
-- остановилась: задача vlm.finalize_run, отказов 12» — при том, что
-- распознавание в эту секунду шло и через минуту успешно закончилось. Хуже
-- того, поллер перебивал НАСТОЯЩЕГО мертвеца: плашка выбирает тип с наибольшим
-- числом отказов, и двенадцать ожиданий заслоняли одну задачу, которая
-- действительно исчерпала попытки.
--
-- ## Почему это отдельное значение, а не флаг
--
-- `failed` отвечает «работа не получилась»; `deferred` — «работы ещё нет,
-- условие не наступило». Это разные факты о попытке, и сводить их к одному со
-- звёздочкой значило бы оставить экрану догадываться по тексту ошибки.
-- Отсрочка не пишет ни `error_class`, ни `error_message`, не попадает в журнал
-- ошибок (§11) и не поднимает событие ревизии: сообщать не о чем.
--
-- Счётчик попыток отсрочка при этом НЕ откатывает, и потолок остаётся
-- предохранителем: ожидание, не кончающееся никогда, обязано однажды стать
-- отказом, иначе задача висела бы в очереди вечно, а прогон — в `running`.

ALTER TABLE job_runs DROP CONSTRAINT job_runs_outcome_chk;
ALTER TABLE job_runs ADD CONSTRAINT job_runs_outcome_chk CHECK (
  outcome IS NULL OR outcome IN ('succeeded', 'failed', 'cancelled', 'lease_expired', 'deferred'));
