-- Месяц комплекта — производный факт, а не вопрос человеку (S30).
--
-- ## Что было неверно
--
-- `works.period` заполнялся ВРУЧНУЮ в форме заведения комплекта, и подставленный
-- по умолчанию текущий месяц человек менял далеко не всегда. Иначе и быть не
-- могло: акта в момент заведения ещё нет — есть файл, который никто не читал.
-- На стенде это выглядело так: комплект с актом от 09.03.2026 заведён как
-- «август 2026», и портал послушно показывал выдуманный месяц как факт.
--
-- Теперь месяц выводит конвейер по самому раннему распознанному акту
-- (`periodOfEarliestAct`, задача `doc.extract_fields`), а до распознавания его
-- просто нет. NULL здесь означает «портал ещё не знает», и это честнее любого
-- значения по умолчанию: выдуманный месяц неотличим от прочитанного, а месяц
-- комплекта попадает в реестр передачи.
--
-- ## Почему снятие NOT NULL безопасно
--
-- `period` не участвует НИ В ОДНОМ внешнем ключе и ни в одном уникальном
-- индексе. Составные ключи комплекта построены на других колонках
-- (`works_section_fk`, `works_contractor_fk`, `works_registry_fk`, 0028),
-- уникальность файла описи и порядка в реестре — тоже. Единственный индекс с
-- ним, `ix_works_object_section_period`, обычный и NULL переживает.
--
-- Триггеров неизменяемости на `works` нет вовсе (проверено по 0008): комплект —
-- карточка, а запирается содержимое ревизии.
--
-- ## Почему CHECK переписан, хотя и так пропускал NULL
--
-- `EXTRACT(DAY FROM NULL) = 1` даёт NULL, а CHECK пропускает всё, что не FALSE,
-- — то есть прежнее ограничение работало бы и без правки. Оставить его так
-- значило бы полагаться на трёхзначную логику там, где намерение читается
-- глазами: следующий, кто станет ужесточать это ограничение, обязан увидеть,
-- что NULL разрешён НАМЕРЕННО, а не проскочил по недосмотру.
--
-- ## Чего эта миграция НЕ делает
--
-- Не трогает `registries.period`: месяц папки остаётся обязательным. Это
-- свойство подписываемой бумаги (ADR-0011), его называет человек, и выводить
-- его неоткуда.
--
-- Не удаляет снятое правило `AOSR.ACT.032` из `rule_definitions` и
-- `ruleset_rules`. Определение держит внешний ключ `findings.rule_code` —
-- замечания прошлых прогонов ссылаются на него; строку снимка запирает триггер
-- `ruleset_rules_published_immutable`, и запирает верно: снимок описывает, что
-- проверял прогон месячной давности, и переписывать его задним числом нельзя.
-- Правило снято тем, что выведено из `RULE_CATALOG`: движок его не исполняет, а
-- сверка реестра при старте знает о снятых кодах отдельным списком.

ALTER TABLE works ALTER COLUMN period DROP NOT NULL;

ALTER TABLE works DROP CONSTRAINT works_period_chk;

ALTER TABLE works
  ADD CONSTRAINT works_period_chk
  CHECK (period IS NULL OR EXTRACT(DAY FROM period) = 1);

COMMENT ON COLUMN works.period IS
  'Месяц комплекта первым числом; NULL — портал ещё не прочитал акт (S30).';
