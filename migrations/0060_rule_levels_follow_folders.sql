--
-- `rule_definitions.level` — метаданные правила: к чему оно относится. Восемь
-- правил были засеяны со значением `revision`, а ревизия поставки перестала
-- существовать как сущность (0059).
--
-- Значение правится ОТДЕЛЬНОЙ миграцией, а не переписыванием 0017 и 0031:
-- применённая миграция заморожена контрольной суммой раннера, и правка задним
-- числом объявила бы её `modified`. Чем застывшие файлы отличаются от нынешнего
-- каталога, записано в самом каталоге (`RuleSeedBatch.seededAs`) — там же, где
-- сверка на дрейф это отличие и учитывает.

UPDATE rule_definitions SET level = 'folder' WHERE level = 'revision';
