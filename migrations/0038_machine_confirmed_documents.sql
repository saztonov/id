-- 0038. Границы документов подтверждает машина; решение человека остаётся отдельным.
--
-- ## Что было неверно
--
-- §12 ставил между нарезкой и проверками останов «человек подтверждает границы».
-- На практике останов оказался тупиком: `applySegmentation` отказывается
-- пересобирать документы, если хоть один из них `is_confirmed`, и отправляет
-- «снять подтверждение явным действием» — а маршрута снятия в портале нет
-- вовсе. Один клик «Подтвердить границы» навсегда закрывал повторную обработку
-- комплекта, и именно это заказчик увидел как «непонятные ошибки после
-- пересборки».
--
-- Заказчик отменил сам останов: «не нужно ничего собирать, документ уже есть —
-- это загруженный комплект». Границы теперь подтверждает конвейер сразу после
-- сегментации, иначе нарезка (задача 22) не поедет никогда: и
-- `logical_documents_derived_confirmed_chk`, и веер `doc.materialize_pdf`
-- требуют подтверждения.
--
-- ## Почему отдельная колонка, а не `confirmed_by IS NULL`
--
-- Различать машину и человека можно было бы отсутствием автора. Так было бы
-- дешевле на одну колонку и дороже на всё остальное: `confirmed_by` означает
-- «решение приняло это лицо», на нём стоит индекс и внешний ключ, его читают
-- аудит и диагностика, и они продолжали бы называть машинную отметку решением
-- человека. Признак, который надо выводить из отсутствия значения, — это
-- признак, о котором забудет первый же новый вызывающий.
--
-- Умолчание `'human'`, а не `'machine'`. Существующие строки подтверждал
-- человек, и это единственное верное значение для них; но важнее другое —
-- забытая запись обязана давать СТРОГОЕ поведение. Умолчание `'machine'`
-- молча ослабляло бы охранника при каждой новой точке вставки.

ALTER TABLE logical_documents
  ADD COLUMN confirmation_source text NOT NULL DEFAULT 'human';

ALTER TABLE logical_documents
  ADD CONSTRAINT logical_documents_confirmation_source_chk
    CHECK (confirmation_source IN ('human', 'machine'));

-- Прежнее ограничение читалось как «подтверждение требует автора» и запрещало
-- машинную отметку по построению. Смысл сохранён для решения человека: автор
-- обязателен, если подтверждение не машинное.
ALTER TABLE logical_documents
  DROP CONSTRAINT logical_documents_confirmed_chk;

ALTER TABLE logical_documents
  ADD CONSTRAINT logical_documents_confirmed_chk
    CHECK (NOT is_confirmed
           OR confirmation_source = 'machine'
           OR confirmed_by IS NOT NULL);

-- =====================================================================
-- Триггер запирает только решение человека
-- =====================================================================
--
-- Без этой правки автоподтверждение заперло бы удаление и замену файла:
-- `logical_documents` входит в `DERIVED_DELETES` (`purge.ts`), и в строгом
-- режиме триггер отверг бы `purgeDerivedForRevision` на каждом комплекте,
-- прошедшем сегментацию. То есть отметка, поставленная конвейером ради
-- нарезки, запрещала бы пользователю перезалить комплект.
--
-- Тело функции скопировано целиком вместе с ранним выходом из 0036 по той же
-- причине, что и там: триггеры привязаны к функциям по OID, обёртку вокруг них
-- подставить нельзя — будет вызвана исходная. `CREATE OR REPLACE` сохраняет
-- привязку, триггер не пересоздаётся.

CREATE OR REPLACE FUNCTION deny_confirmed_document_delete() RETURNS trigger
LANGUAGE plpgsql AS $fn$
BEGIN
  IF NOT immutability_enforced() THEN
    RETURN OLD;
  END IF;

  IF OLD.is_confirmed AND OLD.confirmation_source = 'human' THEN
    RAISE EXCEPTION 'Удалить логический документ нельзя: он подтверждён человеком'
      USING ERRCODE = 'restrict_violation',
            CONSTRAINT = 'logical_documents_confirmed_lock',
            HINT = 'Снимите подтверждение явным действием, затем пересоберите документы';
  END IF;

  RETURN OLD;
END
$fn$;
