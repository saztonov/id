-- Отменённая задача перестаёт занимать ключ дедупликации (S27).
--
-- Индекс 0007 исключал из уникальности только `done`:
--
--   WHERE dedupe_key IS NOT NULL AND status <> 'done'
--
-- Отменённая задача при этом продолжала держать ключ вечно, а
-- `enqueueSystemJob` на конфликте возвращает НЕ ошибку, а найденную задачу с
-- `created: false` (повторная постановка обязана быть безопасной, §12). В паре
-- это давало худший из возможных исходов: конвейер отвечает «задача уже
-- стоит», указывая на мертвеца, который никогда не выполнится, — то есть
-- молчит и не работает.
--
-- Дефект действовал уже сегодня: маршрут «Проверить» в режиме тестирования
-- снимает остаток детекции `cancelPendingJobsOfStage`, после чего повторное
-- нажатие той же кнопки не ставило ничего. Сброс конвейера, отменяющий задачи
-- ревизии, сделал бы это состояние постоянным.
--
-- `failed` (задача исчерпала попытки) ключ ПРОДОЛЖАЕТ держать, и это не
-- недосмотр: мёртвая задача обязана разбираться человеком — консолью, кнопкой
-- «повторить», — а не пересоздаваться следующим нажатием молча. Разница между
-- «отменили сами» и «упало насмерть» здесь ровно в том, кто принимал решение.
--
-- Предикат индекса обязан совпадать с `ON CONFLICT ... WHERE` в
-- `enqueueSystemJob` ДОСЛОВНО: несовпадение — не тихий дефект, а отказ
-- оператора «no unique or exclusion constraint matching the ON CONFLICT
-- specification». Второе место — запасной `SELECT` там же.
--
-- Отдельного `DROP` для старого индекса достаточно: индекс не участвует ни в
-- одном внешнем ключе и не назван ни в одном ограничении.

DROP INDEX ux_jobs_dedupe_key;

CREATE UNIQUE INDEX ux_jobs_dedupe_key ON jobs (dedupe_key)
  WHERE dedupe_key IS NOT NULL AND status NOT IN ('done', 'cancelled');
