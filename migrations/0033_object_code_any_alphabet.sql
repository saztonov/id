-- Код объекта: от одного до пяти символов любого алфавита (§3.2).
--
-- ## Что было неверно
--
-- `construction_objects_code_chk` из 0002 требовал `^[A-Za-z0-9]{5}$` — ровно
-- пять символов и только латиница. Посылка не выдержала первой же боевой
-- стройки: заказчик заводит объект кодом `ЗИЛ18`, и портал отвечает отказом на
-- реквизит, который назначен не им и переименованию не подлежит. Ни длина, ни
-- алфавит требованием предметной области не были: код печатается в номерах
-- актов, а номера актов на этой стройке кириллические.
--
-- ## Что здесь делается
--
-- Правило РАСШИРЯЕТСЯ, а не заменяется: всё, что проходило прежде, проходит и
-- теперь. Добавились короткие коды и нелатинские буквы.
--
-- ## Почему проверка выражена запретом, а не перечислением
--
-- Напрашивалось `code !~ '[^[:alnum:]]'` — «ни одного не-буквенно-цифрового».
-- Так делать нельзя: класс `[:alnum:]` для кириллицы зависит от `LC_CTYPE`
-- кластера, и на базе, поднятой в локали `C`, буква «З» не является `alnum`.
-- Проверка прошла бы на стенде разработчика и отвергла бы `ЗИЛ18` на проде —
-- то есть ровно тот дефект, который эта миграция чинит, вернулся бы молча и в
-- худшем месте.
--
-- Поэтому здесь стоят только классы, одинаковые во всех локалях: кириллическая
-- буква не является ни пробелом, ни управляющим символом, ни знаком пунктуации
-- ни при какой настройке. База держит грубый инвариант — длину и отсутствие
-- разделителей, из-за которых код нельзя было бы напечатать в номере акта.
--
-- ТОЧНЫЙ алфавит держит `objectCodeSchema` в `@id/contracts`
-- (`/^[\p{L}\p{N}]{1,5}$/u`), и это единственный источник правды о нём: у
-- регулярных выражений PostgreSQL нет юникодных категорий `\p{L}`, а вторая
-- копия правила, выраженная другими средствами, разошлась бы с первой на первой
-- же правке.
--
-- `varchar(5)` не меняется: длина в PostgreSQL считается в СИМВОЛАХ, и «ЗИЛ18»
-- это пять символов, а не десять байт.

ALTER TABLE construction_objects
  DROP CONSTRAINT construction_objects_code_chk;

ALTER TABLE construction_objects
  ADD CONSTRAINT construction_objects_code_chk
  CHECK (char_length(code) BETWEEN 1 AND 5
         AND code !~ '[[:space:][:cntrl:][:punct:]]');

COMMENT ON COLUMN construction_objects.code IS
  'Код объекта: 1–5 символов любого алфавита; печатается в номерах актов.';
