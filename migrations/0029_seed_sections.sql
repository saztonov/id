-- Стартовый справочник разделов работ (§3.2).
--
-- Перечень взят из сметного деления заказчика: это тот список, которым уже
-- пользуются на площадке, и заводить рядом свой значило бы заставить инженера
-- держать в голове два разных деления одних и тех же работ.
--
-- ## Почему сид рукописный, а не порождённый
--
-- Виды ИД, роли страниц и правила порождаются из кода (`pnpm seed:generate`) —
-- там перечень принадлежит коду, потому что от него зависят реализации правил.
-- Раздел работ ни от чего в коде не зависит: он ссылка, по которой ищут профиль.
-- Порождать его значило бы объявить, что заведение раздела — это релиз, тогда
-- как справочник заведён ровно ради обратного.
--
-- ## Наименования приведены к обычному регистру
--
-- В исходном списке они набраны прописными. Прописные — это оформление таблицы,
-- в которой список жил, а не часть названия; в выпадающем списке портала они
-- читаются как крик. Формулировки при этом сохранены дословно, кроме двух
-- случаев, где дословность мешала:
--
-- * «ВИС / МЕХАНИЧЕСКИЕ ИНЖЕНЕРНЫЕ СИСТЕМЫ» и «НИС / МЕХАНИЧЕСКИЕ ИНЖЕНЕРНЫЕ
--   СИСТЕМЫ» отличались только тремя буквами в начале. В списке выбора их не
--   различить, а ошибка стоит того, что комплект уезжает не в тот реестр:
--   аббревиатуры развёрнуты.
--
-- ## Что в перечне спорно и почему это не исправлено здесь
--
-- Границы некоторых разделов пересекаются: «Электрические системы» и
-- «Электромонтажные работы», «Слаботочные системы» и «Автоматика и
-- диспетчеризация», «Кровля» и «Гидроизоляционные работы». «Отделка квартир
-- MR BASE» называет продукт конкретного застройщика, а «Мокап» — не вид работ, а
-- демонстрационный образец. Всё это решается эксплуатацией — отключением
-- лишнего и переименованием — из интерфейса, а не правкой этого файла: сид
-- задаёт стартовое состояние, а не постоянное.
--
-- Коды `roofing` и `concrete_frame` сохранены от прежних видов разделов: на них
-- ссылается эталонный корпус (`tools/fixtures/corpus`), и смена кода
-- рассогласовала бы его с базой.

