-- Версионность профилей разделов и пиннинг прогонов (§3.2, §9.1).
--
-- Два дефекта S4, которые правятся здесь на уровне БД, а не только в коде:
--
-- 1. У одного вида раздела оставались ДВА опубликованных профиля с открытым
--    периодом, и вопрос «какой профиль действовал на дату» терял единственный
--    ответ. Инвариант «на любую дату действует не более одного профиля» обязан
--    держаться базой: писатель — не только этот репозиторий, но и рука в psql,
--    и миграция данных, и будущий воркер.
-- 2. `validation_runs` пиннил версию набора правил и профиль правил объекта, но
--    НЕ профиль вида раздела. Значит «какой состав документов и какие правила
--    ожидались» вычислялись по дате при каждом чтении, и прогон месячной
--    давности переставал воспроизводиться после публикации нового профиля —
--    ровно то, ради чего §3.2 сделал профиль версионным.

-- Частичный уникальный индекс, а НЕ исключающее ограничение и не триггер.
--
-- Почему не EXCLUDE USING gist (daterange(effective_from, effective_to, '[]')
-- WITH &&), хотя выразил бы инвариант целиком: оператор пересечения диапазонов
-- в классе gist приносит расширение btree_gist, а разрешённый список
-- расширений проекта — pgcrypto, citext, pg_trgm. Четвёртое расширение ради
-- одного ограничения расширяет поверхность развёртывания (и требует его наличия
-- в каждой среде, включая pglite в тестах).
--
-- Почему не триггер: проверка пересечения запросом НЕ защищает от гонки. Две
-- одновременные транзакции не видят строк друг друга, обе проходят проверку и
-- обе фиксируются — то есть триггер даёт ровно тот же дефект, что и проверка в
-- коде приложения, только глубже спрятанный. Уникальный индекс здесь
-- единственный механизм, надёжный без явной блокировки таблицы.
--
-- Индекс закрывает тот случай, который при одновременной записи и возникает:
-- два опубликованных профиля одного вида раздела с ОТКРЫТЫМ периодом. Остальные
-- пересечения требуют публикации профиля с датой начала внутри уже
-- опубликованного периода — это запрещено на входе (история профилей не
-- переписывается, см. createSectionProfile), а период предшественника
-- закрывается той же транзакцией, что публикует новый профиль.
--
-- `published_at IS NOT NULL` в условии обязателен: черновиков с открытым
-- периодом у вида раздела может быть сколько угодно. Они в выборе действующего
-- профиля не участвуют, и запрет на второй черновик закрыл бы штатную работу
-- администратора — подготовить следующую версию, пока действует текущая.
CREATE UNIQUE INDEX ux_section_profiles_open_period
  ON section_profiles (section_kind_code)
  WHERE effective_to IS NULL AND published_at IS NOT NULL;

-- Прогон проверок пиннит профиль вида раздела так же, как версию набора правил.
--
-- Колонка nullable по той же причине, что и object_rule_profile_id: у вида
-- раздела может не быть опубликованного профиля на дату прогона, и это законное
-- состояние открытого мира (§9.1 требует отличать «раздел не настроен» от
-- «комплект неполон»). NULL здесь означает именно «профиля не было», а не
-- «забыли записать», поэтому воспроизведение прогона не обязано угадывать.
ALTER TABLE validation_runs
  ADD COLUMN section_profile_id uuid REFERENCES section_profiles (id);

-- Индекс на столбец внешнего ключа: без него удаление/проверка ссылок и запрос
-- «по каким прогонам действовал этот профиль» идут перебором таблицы прогонов.
CREATE INDEX ix_validation_runs_section_profile
  ON validation_runs (section_profile_id);
