-- Логин встроенного администратора — адрес почты.
--
-- До подключения Keycloak логином служит введённый адрес: так заводятся и
-- пользователи из формы регистрации, и созданные администратором, и заведённые
-- через CLI — все три пути кладут в `login_key` то, что ввели в поле адреса.
-- Встроенная учётная запись была единственным исключением: логином у неё было
-- слово `admin`, а `users.email` пустовал. Исключение убрано — правило одно на
-- всех, и после перехода на Keycloak адрес встроенной записи можно связать с
-- субъектом так же, как у любой другой.
--
-- Новой миграцией, а не правкой 0023: та уже применена на развёртываниях, а
-- раннер сверяет контрольные суммы и роняет запуск на изменённом задним числом
-- файле. На чистой базе 0023 заводит запись с логином `admin`, а эта миграция
-- тут же его переименовывает — результат тот же, что и на существующей базе.
--
-- Пароль не меняется, поэтому хэш не трогается: `qwedcxz1@` и требование
-- сменить его при первом входе остаются в силе.

-- Условие на отсутствие занятого адреса — не перестраховка: `login_key`
-- объявлен UNIQUE, и без него миграция упала бы, обвалив всё развёртывание,
-- если кто-то успел завести учётную запись с этим адресом вручную. Такой
-- конфликт обязан разбирать человек, а не откат деплоя.
UPDATE user_credentials
   SET login_key = 'admin@test.com',
       login_display = 'admin@test.com',
       updated_at = now()
 WHERE login_key = 'admin'
   AND user_id IN (SELECT id FROM users WHERE kc_sub = 'local:builtin-admin')
   AND NOT EXISTS (
     SELECT 1 FROM user_credentials AS taken WHERE taken.login_key = 'admin@test.com'
   );

-- `email` заполняется только если он пуст: администратор мог уже указать свой
-- настоящий адрес, и затирать его миграцией нельзя.
UPDATE users
   SET email = 'admin@test.com',
       updated_at = now()
 WHERE kc_sub = 'local:builtin-admin'
   AND email IS NULL;
