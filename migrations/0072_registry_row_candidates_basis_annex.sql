-- S54. Основание кандидата «по родительскому документу» принимается базой.
--
-- ## Что сломалось на бою
--
-- S53 научил сверку искать приложение по родителю, при котором оно лежит
-- (`match.ts`, ступень до номерных): строка описи «Реестр к АОСР № 48-ОТ/-1»
-- ищет не свой номер, а акт, к которому подшита. Когда родителей подходящего
-- вида несколько, документ уходит в кандидаты с основанием `annex_pages` —
-- новым значением, которого CHECK из 0051 не знает:
--
--   new row for relation "registry_row_candidates" violates check constraint
--   "registry_row_candidates_basis_chk"
--
-- Задача `doc.match_registry` умерла с трёх попыток, все 128 строк описи
-- остались `missing`, граф и проверка правилами не построены. Код уехал на бой
-- без миграции: перечисление живёт в двух местах, и второе не поправили.
--
-- ## Почему CHECK, а не свободный текст
--
-- Соблазн после такого отказа — снять ограничение вовсе. Он неверен: основание
-- уходит в отчёт ДОСЛОВНО и переводится на русский разбором по вариантам
-- (`basisLabel`). Значение, о котором разбор не знает, — это пустая строка в
-- объяснении «почему портал считает документ похожим». Ограничение остаётся
-- закрытым, а чтобы код и база больше не расходились молча, перечисление
-- `CANDIDATE_BASES` сверяется с этим CHECK тестом (`match-basis.test.ts`).
ALTER TABLE registry_row_candidates DROP CONSTRAINT registry_row_candidates_basis_chk;

ALTER TABLE registry_row_candidates ADD CONSTRAINT registry_row_candidates_basis_chk
  CHECK (basis IN ('doc_no', 'doc_type', 'issued_at', 'doc_type_and_issued_at', 'annex_pages'));
