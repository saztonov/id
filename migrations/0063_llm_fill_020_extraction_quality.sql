-- S44. «Портал прочитал иначе» перестаёт быть дефектом бумаги.
--
-- ## Что чинится
--
-- `LLM.FILL.020` утверждает: «извлечённое порталом значение расходится с текстом
-- документа». Это отчёт о качестве ИЗВЛЕЧЕНИЯ, а не дефект документа —
-- подрядчику с ним делать нечего, исправлять надо не бумагу. На боевой папке
-- таких предупреждений 61, и они лежали вперемешку с настоящими дефектами, где
-- их и принимали за дефекты: счётчик «201 предупреждение» на треть состоял из
-- претензий портала к самому себе.
--
-- ## Почему миграцией, а не правкой сида
--
-- Правило засеяно `0031_seed_llm_review_rules`, а применённый файл заморожен
-- контрольной суммой раннера: переписать его значит объявить миграцию
-- `modified` при следующем старте. Значение правит отдельная миграция, а чем
-- застывший файл отличается от нынешнего каталога, записано в самом каталоге
-- (`RuleSeedBatch.seededAs`) — там же, где сверка на дрейф это отличие и
-- учитывает. Тем же приёмом и по той же причине снят уровень `revision` (0060).
--
-- Ограничения на `kind` в схеме нет (`rule_definitions_kind_chk` — это регулярное
-- выражение), поэтому расширять нечего: меняется только значение.

UPDATE rule_definitions SET kind = 'extraction_quality' WHERE code = 'LLM.FILL.020';
