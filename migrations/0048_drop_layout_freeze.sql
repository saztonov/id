-- 0048. Заморозки разметки больше нет.
--
-- ## Что было неверно
--
-- Разметка замораживалась перед распознаванием и после этого не правилась: ни
-- строка ревизии, ни блоки. Смысл был в доказательстве — `blocks_hash` прогона
-- обязан описывать набор блоков, по которому прогон шёл. На практике механизм
-- оказался ловушкой ровно того же рода, что и подтверждение границ (0038):
--
-- - маршрута разморозки в портале нет; правка блоков после нажатия
--   «Распознать» отвечала 409 «исправление — новая ревизия разметки»;
-- - новую ревизию разметки заводит только повторная детекция, а она стирает
--   автоблоки — то есть «поправить одну рамку» стоило полной переразметки;
-- - повторный прогон по той же разметке был запрещён отдельно
--   (`startRecognitionRun`), и цикл «поправил — распознал заново» не
--   существовал вовсе.
--
-- Заказчик отменил сам механизм: нужен простой и гибкий цикл проверки, блокеры
-- не нужны. Блоки правятся всегда; прогон распознавания фиксирует хэш набора
-- блоков в момент старта — в `recognition_runs.local_layout_hash`, где он и
-- нужен. Доказательство от этого не слабеет: хэш по-прежнему называет набор, по
-- которому шёл прогон, просто хранится он у прогона, а не запирает разметку.
--
-- ## Что делает миграция
--
-- 1. Снимает два триггера, которые запирали `frozen`-строку и разрешали ей
--    единственный переход в `superseded`.
-- 2. Переводит существующие `frozen`-строки: последняя по номеру у каждой
--    поставки становится черновиком, прежние — `superseded`. Порядок именно
--    такой из-за частичного уникального индекса «одна незамороженная ревизия
--    разметки на поставку» (0004): перевести в черновик все значило бы его
--    нарушить.
-- 3. Убирает `frozen` из списка допустимых состояний. Инвариант «портал больше
--    не замораживает» держит база, а не дисциплина вызывающих.
--
-- Что НЕ трогается: `superseded` остаётся запертым состоянием, и содержимое
-- таких ревизий по-прежнему неизменяемо (`deny_frozen_layout_content`). Это
-- история, по которой уже прошли прогоны, и переписывать её нельзя.

DROP TRIGGER IF EXISTS layout_revisions_frozen_immutable ON layout_revisions;
DROP TRIGGER IF EXISTS layout_revisions_supersede_only ON layout_revisions;

-- Прежние ревизии вытесняются: черновик у поставки может быть только один.
WITH latest AS (
  SELECT DISTINCT ON (revision_id) id
    FROM layout_revisions
   WHERE state = 'frozen'
   ORDER BY revision_id, revision_no DESC
)
UPDATE layout_revisions
   SET state = 'superseded',
       updated_at = now()
 WHERE state = 'frozen'
   AND id NOT IN (SELECT id FROM latest);

-- `blocks_hash` НЕ обнуляется: у черновика он законен и читается как «хэш
-- набора, по которому шёл последний прогон». `frozen_at`/`frozen_by` снимаются
-- — отметки о действии, которого больше не существует.
UPDATE layout_revisions
   SET state = 'draft',
       frozen_at = NULL,
       frozen_by = NULL,
       updated_at = now()
 WHERE state = 'frozen';

ALTER TABLE layout_revisions
  DROP CONSTRAINT layout_revisions_state_chk;

ALTER TABLE layout_revisions
  ADD CONSTRAINT layout_revisions_state_chk
    CHECK (state IN ('draft', 'superseded'));

-- Прежний CHECK требовал у нечерновой ревизии И хэш блоков, И время заморозки.
-- Времени заморозки больше не существует как факта: `frozen_at` не пишет никто,
-- и требовать его значило бы запретить вытеснение навсегда. Хэш требовать
-- по-прежнему верно — вытесненная ревизия описывает набор, по которому уже
-- прошёл прогон.
ALTER TABLE layout_revisions
  DROP CONSTRAINT layout_revisions_frozen_chk;

ALTER TABLE layout_revisions
  ADD CONSTRAINT layout_revisions_superseded_chk
    CHECK (state = 'draft' OR blocks_hash IS NOT NULL);

COMMENT ON COLUMN layout_revisions.blocks_hash IS
  'Хэш набора блоков на момент последнего прогона распознавания; у нетронутого черновика NULL.';
