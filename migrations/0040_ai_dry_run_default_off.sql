-- Dry-run перестаёт быть умолчанием (S27, ADR-0007).
--
-- ## Что было неверно
--
-- `ai.dry_run_only` объявлен со значением по умолчанию `true`, и настройки
-- читаются через `readEffectiveSetting`: отсутствующая строка в `app_settings`
-- означает «взять умолчание из кода». То есть свежее развёртывание получало
-- shadow-режим, ничего об этом не сообщая.
--
-- Последствие видно в прогоне на стенде: 20 блоков распознаны, страниц с
-- отказом ноль, canonical записан — и `page_text_versions` пуст, потому что
-- финализация в dry-run выходит ДО публикации. Ни анализа, ни проверок за этим
-- не следует, экран «Проверка» пуст, а прогон при этом закрыт статусом `done`.
-- Портал из коробки делал всю работу в мусор, и отличить это от исправной
-- работы на экране было нечем.
--
-- ## Почему миграция, а не только правка умолчания в коде
--
-- Правка `SETTINGS_REGISTRY` лечит только случай «строки нет». Развёртывания,
-- где значение однажды записали явно, остались бы в shadow-режиме навсегда, и
-- разбирались бы с пустым экраном ровно так же.
--
-- ## Что миграция затирает
--
-- Осознанный выбор администратора, если он был. Это принято сознательно:
-- shadow-режим — инструмент сравнения провайдеров на время, а не состояние, в
-- котором портал живёт, и цена «сравнение прервалось» несопоставима с ценой
-- «портал молча не работает». ПЕРЕД накатом на боевую базу снимите и приложите
-- к журналу выката:
--
--   SELECT key, value, updated_by, updated_at
--     FROM app_settings WHERE key = 'ai.dry_run_only';
--
-- `updated_by = NULL` после правки — не потеря следа, а точное утверждение:
-- значение поставил не пользователь портала, а тот, кто накатил миграции. Тем
-- же приёмом и по той же причине seed встроенного администратора не пишет в
-- `audit_log` (0023).
--
-- Условие `value <> 'false'` оставляет строку нетронутой там, где режим уже
-- выключен: `updated_at` — это «когда решили», и переписывать его накатом
-- миграции значило бы врать о времени решения.

UPDATE app_settings
   SET value = 'false'::jsonb,
       updated_by = NULL,
       updated_at = now()
 WHERE key = 'ai.dry_run_only'
   AND value <> 'false'::jsonb;
