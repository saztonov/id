-- Решение классификатора по каждой странице (§8.2, задачи 14 и 15 §12).
--
-- ## Почему таблица, а не промежуточное значение в памяти
--
-- §12 разводит классификацию страниц (задача 14) и сборку документов (задача
-- 15) по РАЗНЫМ задачам: у них разные очереди, разная стоимость и разное число
-- попыток — первая ходит в LLM, вторая считает границы по уже принятым меткам.
-- Значит между ними обязана быть передача решения. Двух вариантов ровно два, и
-- второй негоден: «пересчитать метки заново внутри задачи 15» означало бы два
-- источника правды об одной и той же странице — при неидемпотентной фазе 2
-- (модель, кэш промта, версия схемы) вторая задача собрала бы документы не из
-- тех меток, которые видел и подтверждал человек.
--
-- ## Почему решение обязано быть объяснимым, а не только принятым
--
-- Экран «Документы» §14 показывает границы, и первый вопрос инженера к нему —
-- «почему эта страница попала сюда». Ответ складывается из четырёх вещей,
-- поэтому все четыре здесь колонками, а не текстом в журнале: чем получена
-- метка (`source` — якорь, состав блоков, модель или рука), насколько уверенно
-- (`confidence`), по какому именно фрагменту текста (`page_text_version_id` +
-- `char_span` + `quote`) и что проиграло (`alternatives`, `ambiguous`).
-- Решение, о котором известен только исход, неотличимо от угаданного, а §16
-- требует отсутствия ТИХИХ высокоуверенных ошибок границ — то есть требует,
-- чтобы уверенность и основание были видны до того, как ошибка найдётся.
--
-- ## Почему `type_outcome` отдельно от `doc_type_code`
--
-- Мир открытый (§0.5): корпус покрывает два раздела работ из многих. «Это
-- документ, но ни один известный тип не подходит» (`other`) и «похоже на
-- известный тип, но не уверен» (`uncertain`) — РАЗНЫЕ состояния с разным
-- поведением: первое получает резервный тип и запись в `doc_type_candidates`,
-- второе — `needs_review` и гипотезу. Свести их к одному «тип не определён»
-- значило бы сделать незнакомый раздел неотличимым от плохого скана, и правила
-- §9.1 не смогли бы выдать `n_a` вместо `fail`.

CREATE TABLE page_classifications (
  -- Ключ по паре, а не суррогат: решение по странице ревизии ровно одно.
  -- Второе решение по той же странице — это не «ещё одно мнение», а
  -- рассогласование, при котором задача 15 выбирала бы из двух молча.
  revision_id          uuid NOT NULL,
  source_page_id       uuid NOT NULL,
  -- B-DOC начинает документ, I-DOC продолжает предыдущий, A-ROLE — служебная
  -- роль (копия верна, лист подписи, продолжение приложения), U — сигнала нет.
  label                text NOT NULL,
  -- Код каталога либо резервный код открытого мира. NULL — тип не присвоен.
  doc_type_code        text REFERENCES doc_types (code),
  type_outcome         text NOT NULL,
  -- Заголовок документа дословно. Обязателен при `other` — см. CHECK ниже.
  observed_title       text,
  page_role_code       text REFERENCES page_roles (code),
  -- Номер документа-родителя из якоря роли («К сертификату соответствия №…»):
  -- по нему приложение присоединяется к своему документу, а не к соседнему.
  parent_ref           text,
  confidence           double precision,
  reason               text,
  source               text NOT NULL,
  -- Доказательство: точный диапазон в КОНКРЕТНОЙ версии текста страницы.
  -- Версия обязательна вместе со спаном (§3.5, `offset_convention`): текст
  -- страницы переписывается новым прогоном распознавания, и диапазон, не
  -- привязанный к версии, назавтра указывает на другое место.
  page_text_version_id uuid,
  char_span            int4range,
  quote                text,
  -- Проигравшие кандидаты: показываются инженеру, а не отбрасываются молча.
  -- jsonb, а не text[]: массив кодов сегодня и массив пар «код + уверенность»
  -- завтра — это правка формы значения, а не миграция схемы.
  alternatives         jsonb NOT NULL DEFAULT '[]'::jsonb,
  -- Несколько кандидатов равного приоритета: каталог их не различает
  -- (`resolveDocType` §8.1 отделяет штатное разрешение конфликта от настоящей
  -- неоднозначности, и второе обязано доезжать до человека).
  ambiguous            boolean NOT NULL DEFAULT false,
  created_at           timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (revision_id, source_page_id),

  -- Закрытые перечисления. Значения приходят из типов `apps/api/src/segmentation`
  -- и из ответа модели, то есть с двух разных сторон: без CHECK опечатка в
  -- метке («B_DOC» вместо «B-DOC») не была бы отвергнута ничем и превратилась
  -- бы в страницу, которую декодер молча отнесёт к `U`.
  CONSTRAINT page_classifications_label_chk
    CHECK (label IN ('B-DOC', 'I-DOC', 'A-ROLE', 'U')),
  CONSTRAINT page_classifications_type_outcome_chk
    CHECK (type_outcome IN ('known', 'other', 'uncertain', 'none')),
  CONSTRAINT page_classifications_source_chk
    CHECK (source IN ('anchor', 'blocks', 'llm', 'manual')),
  CONSTRAINT page_classifications_confidence_chk
    CHECK (confidence IS NULL OR (confidence >= 0 AND confidence <= 1)),

  -- ГЛАВНОЕ ограничение этой таблицы.
  --
  -- `other` — единственная точка входа в цикл роста каталога (§3.2): именно
  -- `observed_title` нормализуется и уходит в `doc_type_candidates`, откуда
  -- администратор заводит или сопоставляет тип. Без заголовка запись кандидата
  -- невозможна, документ незнакомого типа получает резервный код и БЕССЛЕДНО
  -- растворяется в нём — а это ровно тот механизм, которым система обязана
  -- покрывать разделы, отсутствовавшие в корпусе, и который §16 проверяет
  -- отдельным пунктом приёмки. Ломалось бы это молча: резервный тип есть,
  -- задача зелёная, очередь кандидатов пуста.
  --
  -- Проверяется непустота после обрезки пробелов, а не только NOT NULL: строка
  -- из пробелов нормализуется в пустой ключ и склеила бы в одного кандидата все
  -- незнакомые документы всех поставок.
  CONSTRAINT page_classifications_observed_title_chk
    CHECK (type_outcome <> 'other' OR (observed_title IS NOT NULL AND btrim(observed_title) <> '')),

  -- «Тип известен» без указания, какой именно, — утверждение ни о чём.
  -- Обратное направление (`none` обязан быть без кода) НЕ проверяется
  -- намеренно: страница-продолжение несёт код документа, который продолжает,
  -- при собственном типовом сигнале `none`, и запрет превратил бы штатный
  -- случай в отказ — ровно то перерасширение, которое S2 пришлось откатывать.
  CONSTRAINT page_classifications_known_type_chk
    CHECK (type_outcome <> 'known' OR doc_type_code IS NOT NULL),

  -- Диапазон символов без текста, в котором он измерен, ни на что не
  -- отображается: то же правило, что у `field_values_span_source_chk`.
  CONSTRAINT page_classifications_span_source_chk
    CHECK (char_span IS NULL OR page_text_version_id IS NOT NULL),
  CONSTRAINT page_classifications_span_bounds_chk
    CHECK (char_span IS NULL OR lower(char_span) >= 0),
  -- Цитата без диапазона — это то, что ВЕРНУЛА модель, а не то, что написано в
  -- документе. §8.2 прямо требует обратного отображения цитаты на точный span,
  -- и невозможность отображения даёт `undetermined`, а не «сохраним как есть».
  CONSTRAINT page_classifications_quote_span_chk
    CHECK (quote IS NULL OR char_span IS NOT NULL),

  -- Страница и её классификация — из одной ревизии. Простым FK на
  -- `source_pages (id)` это не выражается: `revision_id` здесь
  -- денормализован ради области видимости и триггера неизменяемости, и без
  -- составного ключа он мог бы указывать на чужую поставку.
  CONSTRAINT page_classifications_source_page_fk
    FOREIGN KEY (revision_id, source_page_id)
    REFERENCES source_pages (revision_id, id) ON DELETE CASCADE,
  -- Версия текста — тоже из этой ревизии. Доказательство, снятое с текста чужой
  -- поставки, — худший вид ложного факта: оно выглядит проверенным.
  CONSTRAINT page_classifications_page_text_fk
    FOREIGN KEY (revision_id, page_text_version_id)
    REFERENCES page_text_versions (revision_id, id)
);

-- Экран объяснения читает решения ревизии в порядке страниц; сортировка по
-- `revision_ordinal` требует соединения с `source_pages`, поэтому индекс здесь
-- только по ревизии (PK её и так возглавляет — отдельный индекс не нужен).
CREATE INDEX ix_page_classifications_doc_type ON page_classifications (doc_type_code);
CREATE INDEX ix_page_classifications_role ON page_classifications (page_role_code);
CREATE INDEX ix_page_classifications_page_text ON page_classifications (page_text_version_id);
-- Очередь наблюдений для `doc_type_candidates`: страницы открытого мира.
CREATE INDEX ix_page_classifications_other ON page_classifications (revision_id)
  WHERE type_outcome = 'other';

-- Класс `derived` (0008, п. 7).
--
-- Классификация — то, что произвёл конвейер, а не то, что подал подрядчик: в
-- `aggregate_manifest_hash` она не входит и о составе поставки ничего не
-- говорит. Значит запирать её с момента submit нельзя — пересегментация на
-- проверке штатна: инженер правит границы и подтверждает тип именно в статусе
-- `submitted`/`in_review`, а по §5.3 и §8.2 повторный прогон классификации
-- допустим до самого решения. Заперты только терминальные состояния
-- (`returned`, `approved`, `superseded`): после них решение по границам —
-- часть вынесенного вердикта, и переписать его значило бы переписать основание
-- согласования, оставив дату и подпись прежними.
--
-- Это ровно то разделение, отсутствие которого S2 назвал перерасширением
-- запрета: тогда `submitted` и `in_review` заперли вместе с терминальными, и
-- проверяющий не мог подтвердить тип документа — ему оставался единственный
-- ход, вернуть всю ревизию подрядчику.
CREATE TRIGGER page_classifications_revision_locked
  BEFORE INSERT OR UPDATE OR DELETE ON page_classifications FOR EACH ROW
  EXECUTE FUNCTION deny_locked_revision_content(
    'классификацию страницы', 'revision_id', '', 'derived');

-- Версия логического документа для оптимистичной блокировки (§14, `If-Match`).
--
-- §14 требует `If-Match` на редактировании документов, а сравнивать было не с
-- чем: у `logical_documents` есть только `updated_at`, и он для ETag негоден —
-- `now()` пишет микросекунды, а ISO-8601 в ответе несёт миллисекунды, то есть
-- клиент вернул бы значение, которое не совпадает с хранимым НИКОГДА, и любое
-- подтверждение падало бы в 412. Округлять же время до миллисекунд ради
-- сравнения значит сделать две правки внутри одной миллисекунды неотличимыми.
--
-- Целочисленная версия — та же схема, что у `layout_revisions.version` (§7.2), и
-- второй способ выражать «эта строка с тех пор не менялась» в одном портале
-- заводить незачем. Без неё поведением по умолчанию становится «последний
-- записавший победил»: два проверяющих открыли карточку одного документа, один
-- подтвердил тип `mill_certificate`, второй — `quality_passport`, и первый об
-- этом не узнает.
ALTER TABLE logical_documents
  ADD COLUMN version integer NOT NULL DEFAULT 0;

ALTER TABLE logical_documents
  ADD CONSTRAINT logical_documents_version_chk CHECK (version >= 0);
