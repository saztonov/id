-- S44. У отказа задачи появляется человекочитаемая причина рядом с отпечатком.
--
-- ## Что чинится
--
-- Плашка конвейера печатает `job_runs.error_message`, а он нормализован:
-- `normalizeErrorMessage` (ADR-0010) вычёркивает ЧИСЛА намеренно — иначе
-- одинаковые дефекты разъезжались бы по журналу на сотни уникальных строк, а в
-- сообщение провайдера или Postgres могли бы попасть данные документа.
--
-- Плата за это видна на боевом прогоне: там, где задача не уложилась в аренду,
-- человек читал «попытка не уложилась в <n> мс». Отпечаток верен, а ответить на
-- вопрос «сколько ждали» по нему нельзя.
--
-- ## Почему отдельная колонка, а не ослабление нормализации
--
-- Это два разных требования к одной строке, и совместить их в ней нельзя.
-- `error_message` — КЛЮЧ АГРЕГАЦИИ: по нему считаются повторы и строится журнал
-- ошибок, и число в нём ломает счёт. `reason_text` — ОТВЕТ ЧЕЛОВЕКУ, и число в
-- нём единственное, ради чего он заведён.
--
-- ## Почему ПДн сюда не просачиваются
--
-- Колонку заполняет закрытый набор СОБСТВЕННЫХ классов ошибок портала из своих
-- типизированных полей: `JobTimeout` печатает свой потолок аренды,
-- `LlmBudgetError` — потраченное и бюджет. Сырое сообщение провайдера, текст
-- Postgres и любая чужая строка сюда не попадают никогда — для них
-- `reason_text IS NULL`, и плашка показывает нормализованный шаблон, как
-- показывала. Это свойство держится кодом (одна чистая функция с закрытым
-- перечнем) и проверяется тестом: сюда нечего добавить ограничением БД, потому
-- что запрет относится к ИСТОЧНИКУ строки, а не к её форме.

ALTER TABLE job_runs ADD COLUMN reason_text text;

COMMENT ON COLUMN job_runs.reason_text IS
  'Человекочитаемая причина отказа из закрытого набора своих классов ошибок; '
  'NULL — причина не из них, и показывать надо нормализованный error_message (S44).';
