-- S39. Закрепление подрядчика перестаёт быть условием заведения комплекта.
--
-- ## Что происходило
--
-- `works_contractor_fk (object_id, contractor_id) → object_contractors` (0028)
-- требовал, чтобы исполнитель комплекта был ЗАКРЕПЛЁН за объектом. На боевых
-- объектах закрепления не ведут: у ЖК KING & SONS их ноль, у ЖК ЗИЛАРТ три и
-- ни одного признака, кто из них генподрядчик. После S37, где исполнитель стал
-- выводиться порталом, ключ превратился в стену: инженер генподрядчика не мог
-- загрузить документацию, пока кто-то не настроит карточку объекта.
--
-- Заказчик снял требование прямо: «убрать проверку закрепления подрядчиков за
-- объектами; инженеру генподрядчика не должно быть препятствий в виде
-- назначенных на объект подрядчиков».
--
-- ## Что остаётся
--
-- `works_contractor_id_fkey` (`works.contractor_id → counterparties`) НЕ
-- трогается: исполнитель по-прежнему обязан быть существующей организацией
-- справочника. Снимается только требование ЗАКРЕПЛЕНИЯ — то есть утверждение
-- «эта организация работает на этом объекте», которого портал теперь не делает.
--
-- `works_section_fk` тоже не трогается: раздел на объекте включают в той же
-- карточке, и это условие заказчик не снимал.
--
-- ## Обратный путь
--
-- Ключ возвращается одним оператором, если закрепления снова станут
-- обязательными:
--
--   ALTER TABLE works ADD CONSTRAINT works_contractor_fk
--     FOREIGN KEY (object_id, contractor_id)
--     REFERENCES object_contractors (object_id, contractor_id);
--
-- Перед возвратом придётся закрепить организации уже заведённых комплектов:
-- строки, не проходящие ключ, к этому моменту в базе будут.
ALTER TABLE works DROP CONSTRAINT works_contractor_fk;
