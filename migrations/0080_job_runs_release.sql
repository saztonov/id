-- S58. У попытки задачи появляется метка сборки исполнителя.
--
-- ## Что вскрылось на бою
--
-- С 6 по 8 сентября задачи портала исполняли ДВА воркера: боевой (`-p id`) и
-- дубликат стека, поднятый из каталога deploy без `-p id` (compose назвал проект
-- `deploy`, образ `id-api:latest` сборки 06.09, `restart: unless-stopped`).
-- Дубликат пережил три выкатки и брал задачи из той же очереди кодом до S54:
-- `rd.sync_prepare` падал на `rd_exec_documents_document_path_chk` (старый код
-- строит `folder/{uuid}`), `checks.run` — на «нет реализации для кодов
-- REG.113…117». Та же папка секундами позже проходила на новом воркере.
--
-- Разбор занял день, потому что у попытки НЕТ метки сборки:
--   • `error_samples.release` помечает только отказы, прореживается и хранится
--     по сроку — а зелёные попытки чужой сборки (правила старого каталога,
--     прошедшие «замечаний нет») следа не оставляют вовсе;
--   • `jobs.locked_by` перезаписывает следующая аренда;
--   • вдобавок метка была константой из env-файла (см. compose, S58).
--
-- ## Что делает миграция
--
-- `job_runs.release` пишется при ЗАХВАТЕ, в той же CTE, что открывает попытку:
-- попытка, которую воркер не довёл до исхода, тоже обязана назвать сборку.
-- NULL — исполнитель метку не сообщил (dev, тесты, установка без APP_RELEASE).
-- Разбор прогона на две сборки становится одним запросом:
--   SELECT release, outcome, count(*) FROM job_runs
--    WHERE started_at > now() - interval '1 day' GROUP BY 1, 2;

ALTER TABLE job_runs ADD COLUMN release text;

COMMENT ON COLUMN job_runs.release IS
  'Метка сборки воркера, захватившего попытку (APP_RELEASE); NULL — исполнитель '
  'метку не сообщил. Пишется при захвате, чтобы недоведённая попытка тоже была подписана (S58).';
