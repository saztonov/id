-- Дораспознавание упавших страниц и восстановление упавшего прогона (S28).
--
-- Прогон срывался целиком из-за одного блока. Модель на нём трижды попросила
-- дополнительный кроп, потолок кругов исчерпался, блок остался непокрытым — и
-- строгое покрытие (ADR-0007) закрыло прогон `failed`, выбросив 84 распознанных
-- блока из 85. Единственным выходом был повторный прогон с нуля: те же 118
-- вызовов модели и та же оплата за уже прочитанное.
--
-- Инвариант «публикуется только полное покрытие» при этом верен и остаётся:
-- неполный набор блоков нельзя выдавать за результат, по которому принимают
-- решение. Меняется то, что происходит ДО отказа.
--
-- `recovery_round` — сколько раз финализация уже переигрывала упавшие страницы
-- ЭТОГО прогона. Колонка, а не поле `settings_snapshot`, по двум причинам.
-- Первая: снимок доказывает, ЧЕМ прогон выполнен (провайдер, модель, версии
-- промптов), и подмешивать в него изменяемое состояние значит смешивать
-- доказательство с рабочей переменной. Вторая: колонка даёт атомарный переход
-- `0 → 1` одним UPDATE с условием, и две одновременные финализации разводятся
-- без блокировок — та, что проиграла гонку, просто ждёт.
--
-- `repair_of_run_id` — прогон, который этот восстанавливает. Родитель при этом
-- НЕ переоткрывается: `failed` остаётся `failed` навсегда, его результаты
-- неизменяемы, а совместимые из них переносятся в дочерний прогон до первого
-- вызова модели. Ссылка нужна, чтобы «распознано заново» и «дочитано поверх
-- прежнего» различались в аудите, а не выглядели одинаково.

ALTER TABLE recognition_runs
  ADD COLUMN recovery_round integer NOT NULL DEFAULT 0,
  ADD COLUMN repair_of_run_id uuid NULL REFERENCES recognition_runs(id);

ALTER TABLE recognition_runs
  ADD CONSTRAINT recognition_runs_recovery_round_chk CHECK (recovery_round >= 0);

-- Прогон не восстанавливает сам себя: ссылка на собственную строку означала бы
-- цикл в истории и «переиспользование» результатов у самого себя.
ALTER TABLE recognition_runs
  ADD CONSTRAINT recognition_runs_repair_not_self_chk CHECK (repair_of_run_id IS DISTINCT FROM id);

-- По ссылке ходят от родителя к потомку («чем кончилась попытка починки»),
-- поэтому индекс по колонке, а не только по первичному ключу цели.
CREATE INDEX ix_recognition_runs_repair_of ON recognition_runs (repair_of_run_id)
  WHERE repair_of_run_id IS NOT NULL;
