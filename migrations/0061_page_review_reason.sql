-- S44. У пометки «проверьте лист» появляется причина.
--
-- ## Что чинится
--
-- Приложение-продолжение без напечатанного номера родителя теперь присоединяется
-- к документу по соседству, а не уходит в непривязанные: на боевой папке это
-- было 17 из 27 непривязанных листов, и каждый такой лист уменьшал покрытие, по
-- которому правила полноты решают, вправе ли они вообще сказать «документа нет в
-- комплекте».
--
-- Присоединение по соседству — довод, а не доказательство, поэтому лист метится
-- `needs_review`. Но одной метки мало: «проверьте» без «что именно» человек
-- проверить не может, а `reason` для присоединённой строки запрещён
-- `page_assignments_state_chk` — и запрещён верно, там он означает «почему НЕ
-- привязана».
--
-- ## Почему отдельная колонка, а не ослабление CHECK
--
-- Два разных факта: `reason` объясняет, почему страница осталась ничьей,
-- `review_reason` — почему её принадлежность стоит перепроверить. Слить их в одну
-- колонку значило бы получить строку, у которой «не привязана» и «привязана, но
-- сомнительно» неразличимы по данным, — ровно то, что `page_assignments_state_chk`
-- и не даёт сделать с остальными полями.
--
-- Колонка необязательная и заполняется только вместе с `needs_review`: причина без
-- пометки была бы объяснением того, чего не происходит.

ALTER TABLE page_assignments
  ADD COLUMN review_reason text,
  ADD CONSTRAINT page_assignments_review_reason_chk
    CHECK (review_reason IS NULL OR needs_review);

COMMENT ON COLUMN page_assignments.review_reason IS
  'Чем присоединение листа не доказано; заполняется только при needs_review (S44).';
